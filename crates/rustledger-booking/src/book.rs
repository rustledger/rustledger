    /// The snapshot is skipped for ordinary transactions and kept whenever
    /// overflow cannot be ruled out (#1897).
    ///
    /// Both directions matter. Skipping when overflow IS possible is silent
    /// corruption; keeping it always is the 2.4x heap churn this guard exists
    /// to remove. The third case is the one a naive guard gets wrong: the
    /// posting is tiny, but the account it lands in already sits at the
    /// ceiling, so the add still overflows.
    /// Two reducing postings on the SAME account in one transaction: the
    /// second must see what the first took.
    ///
    /// This is the case the working-copy clone exists for, and the only one
    /// that still gets a copy — everything else previews against the live
    /// inventory without copying. If the "does this account need a working
    /// copy" gate ever drifts toward cloning less, both postings would match
    /// against the full 10-unit lot and a 6+6 oversell would book cleanly.
    ///
    /// 10 AAPL held; sell 6 and 6 in one transaction. The second reduction
    /// must fail on insufficient units.
    #[test]
    fn two_reducing_postings_on_one_account_see_each_other() {
        let mut engine = BookingEngine::new();

        let buy = Transaction::new(date(2024, 1, 1), "buy 10")
            .with_synthesized_posting(
                Posting::new("Assets:Stocks", Amount::new(dec!(10), "AAPL")).with_cost(
                    CostSpec::empty()
                        .with_number(rustledger_core::CostNumber::PerUnit { value: dec!(100) })
                        .with_currency("USD"),
                ),
            )
            .with_synthesized_posting(Posting::new("Assets:Bank", Amount::new(dec!(-1000), "USD")));
        engine.apply(&buy).expect("buy applies");

        let oversell = Transaction::new(date(2024, 1, 2), "sell 6 then 6")
            .with_synthesized_posting(
                Posting::new("Assets:Stocks", Amount::new(dec!(-6), "AAPL"))
                    .with_cost(CostSpec::empty()),
            )
            .with_synthesized_posting(
                Posting::new("Assets:Stocks", Amount::new(dec!(-6), "AAPL"))
                    .with_cost(CostSpec::empty()),
            )
            .with_synthesized_posting(Posting::new("Assets:Bank", Amount::new(dec!(1200), "USD")));

        let result = engine.book(&oversell);
        assert!(
            result.is_err(),
            "6 + 6 against a 10-unit lot must fail: the second posting has to \
             see the first one's reduction. Got {result:?}",
        );

        // And the control: 6 + 4 exactly drains the lot and must succeed.
        let mut engine = BookingEngine::new();
        engine.apply(&buy).expect("buy applies");
        let exact = Transaction::new(date(2024, 1, 2), "sell 6 then 4")
            .with_synthesized_posting(
                Posting::new("Assets:Stocks", Amount::new(dec!(-6), "AAPL"))
                    .with_cost(CostSpec::empty()),
            )
            .with_synthesized_posting(
                Posting::new("Assets:Stocks", Amount::new(dec!(-4), "AAPL"))
                    .with_cost(CostSpec::empty()),
            )
            .with_synthesized_posting(Posting::new("Assets:Bank", Amount::new(dec!(1000), "USD")));
        assert!(
            engine.book(&exact).is_ok(),
            "6 + 4 exactly drains the lot and must book",
        );
    }

    #[test]
    fn the_snapshot_is_skipped_only_when_overflow_is_impossible() {
        let mut engine = BookingEngine::new();

        let ordinary = Transaction::new(date(2024, 1, 1), "groceries")
            .with_synthesized_posting(Posting::new(
                "Assets:Bank",
                Amount::new(dec!(-42.50), "USD"),
            ))
            .with_synthesized_posting(Posting::new(
                "Expenses:Food",
                Amount::new(dec!(42.50), "USD"),
            ));
        assert!(
            !engine.overflow_is_possible(&ordinary),
            "a two-posting transaction of ordinary magnitudes must take the \
             fast path, or the guard buys nothing"
        );
        engine.apply(&ordinary).expect("applies");
        assert!(
            !engine.overflow_is_possible(&ordinary),
            "and still does once the accounts hold a balance"
        );

        // Magnitudes alone exceed the range.
        let huge = Transaction::new(date(2024, 1, 2), "huge")
            .with_synthesized_posting(Posting::new("Assets:A", Amount::new(Decimal::MAX, "USD")))
            .with_synthesized_posting(Posting::new("Assets:B", Amount::new(Decimal::MAX, "USD")));
        assert!(engine.overflow_is_possible(&huge));

        // The case that makes the guard non-trivial: a SMALL posting into an
        // account already parked at the ceiling.
        let park = Transaction::new(date(2024, 1, 3), "park").with_synthesized_posting(
            Posting::new("Assets:Full", Amount::new(Decimal::MAX, "USD")),
        );
        engine.apply(&park).expect("one MAX position fits");
        let small_but_doomed = Transaction::new(date(2024, 1, 4), "small")
            .with_synthesized_posting(Posting::new("Assets:Full", Amount::new(dec!(1.00), "USD")));
        assert!(
            engine.overflow_is_possible(&small_but_doomed),
            "the posting is tiny but the destination is at the ceiling — a \
             guard that looked only at the transaction would miss this"
        );
        // ...and the currency it cannot reach is unaffected.
        let other_currency = Transaction::new(date(2024, 1, 4), "eur")
            .with_synthesized_posting(Posting::new("Assets:Full", Amount::new(dec!(1.00), "EUR")));
        assert!(
            !engine.overflow_is_possible(&other_currency),
            "the ceiling is per currency; EUR has room"
        );
    }

    /// A transaction whose `apply` overflows partway must leave the running
    /// balances exactly as it found them.
    ///
    /// The loader DROPS such a transaction (`run_booking`'s `failed_indices`),
    /// so any posting applied before the failing one is a mutation from an
    /// entry the user is told was rejected. Every later transaction then books
    /// against it — wrong lot matching and wrong balances, reported as fact.
    /// Found in review of #1863; the pad path had the identical defect.
    #[test]
    fn a_failed_apply_leaves_no_partial_mutation() {
        let mut engine = BookingEngine::new();

        // Park an account at the ceiling so the SECOND posting overflows.
        let load = Transaction::new(date(2024, 1, 5), "load")
            .with_synthesized_posting(Posting::new("Assets:B", Amount::new(Decimal::MAX, "USD")));
        engine.apply(&load).expect("one MAX position fits");

        let bad = Transaction::new(date(2024, 2, 1), "partial")
            .with_synthesized_posting(Posting::new("Assets:A", Amount::new(dec!(10.00), "USD")))
            .with_synthesized_posting(Posting::new("Assets:B", Amount::new(Decimal::MAX, "USD")));
        engine
            .apply(&bad)
            .expect_err("the second posting overflows");

        let inventories = engine.into_inventories();
        assert!(
            !inventories.contains_key(&rustledger_core::Account::from("Assets:A")),
            "an account first seen in the failed transaction must not survive it"
        );
        assert_eq!(
            inventories
                .get(&rustledger_core::Account::from("Assets:B"))
                .expect("Assets:B predates the failed transaction")
                .units(&rustledger_core::Currency::from("USD")),
            Decimal::MAX,
            "an account that predates the failed transaction must be restored to \
             its prior value, not left doubled or cleared"
        );
    }
