//! Transaction booking with lot matching.
//!
//! This module handles:
//! - Tracking inventory across transactions
//! - Matching sold lots against existing holdings
//! - Calculating capital gains/losses
//! - Filling in cost specs for lot reductions

// ratchet: fxhash-only — hot path; use FxHashMap/FxHashSet, not std SipHash collections (#1237).
use rustc_hash::{FxHashMap, FxHashSet};
use rustledger_core::{
    AccountedBookingError, Amount, BookingMethod, Cost, CostSpec, Decimal, Directive,
    IncompleteAmount, Inventory, Position, Posting, Transaction,
};
use thiserror::Error;

use crate::{
    InterpolationError, InterpolationResult, interpolate_with_tolerance_map,
    interpolate_with_tolerances,
};

// Note: We no longer quantize calculated values during booking.
// Python beancount preserves full precision during booking and only
// rounds at display time. Premature rounding of per-unit costs (e.g.,
// from total cost / units) causes cost basis errors when selling.
// For example: 300.00 / 1.763 = 170.16505... should NOT be rounded
// to 170.17, because 1.763 * 170.17 = 300.00971 ≠ 300.00.

/// Errors that can occur during booking.
///
/// Inventory-level failures (insufficient units, no matching lot, ambiguous
/// match, currency mismatch) are unified under [`BookingError::Inventory`],
/// which carries an [`AccountedBookingError`] from `rustledger-core`. This
/// keeps the user-facing wording in **one place** so it cannot drift between
/// the booking layer and the validator — see #748 / #750.
#[derive(Debug, Clone, Error)]
pub enum BookingError {
    /// An inventory-level booking failure (insufficient units, no matching
    /// lot, ambiguous match, currency mismatch).
    ///
    /// `Display` is delegated to the inner [`AccountedBookingError`], which
    /// is the single canonical source of wording for booking errors. The
    /// pta-standards `reduction-exceeds-inventory` conformance test depends
    /// on this Display containing the literal substring `"not enough"`.
    #[error(transparent)]
    Inventory(AccountedBookingError),

    /// Interpolation failed after booking.
    #[error("interpolation failed: {0}")]
    Interpolation(#[from] InterpolationError),

    /// A posting reached application with its units still elided, which means
    /// it never went through booking.
    ///
    /// Separate from [`BookingError::Interpolation`] on purpose: interpolation
    /// did not FAIL here, it never ran. Reporting an interpolation failure
    /// would send a reader looking for a residual that does not exist.
    ///
    /// This used to be a silent `Ok(())`. A caller replaying an unbooked
    /// ledger got empty balances and no complaint — a wrong figure delivered
    /// quietly, which is worse than a refusal.
    #[error("posting for {account} was not booked: its units are still elided")]
    NotBooked {
        /// The account whose posting was not booked.
        account: rustledger_core::Account,
    },
}

impl BookingError {
    /// The account this failure is about, when it names one.
    ///
    /// One place that knows which account each variant is about, so a
    /// diagnostic can be placed on the posting that failed rather than on the
    /// whole transaction (#2330). Interpolation delegates to its own accessor,
    /// since only some of its variants are about a single posting.
    #[must_use]
    pub const fn account(&self) -> Option<&rustledger_core::Account> {
        match self {
            Self::Inventory(e) => Some(&e.account),
            Self::NotBooked { account } => Some(account),
            Self::Interpolation(e) => e.account(),
        }
    }
}

/// Result of booking a single transaction.
#[derive(Debug, Clone)]
pub struct BookedTransaction {
    /// The transaction with costs filled in.
    pub transaction: Transaction,
    /// Capital gains/losses generated by this transaction.
    pub gains: Vec<CapitalGain>,
    /// Which posting indices had costs filled in.
    pub booked_indices: Vec<usize>,
}

/// A realized capital gain or loss from disposing of **one lot**.
///
/// A sale that crosses several lots produces one `CapitalGain` per matched lot,
/// so each is a self-contained disposal (units, cost basis, proceeds, acquisition
/// date) — the shape tax reporting needs (a Form 8949 line per lot). The gain is
/// only recorded for a reduction that carries a sale `@`price; a costless transfer
/// of a lot is not a disposal.
#[derive(Debug, Clone)]
pub struct CapitalGain {
    /// The account holding the asset.
    pub account: rustledger_core::Account,
    /// The currency of the asset.
    pub currency: rustledger_core::Currency,
    /// Units of this lot disposed of (always positive).
    pub units: Decimal,
    /// Cost basis of this lot (units × per-unit cost), in the lot's cost currency.
    pub cost_basis: Amount,
    /// Sale proceeds attributable to this lot, in the sale-price currency. Equals
    /// the cost-basis currency for an ordinary same-currency disposal; a consumer
    /// derives the realized gain as `proceeds − cost_basis` when the two currencies
    /// match (they cannot be subtracted across currencies without an FX rate — that
    /// policy is the consumer's, not the booking engine's).
    pub proceeds: Amount,
    /// The date of the disposing transaction (the sale/cover date).
    pub sale_date: rustledger_core::NaiveDate,
    /// Acquisition date of the lot, when the lot carried one (the holding-period
    /// start for short vs long term classification).
    pub acquired_date: Option<rustledger_core::NaiveDate>,
    /// True when this disposal CLOSES A SHORT position (the matched lot had
    /// negative units): the lot's cost is the price the units were sold at when
    /// the short was opened, so `proceeds`/`cost_basis` are assigned accordingly.
    /// US tax treats short-sale gains as always short-term.
    pub short_sale: bool,
}

/// Booking engine that tracks inventory across transactions.
#[derive(Debug, Default)]
pub struct BookingEngine {
    /// Inventory per account.
    /// Per-account inventories, behind `Arc` so a caller can take a snapshot
    /// without copying the lots.
    ///
    /// Booking itself never shares one, so `Arc::make_mut` below hands back
    /// `&mut` without copying and the engine pays nothing for this. A caller
    /// that HOLDS a snapshot makes the next mutation of that account copy
    /// once — which is the copy it asked for, and no longer a copy per row
    /// whether anyone wanted it or not (#2086).
    inventories: FxHashMap<rustledger_core::Account, std::sync::Arc<Inventory>>,
    /// Default booking method, used for accounts without an explicit
    /// booking method on their `open` directive.
    booking_method: BookingMethod,
    /// Per-account booking method overrides (from `open` directives).
    /// Looked up first, falling back to `booking_method` if absent.
    account_methods: FxHashMap<rustledger_core::Account, BookingMethod>,
    /// Tolerance knobs used to quantize interpolated amounts. Defaults to
    /// beancount's defaults; the loader overrides it from the ledger's
    /// `option` directives via [`Self::with_tolerance_policy`].
    tolerance: crate::TolerancePolicy,
}

impl BookingEngine {
    /// Create a new booking engine with default FIFO booking.
    #[must_use]
    pub fn new() -> Self {
        Self {
            inventories: FxHashMap::default(),
            booking_method: BookingMethod::Fifo,
            account_methods: FxHashMap::default(),
            tolerance: crate::TolerancePolicy::default(),
        }
    }

    /// Create a booking engine with a specific default booking method.
    #[must_use]
    pub fn with_method(method: BookingMethod) -> Self {
        Self {
            inventories: FxHashMap::default(),
            booking_method: method,
            account_methods: FxHashMap::default(),
            tolerance: crate::TolerancePolicy::default(),
        }
    }

    /// Set the tolerance knobs used to quantize interpolated amounts.
    ///
    /// Interpolation rounds a solved number to the transaction's own balance
    /// tolerance, so a ledger that sets `tolerance_multiplier`,
    /// `infer_tolerance_from_cost` or `inferred_tolerance_default` must pass
    /// them here. Skipping this leaves the engine on beancount's defaults,
    /// which would round against a tolerance the balance validator is not
    /// using.
    #[must_use]
    pub fn with_tolerance_policy(mut self, policy: crate::TolerancePolicy) -> Self {
        self.tolerance = policy;
        self
    }

    /// Register the booking method for a specific account.
    ///
    /// Call this for each `open` directive *before* booking transactions for
    /// that account, so the engine uses the per-account method (e.g. FIFO,
    /// LIFO, NONE) rather than the engine-wide default. Subsequent calls
    /// overwrite the previous method for the account.
    pub fn set_account_method(&mut self, account: rustledger_core::Account, method: BookingMethod) {
        self.account_methods.insert(account, method);
    }

    /// An engine for realizing a booked ledger: `default` for accounts that
    /// declare no method, and each `open`'s declared method for its own.
    ///
    /// `default` must be the ledger's effective method (the loader's
    /// `Ledger::booking_method`), not [`Self::new`]'s FIFO: under a global
    /// `option "booking_method" "NONE"`, a sale at a cost no lot has is booked
    /// as an augmentation, and a FIFO or STRICT replay reads it as a reduction
    /// and fails (#2386). The one constructor for every such consumer, so
    /// they cannot drift apart again.
    #[must_use]
    pub fn for_ledger<'a, I>(default: BookingMethod, directives: I) -> Self
    where
        I: IntoIterator<Item = &'a rustledger_core::Directive>,
    {
        let mut engine = Self::with_method(default);
        engine.register_account_methods(directives);
        engine
    }

    /// Scan a sequence of directives and register any per-account booking
    /// methods found on `open` directives. Open directives whose booking
    /// method is absent or fails to parse are silently ignored (they fall
    /// back to the engine-wide default).
    ///
    /// This is a convenience wrapper around [`Self::set_account_method`] for
    /// the common pipeline pattern of scanning all directives once before
    /// the booking loop. Call this before booking any transactions so the
    /// engine uses each account's declared method rather than the
    /// engine-wide default for every account.
    pub fn register_account_methods<'a, I>(&mut self, directives: I)
    where
        I: IntoIterator<Item = &'a rustledger_core::Directive>,
    {
        for directive in directives {
            if let rustledger_core::Directive::Open(open) = directive
                && let Some(method_str) = &open.booking
                && let Ok(method) = method_str.parse::<BookingMethod>()
            {
                self.set_account_method(open.account.clone(), method);
            }
        }
    }

    /// Resolve the booking method for an account, falling back to the
    /// engine-wide default if not registered.
    fn method_for(&self, account: &rustledger_core::Account) -> BookingMethod {
        self.account_methods
            .get(account)
            .copied()
            .unwrap_or(self.booking_method)
    }

    /// Get the inventory for an account.
    #[must_use]
    pub fn inventory(&self, account: &rustledger_core::Account) -> Option<&Inventory> {
        self.inventories.get(account).map(AsRef::as_ref)
    }

    /// A snapshot of an account's inventory that costs a refcount bump.
    ///
    /// The engine keeps mutating; this hands back the state as of now, without
    /// copying the lots. The copy happens later and only if it has to — the
    /// next mutation of this account finds the `Arc` shared and clones once
    /// (`Arc::make_mut`). A caller that drops the snapshot before then, such as
    /// a query filter that reads the balance and moves on, causes no copy at
    /// all (#2086).
    #[must_use]
    pub fn inventory_snapshot(
        &self,
        account: &rustledger_core::Account,
    ) -> Option<std::sync::Arc<Inventory>> {
        self.inventories.get(account).map(std::sync::Arc::clone)
    }

    /// Consume the engine and return its realized per-account inventories.
    ///
    /// After [`apply`](Self::apply)ing a booked directive stream, this is the
    /// canonical realization — each account's `Inventory` carries its lots at
    /// cost, with reductions already matched (FIFO/LIFO/etc. per the account's
    /// booking method). Callers that render balances (reports, holdings) read
    /// this rather than re-summing postings, so cost is retained and lot
    /// matching is the engine's, not a re-implementation.
    #[must_use]
    pub fn into_inventories(self) -> FxHashMap<rustledger_core::Account, Inventory> {
        self.inventories
            .into_iter()
            .map(|(account, inv)| {
                // Unwrap when this engine holds the only reference, which is
                // the normal case; a caller still holding a snapshot pays for
                // the copy it kept alive.
                (
                    account,
                    std::sync::Arc::try_unwrap(inv).unwrap_or_else(|shared| (*shared).clone()),
                )
            })
            .collect()
    }

    /// Borrow the realized per-account inventories without consuming the engine.
    ///
    /// The borrowing counterpart to [`into_inventories`](Self::into_inventories),
    /// for callers that must read the realization *mid-walk* and keep applying —
    /// e.g. snapshotting portfolio value at successive dates in one forward pass
    /// (`rustledger-returns`' single-pass TWR). Iteration order is the underlying
    /// `FxHashMap`'s (unspecified); collect into a `BTreeMap` if a stable order
    /// matters.
    // (No `#[must_use]`: the returned `impl Iterator` already carries it.)
    pub fn inventories(&self) -> impl Iterator<Item = (&rustledger_core::Account, &Inventory)> {
        self.inventories
            .iter()
            .map(|(account, inv)| (account, inv.as_ref()))
    }

    /// Book a transaction: fill in empty cost specs and calculate gains.
    ///
    /// This does NOT modify the internal inventories - call `apply` for that.
    ///
    /// When a reduction matches multiple lots (e.g., selling shares that were purchased
    /// across multiple buy transactions), the posting is expanded into multiple postings,
    /// one for each matched lot. This matches Python beancount's behavior.
    pub fn book(&self, txn: &Transaction) -> Result<BookedTransaction, BookingError> {
        // Fast path: if no postings have cost specs, no booking is needed.
        // This avoids expensive inventory cloning for simple transactions.
        let has_cost_specs = txn.postings.iter().any(|p| p.cost.is_some());
        if !has_cost_specs {
            return Ok(BookedTransaction {
                transaction: txn.clone(),
                gains: Vec::new(),
                booked_indices: Vec::new(),
            });
        }

        let mut result = txn.clone();
        let mut gains = Vec::new();
        let mut booked_indices: FxHashSet<usize> =
            FxHashSet::with_capacity_and_hasher(txn.postings.len(), Default::default());
        // Track posting expansions: (original_idx, expanded_postings)
        let mut expansions: Vec<(usize, Vec<rustledger_core::Spanned<Posting>>)> =
            Vec::with_capacity(txn.postings.len());

        // Create working copies of inventories for this transaction.
        // This allows us to track inventory changes across multiple postings
        // within the same transaction (e.g., main sale + fee posting).
        //
        // Clone only the inventories we actually need for this transaction's
        // accounts. Use `entry().or_insert_with(...)` so that a posting list
        // with repeated accounts (e.g., two postings on `Assets:Stock`) only
        // triggers one clone per unique account instead of cloning the same
        // inventory every time it appears. Without deduping, the optimization
        // would be silently undone by transactions that list the same
        // account more than once.
        let mut working_inventories: FxHashMap<rustledger_core::Account, Inventory> =
            FxHashMap::with_capacity_and_hasher(txn.postings.len(), Default::default());
        //
        // Only accounts with MORE THAN ONE reducing posting need a working
        // copy at all. The copy exists so a second posting on the same account
        // sees what the first one took; with a single posting nothing ever
        // reads the mutation back, and `Inventory::try_reduce` answers from
        // `&self` without copying (it stopped being `self.clone().reduce(..)`
        // in this same change).
        //
        // That matters because the copy is O(lots): the engine's stores are
        // `PositionStore::Owned`, so a long-lived investment account copied
        // its entire lot list on every transaction that touched it.
        // `Position::clone` grew 104x for 10x the input on the `investment`
        // profiling shape — the dominant superlinear term left in the
        // pipeline.
        //
        // The gate below must stay in step with the reduction path's own
        // gate (`Complete` units + a cost spec). If it ever drifts toward
        // cloning MORE, the result is only wasted work; drifting toward
        // cloning less would silently drop a second posting's view of the
        // first, which is what `two_reducing_postings_on_one_account_*`
        // pins.
        let mut reducing_postings: FxHashMap<&rustledger_core::Account, usize> =
            FxHashMap::with_capacity_and_hasher(txn.postings.len(), Default::default());
        for posting in &txn.postings {
            if matches!(posting.units, Some(IncompleteAmount::Complete(_)))
                && posting.cost.is_some()
            {
                *reducing_postings.entry(&posting.account).or_default() += 1;
            }
        }
        for posting in &txn.postings {
            if reducing_postings
                .get(&posting.account)
                .is_some_and(|n| *n > 1)
                && let Some(inv) = self.inventories.get(&posting.account)
            {
                working_inventories
                    .entry(posting.account.clone())
                    .or_insert_with(|| (**inv).clone());
            }
        }

        // First pass: identify postings that need lot matching (reductions)
        for (idx, posting) in txn.postings.iter().enumerate() {
            // Check if this is a reduction with a cost spec
            if let Some(IncompleteAmount::Complete(units)) = &posting.units
                && let Some(cost_spec) = &posting.cost
            {
                // Normalize compound `{a # b}` up front (#1700): both the
                // reduction path (which uses the spec as a lot-match filter
                // via `per_unit()`) and apply() (which re-reduces from the
                // BOOKED posting) need a resolved per-unit — the raw
                // Compound form deliberately exposes neither component as
                // an effective value. Combined total N*a + b is preserved
                // exactly for residual math, same as the {{T}} conversion.
                let normalized_compound: Option<CostSpec> = match cost_spec.number {
                    Some(rustledger_core::CostNumber::Compound { per_unit, total })
                        if !units.number.is_zero() =>
                    {
                        // Checked (#1863): `N*a + b` for a compound cost is a
                        // product of two user-supplied numbers, so it leaves
                        // `Decimal`'s range on inputs well inside it. This is
                        // the ONE reachable site the first pass of the fix
                        // missed — the sweep that was supposed to catch it ran
                        // against a wrongly-assigned binary path and silently
                        // tested nothing.
                        let combined = units
                            .number
                            .abs()
                            .checked_mul(per_unit)
                            .and_then(|v| v.checked_add(total))
                            .ok_or_else(|| {
                                cost_overflow(&posting.account, cost_spec.currency.as_ref(), units)
                            })?;
                        // The per-unit from the shared `a + b/N`, NOT
                        // `combined / N`. `combined` is fine as the total it
                        // is — a final value, correctly rounded — but as the
                        // dividend of a per-unit it is an intermediate product
                        // `checked_mul` rounded to 28 places without failing:
                        // `1e-11` units at `{1e-18 # 0}` made it zero and
                        // booked a per-unit cost of `0` for `1e-18` (#2351).
                        // This site was a copy of `CostSpec::resolve`'s logic
                        // that had drifted into the unsafe form.
                        let combined_per_unit = rustledger_core::CostNumber::compound_per_unit(
                            per_unit,
                            total,
                            units.number,
                        )
                        .ok_or_else(|| {
                            cost_overflow(&posting.account, cost_spec.currency.as_ref(), units)
                        })?;
                        // `try_new`, not `new`: see the underflow case at
                        // the head of this file's sibling site in
                        // `interpolate.rs` (#2340) — a successful division
                        // can still produce a per-unit that cannot
                        // reproduce the total.
                        let booked = rustledger_core::BookedCost::try_new(
                            combined_per_unit,
                            combined,
                            units.number,
                        )
                        .map_err(|_| {
                            cost_overflow(&posting.account, cost_spec.currency.as_ref(), units)
                        })?;
                        Some(CostSpec {
                            number: Some(rustledger_core::CostNumber::PerUnitFromTotal(booked)),
                            currency: cost_spec.currency.clone(),
                            // Date deliberately NOT defaulted to txn.date
                            // here: on a REDUCTION the spec date is a lot
                            // match FILTER (injecting the sell date would
                            // match nothing); on an augmentation the lot's
                            // acquisition date defaults via resolve()'s
                            // date parameter as for plain {N} specs.
                            date: cost_spec.date,
                            label: cost_spec.label.clone(),
                            merge: cost_spec.merge,
                        })
                    }
                    _ => None,
                };
                let normalized_owned;
                let cost_spec = if let Some(normalized) = normalized_compound {
                    result.postings[idx].cost = Some(Box::new(normalized.clone()));
                    normalized_owned = normalized;
                    &normalized_owned
                } else {
                    cost_spec
                };
                // Check if this is a reduction (units have opposite sign of inventory)
                // This handles both:
                // - Selling long positions (negative units, positive inventory)
                // - Closing short positions (positive units, negative inventory)
                if let Some(inv) = working_inventories
                    .get(&posting.account)
                    .or_else(|| self.inventories.get(&posting.account).map(AsRef::as_ref))
                {
                    // Check if these units reduce existing cost-bearing inventory lots.
                    // Only positions with a cost basis are considered; simple (no-cost)
                    // positions are ignored to avoid misclassifying augmentations.
                    //
                    // Under `option "booking_method" "NONE"` (issue #1182),
                    // reduction matching is skipped entirely: NONE means
                    // "accumulate positions without booking against
                    // existing lots." Otherwise the booker would replace
                    // the user-written `{{ total }}` cost spec with a
                    // FIFO-matched per-unit (line ~282 below), and the
                    // residual calculation downstream would weigh the
                    // posting by the matched lots' costs instead of the
                    // user's stated total — producing a phantom
                    // E3001 imbalance for ledgers that round-trip
                    // cleanly through Python beancount.
                    // The canonical predicate, not a re-derivation of it: it
                    // carries the NONE gate and the #2384 own-side exception,
                    // and `apply`, the validator and the query replay ask the
                    // same one.
                    //
                    // Asked with the cost currency this posting will be booked
                    // with, filled in the way the augmentation branch below
                    // fills it. `apply` asks again of the booked posting; a
                    // missing currency is a wildcard here and a fixed one
                    // there, so classifying `{102}` against a 102 EUR lot and
                    // then booking it as `{102 USD}` made the two disagree
                    // (#2384 review). Only the classification sees the filled
                    // currency; the reduction below still matches as written.
                    let method = self.method_for(&posting.account);
                    let classify_spec;
                    // Nothing to fill for a spec naming no per-unit cost
                    // either: the own-side rule never applies to one, and `{}`
                    // is how most sales are written, so it must stay cheap.
                    let classify_as = if cost_spec.currency.is_some()
                        || cost_spec.number.and_then(|n| n.per_unit()).is_none()
                    {
                        cost_spec
                    } else {
                        classify_spec = CostSpec {
                            currency: inferred_cost_currency(posting, cost_spec, txn),
                            ..cost_spec.clone()
                        };
                        &classify_spec
                    };
                    let is_reduction = inv.is_booking_reduction(units, Some(classify_as), method);

                    if is_reduction {
                        // Use reduce (not try_reduce) to actually update the working inventory.
                        // This ensures subsequent postings in the same transaction see
                        // the updated inventory state (e.g., after first posting exhausts a lot).
                        //
                        // Booking errors (ambiguous match, no matching lot, insufficient
                        // units) are propagated so callers see them once. The full
                        // pipeline path in `rustledger check` filters failed transactions
                        // out of the validator's input to avoid double-reporting against
                        // the validator's independent lot-matching pass.
                        // (`method` is resolved above next to the NONE-method gate.)
                        // Mutate the working copy when we made one, so a
                        // later posting on this account sees the reduction.
                        // Otherwise preview against the live inventory:
                        // nothing reads the mutation back, and this way
                        // nothing was copied to produce it. Both call the
                        // same planner inside `Inventory`.
                        // A `{{T}}` reduction names its lot by the total, so match on T/|units|.
                        // `CostSpec::matches` filters on `per_unit()`, which `CostNumber::Total`
                        // does not have: left as-is the spec matches any lot in the currency,
                        // and a wrong total books silently (#2325). The date stays a filter.
                        let total_filter;
                        let match_spec: &CostSpec = match cost_spec.number {
                            Some(rustledger_core::CostNumber::Total { value: total })
                                if !units.number.is_zero() =>
                            {
                                let per_unit =
                                    total.checked_div(units.number.abs()).ok_or_else(|| {
                                        cost_overflow(
                                            &posting.account,
                                            cost_spec.currency.as_ref(),
                                            units,
                                        )
                                    })?;
                                // `try_new`, not `new` (#2340).
                                let booked = rustledger_core::BookedCost::try_new(
                                    per_unit,
                                    total,
                                    units.number,
                                )
                                .map_err(|_| {
                                    cost_overflow(
                                        &posting.account,
                                        cost_spec.currency.as_ref(),
                                        units,
                                    )
                                })?;
                                total_filter = CostSpec {
                                    number: Some(rustledger_core::CostNumber::PerUnitFromTotal(
                                        booked,
                                    )),
                                    ..cost_spec.clone()
                                };
                                &total_filter
                            }
                            _ => cost_spec,
                        };
                        let booking_result = match working_inventories.get_mut(&posting.account) {
                            Some(working) => working.reduce(units, Some(match_spec), method),
                            // Indexing cannot panic here: reaching this arm
                            // means the enclosing `if let` bound `inv` from
                            // its `self.inventories` branch, so the account is
                            // present.
                            None => self.inventories[&posting.account].try_reduce(
                                units,
                                Some(match_spec),
                                method,
                            ),
                        }
                        .map_err(|e| convert_core_booking_error(e, &posting.account))?;
                        {
                            // Check if multiple lots were matched
                            if booking_result.matched.len() > 1 {
                                // Expand single posting into multiple postings
                                let mut expanded = Vec::new();
                                for matched_pos in &booking_result.matched {
                                    let mut new_posting = posting.clone();
                                    // Set units to the matched portion with NEGATED sign
                                    // (matched_pos.units has the inventory sign, but we need
                                    // the reduction sign which is opposite)
                                    let expanded_units = rustledger_core::Amount::new(
                                        -matched_pos.units.number, // Negate: inventory→reduction
                                        matched_pos.units.currency.clone(),
                                    );
                                    new_posting.units =
                                        Some(IncompleteAmount::Complete(expanded_units));
                                    // Set cost from the matched lot
                                    if let Some(cost) = &matched_pos.cost {
                                        new_posting.cost = Some(Box::new(CostSpec {
                                            number: Some(rustledger_core::CostNumber::PerUnit {
                                                value: cost.number,
                                            }),
                                            currency: Some(cost.currency.clone()),
                                            date: cost.date,
                                            label: cost.label.clone(),
                                            merge: false,
                                        }));
                                    }
                                    expanded.push(new_posting);
                                }
                                // STRICT books a multi-lot match only when it takes
                                // EVERY lot the spec matches, and `apply` re-selects
                                // each of these postings by its spec. A lot with no
                                // date (a `{*}` or AVERAGE pool) gets a spec whose
                                // missing date is a wildcard, so it also matches a
                                // dated lot at the same cost, and STRICT refuses the
                                // choice (#2378). Move it to just after the last such
                                // lot: by then they are gone and it is the only lot
                                // left at its cost. Only when one exists, so every
                                // sale that already applied keeps its posting order.
                                // The other methods re-select with the same ordering
                                // `book` used, so a wildcard date lands on the same
                                // lot there.
                                if matches!(
                                    method,
                                    BookingMethod::Strict | BookingMethod::StrictWithSize
                                ) {
                                    sell_undated_lots_after_their_dated_twins(&mut expanded);
                                }
                                expansions.push((idx, expanded));
                                booked_indices.insert(idx);
                            } else if let Some(cost_basis) = &booking_result.cost_basis {
                                // Single lot match - update posting in place.
                                // Prefer the matched lot's exact stored cost to avoid
                                // rounding loss from `(take * c) / take` on full-precision
                                // total-cost lots (#2048).
                                let matched_pos = booking_result.matched.first();
                                // The `else` is reached when the matched position
                                // carries no cost of its own, and the quotient there
                                // is checked like the other three (#2327): it can
                                // leave `Decimal`'s range even though the basis and
                                // the units each sit inside it. `unwrap_or_else`
                                // cannot carry the error out of its closure, which is
                                // why this is an `if let` rather than that.
                                let matched_cost = if let Some(cost) =
                                    matched_pos.and_then(|p| p.cost.as_ref()).cloned()
                                {
                                    cost
                                } else {
                                    let per_unit = cost_basis
                                        .number
                                        .checked_div(units.number.abs())
                                        .ok_or_else(|| {
                                            cost_overflow(
                                                &posting.account,
                                                Some(&cost_basis.currency),
                                                units,
                                            )
                                        })?;
                                    Cost::new_calculated(per_unit, cost_basis.currency.clone())
                                };

                                // Update posting with filled cost. Carry the
                                // matched lot's label (as the date already is) so
                                // the reduction shares lot identity with its
                                // augmenting lot and nets against it — otherwise a
                                // labeled reduction leaves a phantom unlabeled
                                // negative lot in the holdings view (#1666).
                                result.postings[idx].cost = Some(Box::new(CostSpec {
                                    number: Some(rustledger_core::CostNumber::PerUnit {
                                        value: matched_cost.number,
                                    }),
                                    currency: Some(matched_cost.currency),
                                    date: matched_cost.date,
                                    label: matched_cost.label,
                                    // Carry `{*}` through to application (#2068).
                                    // Every other cost spec is a FILTER: it
                                    // selects among lots that already exist, so
                                    // booking can safely resolve it into the one
                                    // lot it picked. `{*}` is an OPERATION — it
                                    // merges the pool and only then reduces it.
                                    // Resolving it into the per-unit cost of the
                                    // pool it created names a lot that does not
                                    // exist until the merge has run, so `apply`
                                    // reported `No matching lot` for holdings the
                                    // account plainly had. The marker has to
                                    // survive so application re-runs the merge.
                                    merge: cost_spec.merge,
                                }));
                                booked_indices.insert(idx);
                            }
                        }

                        // Realized capital gains, per matched lot, for a reduction
                        // that carries a sale `@`price. Iterating `matched` covers
                        // the single-lot AND multi-lot (expanded) cases uniformly, so
                        // a sale crossing several lots yields one disposal per lot,
                        // each with its own acquisition date and cost basis (the
                        // shape tax reporting needs). A costless transfer of a lot
                        // (no price) is not a disposal, so it records nothing.
                        if let Some(price) = &posting.price
                            && let Some(amt) =
                                price.amount.as_ref().and_then(IncompleteAmount::as_amount)
                            // A zero-unit reduction is degenerate — no proceeds to
                            // pro-rate — so record no disposal (guards the `@@`
                            // division too).
                            && !units.number.is_zero()
                        {
                            let total_units = units.number.abs();
                            for m in &booking_result.matched {
                                // A matched cost-bearing lot always carries a cost; skip a
                                // (defensive) cost-less one since it has no basis. The
                                // cost and sale currencies are recorded as-is — a
                                // cross-currency disposal (sale price in a different
                                // currency than the lot's cost) is NOT dropped here; whether
                                // its `proceeds − cost_basis` gain is computable is the
                                // consumer's policy, not the booking engine's.
                                let Some(cost) = &m.cost else { continue };
                                let lot_units = m.units.number.abs();
                                // The lot's cost value (in the cost currency).
                                // Checked like every other product here (#1863,
                                // #2327): both factors are user-supplied, so
                                // their product can leave the range where a bare
                                // `*` PANICS. The fuzzer reaches these now (#2340).
                                let lot_value =
                                    lot_units.checked_mul(cost.number).ok_or_else(|| {
                                        cost_overflow(&posting.account, Some(&cost.currency), units)
                                    })?;
                                // The reduction's sale value (in the sale-price currency).
                                // A `Unit` (`@`) price is exact per unit. A `Total` (`@@`)
                                // price is the EXACT pro-rata share `total × units /
                                // total_units` (multiply before divide, so a single lot and
                                // evenly-dividing splits are exact). It is deliberately NOT
                                // rounded here: rounding a money split to a clean per-lot
                                // figure is a presentation concern that needs the currency's
                                // precision (the report's `DisplayContext`), and rounding in
                                // the booking layer to the total's own scale both distorts
                                // round-dollar totals and can drive the last lot negative.
                                // The exact fractions match Python beancount.
                                let overflow =
                                    || cost_overflow(&posting.account, Some(&amt.currency), units);
                                let sale_value = match price.kind {
                                    rustledger_core::PriceKind::Unit => {
                                        amt.number.checked_mul(lot_units).ok_or_else(overflow)?
                                    }
                                    rustledger_core::PriceKind::Total if !total_units.is_zero() => {
                                        // `prorate`, not a bare
                                        // multiply-then-divide: the product
                                        // leaves `Decimal`'s range long before
                                        // the SHARE does, so a total price of
                                        // 5e14 over 1e15 of 1e15 units has an
                                        // ordinary answer of 5e14 and an
                                        // intermediate of 5e29. This was a bare
                                        // `*` that panicked until #2344 made it
                                        // checked, and checked still refused a
                                        // figure that is perfectly
                                        // representable (#2346).
                                        crate::prorate(amt.number, lot_units, total_units)
                                            .ok_or_else(overflow)?
                                    }
                                    rustledger_core::PriceKind::Total => Decimal::ZERO,
                                };
                                // Closing a SHORT (matched lot has negative units) inverts
                                // the roles: the lot's cost is the price the units were SOLD
                                // at when the short was opened (the proceeds), and the
                                // reduction's price is what is PAID to cover (the basis) —
                                // and the currencies follow suit.
                                let short_sale = m.units.number.is_sign_negative();
                                let (proceeds, cost_basis) = if short_sale {
                                    (
                                        Amount::new(lot_value, &cost.currency),
                                        Amount::new(sale_value, &amt.currency),
                                    )
                                } else {
                                    (
                                        Amount::new(sale_value, &amt.currency),
                                        Amount::new(lot_value, &cost.currency),
                                    )
                                };
                                gains.push(CapitalGain {
                                    account: posting.account.clone(),
                                    currency: units.currency.clone(),
                                    units: lot_units,
                                    cost_basis,
                                    proceeds,
                                    sale_date: txn.date,
                                    acquired_date: cost.date,
                                    short_sale,
                                });
                            }
                        }
                    }
                    // If not a reduction: fall through to augmentation code below
                }

                let is_booked = booked_indices.contains(&idx);
                if !is_booked
                    && let Some(rustledger_core::CostNumber::Total { value: total }) =
                        cost_spec.number
                {
                    // Augmentation with total cost — convert to the
                    // post-booking `PerUnitFromTotal` shape:
                    //   `1.763 VIIIX {{300.00 USD}}` → derived per-unit
                    //   170.165… with total 300.00 preserved.
                    // The preserved total is load-bearing for
                    // precision-preserving residual math (#1026) —
                    // division-then-multiplication at the
                    // `rust_decimal` 28-digit ceiling loses precision.
                    if let Some(currency) = &cost_spec.currency
                        && !units.number.is_zero()
                    {
                        let per_unit = total.checked_div(units.number.abs()).ok_or_else(|| {
                            cost_overflow(&posting.account, Some(currency), units)
                        })?;
                        // `try_new`, not `new` (#2340).
                        let booked =
                            rustledger_core::BookedCost::try_new(per_unit, total, units.number)
                                .map_err(|_| {
                                    cost_overflow(&posting.account, Some(currency), units)
                                })?;
                        result.postings[idx].cost = Some(Box::new(CostSpec {
                            number: Some(rustledger_core::CostNumber::PerUnitFromTotal(booked)),
                            currency: Some(currency.clone()),
                            // Fill in transaction date if no date specified
                            date: cost_spec.date.or(Some(txn.date)),
                            label: cost_spec.label.clone(),
                            merge: cost_spec.merge,
                        }));
                        booked_indices.insert(idx);
                    }
                }

                // Fill in dates and currencies for augmentations (not already booked)
                if !booked_indices.contains(&idx) && cost_spec.number.is_some() {
                    // Cost spec has a number but may be missing date or currency
                    // Fill in missing parts from price annotation, other postings, and transaction date
                    let inferred_currency = inferred_cost_currency(posting, cost_spec, txn);

                    // Check if this is a reduction (opposite sign exists in inventory)
                    // Reductions get their date from matched lot, augmentations get txn date
                    // Must agree with the classification above, or a posting
                    // booked as an augmentation would be left undated.
                    let is_reduction = self.inventories.get(&posting.account).is_some_and(|inv| {
                        let method = self.method_for(&posting.account);
                        // Cloned only to fill a missing currency, which is rare:
                        // this runs for every cost-bearing augmentation.
                        if cost_spec.currency.is_some() {
                            inv.is_booking_reduction(units, Some(cost_spec), method)
                        } else {
                            let filled = CostSpec {
                                currency: inferred_currency.clone(),
                                ..cost_spec.clone()
                            };
                            inv.is_booking_reduction(units, Some(&filled), method)
                        }
                    });

                    // Fill in date for augmentations only (not reductions)
                    let inferred_date = if is_reduction {
                        None // Reductions get their date from matched lot
                    } else {
                        cost_spec.date.or(Some(txn.date))
                    };

                    // Only update if we actually inferred something
                    if inferred_currency.is_some() || inferred_date.is_some() {
                        result.postings[idx].cost = Some(Box::new(CostSpec {
                            number: cost_spec.number,
                            currency: inferred_currency.or_else(|| cost_spec.currency.clone()),
                            date: inferred_date.or(cost_spec.date),
                            label: cost_spec.label.clone(),
                            merge: cost_spec.merge,
                        }));
                    }
                }
            }
        }

        // Apply posting expansions (replace single postings with multiple)
        // Build new postings Vec in one O(n) pass instead of O(n²) remove+insert
        if !expansions.is_empty() {
            // Sort expansions by index for forward iteration
            expansions.sort_by_key(|(idx, _)| *idx);

            let mut new_postings = Vec::with_capacity(
                result.postings.len() + expansions.iter().map(|(_, e)| e.len()).sum::<usize>(),
            );
            let mut expansion_iter = expansions.into_iter().peekable();

            for (idx, posting) in result.postings.into_iter().enumerate() {
                if expansion_iter
                    .peek()
                    .is_some_and(|(exp_idx, _)| *exp_idx == idx)
                {
                    // Replace this posting with expanded postings
                    let (_, expanded) = expansion_iter.next().unwrap();
                    new_postings.extend(expanded);
                } else {
                    // Keep original posting
                    new_postings.push(posting);
                }
            }
            result.postings = new_postings;
        }

        // NOTE: Price normalization (@@→@) is NOT done here to preserve exact
        // total prices for precise residual calculation. Call `normalize_prices()`
        // on the transaction after validation to convert total prices to per-unit.

        Ok(BookedTransaction {
            transaction: result,
            gains,
            booked_indices: booked_indices.into_iter().collect(),
        })
    }

    /// Apply ONE booked posting to the running inventories.
    ///
    /// The canonical "what does this posting do to an inventory" decision:
    /// resolve the account's booking method, then REDUCE against a lot or ADD a
    /// new one. Public because the query engine needs exactly this and was
    /// re-deriving a broken half of it — `Inventory::add` unconditionally, with
    /// no reduction branch at all (#1985). That looked right for FIFO/LIFO,
    /// where booking has already resolved the reduction's cost so its lot key
    /// matches an existing lot and `add` nets it by coincidence, and produced a
    /// dangling negative position under AVERAGE, where the reduction is booked
    /// at the merged average cost — a key belonging to no augmentation.
    ///
    /// # Errors
    ///
    /// [`BookingError`] when the reduction finds no matching lot, or an `add`
    /// overflows. Unlike [`Self::apply`] this is a SINGLE posting, so there is
    /// nothing to roll back — the caller owns transaction atomicity.
    ///
    /// Verify a carried `{*}` against the pool booking recorded (#2068).
    ///
    /// `{*}` is the one cost spec that is an OPERATION rather than a filter, so
    /// booking cannot resolve it into the lot it picked — the merged pool does
    /// not exist until the merge runs. The marker is carried instead, which
    /// means the booked posting re-executes the merge and is only meaningful
    /// against the inventory it was booked against. Applied to different state
    /// it would silently build a DIFFERENT pool.
    ///
    /// Booking records the per-unit cost of the pool it computed, so compare
    /// that against the pool this inventory would produce. Read-only: nothing
    /// has mutated when this reports, so the error needs no rollback to be
    /// honest about the state it leaves behind.
    ///
    /// Skips rather than reports when there is nothing recorded to compare
    /// against — a raw, never-booked `{*}` (`number: None`), a total or
    /// compound cost whose per-unit value is not knowable until units are, or
    /// cost-less lots where `{*}` degrades to AVERAGE. Errors from the merge
    /// plan itself are also skipped: the reduction raises them with its own
    /// message a moment later, and one function should own each message.
    fn verify_merge_precondition(&self, posting: &Posting) -> Result<(), BookingError> {
        let Some(spec) = posting.cost.as_deref() else {
            return Ok(());
        };
        if !spec.merge {
            return Ok(());
        }
        let (Some(units), Some(expected_number), Some(expected_currency)) = (
            posting.amount(),
            spec.number.and_then(|n| n.per_unit()),
            spec.currency.clone(),
        ) else {
            return Ok(());
        };
        let Some(inv) = self.inventories.get(&posting.account) else {
            return Ok(());
        };
        // Only a posting that will actually REDUCE runs the merge; an
        // augmentation carrying `{*}` is added, and comparing it against a pool
        // it never builds would reject a valid posting. Uses the canonical
        // predicate `realize_posting` itself consults, so the two cannot drift.
        //
        // This also keeps `apply`'s rollback guard sound: every posting this
        // can reject is a cost-bearing reduction, which is exactly what
        // `has_reduction` counts, so the undo log is open whenever the check
        // reports. Without the gate, a positive-units `{*}` posting could fail
        // where `rollback_needed` said failure was impossible — an assert, not
        // an error.
        let method = self.method_for(&posting.account);
        if !inv.is_booking_reduction(units, posting.cost.as_deref(), method) {
            return Ok(());
        }
        let Ok(Some(got)) = inv.merged_pool_cost(units) else {
            return Ok(());
        };

        let expected = rustledger_core::Amount::new(expected_number, expected_currency);
        if got == expected {
            return Ok(());
        }
        Err(convert_core_booking_error(
            rustledger_core::BookingError::MergeMismatch {
                currency: units.currency.clone(),
                expected,
                got,
            },
            &posting.account,
        ))
    }

    /// Replay one booked posting against this engine's inventories,
    /// **re-deriving** what it does rather than being told.
    ///
    /// # Which question this answers
    ///
    /// Two different questions run through this engine, and they are not the
    /// same computation done twice:
    ///
    /// - **Realize the booked ledger** — [`Self::apply`]. Every posting of a
    ///   transaction, against the real inventories, in booking's order. What
    ///   booking decided is authoritative, and a disagreement is a defect:
    ///   #2068 and #2070 were both this, and [`Self::apply`]'s `{*}`
    ///   precondition exists to catch a third.
    /// - **Replay a filtered subset** — this method, and the whole-transaction
    ///   [`Self::replay_transaction`] / [`Self::begin_replay`] the query
    ///   executor now uses. They take whatever transactions a filter left, and
    ///   ask what the inventory would be if only those existed. Under AVERAGE
    ///   or `{*}` that is a genuinely different pool, and answering it with the
    ///   whole ledger's pool is the bug (#1985).
    ///
    /// Prefer the transaction-level replays. This one applies a single
    /// posting against live state, so replaying a transaction's postings
    /// through it one by one misreads a transaction that sells past a lot it
    /// touches: a later posting can read as a reduction `book` never made
    /// (#2380). Kept for callers replaying a single posting on purpose.
    ///
    /// So re-derivation here is the FEATURE, not a shortcut, and the
    /// disagreement [`Self::apply`] refuses to tolerate is exactly what this
    /// method is for. That is why the `{*}` precondition sits on
    /// [`Self::apply`] and not here.
    ///
    /// The two used to share one public entry point, distinguished only by
    /// which level a caller happened to call and a comment explaining the
    /// difference. Nothing stopped a filtered replay from being handed
    /// booking's answer, or the realize path from quietly re-deriving.
    ///
    /// # Precondition
    ///
    /// Same as [`Self::apply`]: the posting must already be booked.
    ///
    /// This is a precondition, not a check. A posting whose units are still
    /// elided is SKIPPED and reports success — booking is what fills them in,
    /// so replaying a ledger that never went through it produces empty
    /// balances rather than an error. Nothing in the workspace suite reaches
    /// that path, and the callers that exist all replay booked directives
    /// (`process` partitions failed transactions out before the query
    /// executor sees them), but a caller that skipped booking would be told
    /// nothing. Making it loud is a behavior change and belongs in its own
    /// commit, not a rename.
    pub fn replay_posting(
        &mut self,
        posting: &Posting,
        date: rustledger_core::NaiveDate,
    ) -> Result<(), BookingError> {
        self.realize_posting(posting, date)
    }

    /// Realize one booked posting as part of [`Self::apply`].
    ///
    /// Private on purpose. This is the per-posting half of the *realize*
    /// question, and a caller outside this engine has no business reaching it:
    /// realizing means [`Self::apply`], which applies a whole transaction and
    /// runs the `{*}` precondition first. Replaying a filtered stream means
    /// [`Self::replay_posting`], which is a different question. Leaving this
    /// public is what let the two blur together.
    fn realize_posting(
        &mut self,
        posting: &Posting,
        date: rustledger_core::NaiveDate,
    ) -> Result<(), BookingError> {
        let Some(IncompleteAmount::Complete(units)) = &posting.units else {
            // Booking fills these in, so reaching here means the caller skipped
            // it. Refusing beats the silent `Ok(())` this used to return, which
            // handed back empty balances for an unbooked ledger and said
            // nothing.
            return Err(BookingError::NotBooked {
                account: posting.account.clone(),
            });
        };
        // Resolve the per-account booking method before mutably borrowing the
        // inventories map.
        let method = self.method_for(&posting.account);
        // `make_mut` copies only when a caller is holding a snapshot of this
        // account. Booking on its own never is, so this is a plain `&mut`.
        let inv =
            std::sync::Arc::make_mut(self.inventories.entry(posting.account.clone()).or_default());

        // Reduction vs augmentation — the single source for this decision
        // (`Inventory::is_booking_reduction`), shared with the Late validator so
        // the two can't drift (including the #1182 NONE gate that previously had
        // to be maintained in both crates).
        if inv.is_booking_reduction(units, posting.cost.as_deref(), method) {
            // `reduce` only errors when the lot it would match is missing — a
            // "must book first" precondition violation.
            inv.reduce(units, posting.cost.as_deref(), method)
                .map_err(|e| convert_core_booking_error(e, &posting.account))?;
        } else {
            return self.augment_posting(posting, date);
        }
        Ok(())
    }

    /// Where the booking-order walk puts one posting (#2368).
    ///
    /// `book` reads each posting against the inventory before the transaction
    /// plus that transaction's earlier REDUCTIONS, never its augmentations. A
    /// walk that applies each reduction as it is reached and holds every
    /// augmentation back until the end therefore has `book`'s view in live
    /// state at every step, and this question, asked of live state, gets
    /// `book`'s answer. [`Self::apply`] and [`TransactionReplay`] both walk
    /// through it, so they cannot drift apart.
    ///
    /// `any_cost` is whether any posting of the transaction carries a cost
    /// spec. Without one nothing can reduce, so each posting can be added as
    /// it comes ([`WalkStep::AddNow`]). Only then: a cost-less position does
    /// not change the classification, but `AVERAGE` pools it, so adding one
    /// ahead of an `AVERAGE` sale would move that sale's basis.
    fn walk_step(&self, posting: &Posting, any_cost: bool) -> WalkStep {
        let is_reduction = posting.cost.is_some()
            && posting.amount().is_some_and(|units| {
                self.inventories.get(&posting.account).is_some_and(|inv| {
                    inv.is_booking_reduction(
                        units,
                        posting.cost.as_deref(),
                        self.method_for(&posting.account),
                    )
                })
            });
        if is_reduction {
            WalkStep::Reduce
        } else if any_cost {
            WalkStep::Defer
        } else {
            WalkStep::AddNow
        }
    }

    /// Start replaying `txn` one posting at a time, in the order `book` read
    /// it.
    ///
    /// For a caller that needs the state between postings, as the query
    /// executor's per-posting `account_balance` column does. A caller that
    /// only needs the state after the whole transaction wants
    /// [`Self::replay_transaction`].
    ///
    /// Like [`Self::replay_posting`] this is a *replay*: it runs no `{*}`
    /// precondition and no rollback, because a filtered stream legitimately
    /// meets a different pool than booking recorded (#1985). Unlike it, the
    /// postings are applied in `book`'s order rather than one at a time
    /// against live state, which misreads a transaction that sells past a lot
    /// it touches (#2380).
    pub fn begin_replay<'e, 't>(&'e mut self, txn: &'t Transaction) -> TransactionReplay<'e, 't> {
        TransactionReplay {
            any_cost: txn.postings.iter().any(|p| p.cost.is_some()),
            engine: self,
            txn,
            next: 0,
            deferred: smallvec::SmallVec::new(),
        }
    }

    /// Replay a whole booked transaction in the order `book` read it.
    ///
    /// See [`Self::begin_replay`].
    ///
    /// # Errors
    ///
    /// Any [`BookingError`] a posting's reduction or addition reports; the
    /// postings before it stay applied, as with [`Self::replay_posting`].
    pub fn replay_transaction(&mut self, txn: &Transaction) -> Result<(), BookingError> {
        self.begin_replay(txn).finish()
    }

    /// Add one booked posting as a new position, without asking whether it
    /// reduces anything.
    ///
    /// The augmentation half of [`Self::realize_posting`], split out so
    /// [`Self::apply`] can add a posting it already knows is an augmentation.
    /// Asking again against live state is what went wrong in #2368.
    fn augment_posting(
        &mut self,
        posting: &Posting,
        date: rustledger_core::NaiveDate,
    ) -> Result<(), BookingError> {
        let Some(IncompleteAmount::Complete(units)) = &posting.units else {
            return Err(BookingError::NotBooked {
                account: posting.account.clone(),
            });
        };
        let inv =
            std::sync::Arc::make_mut(self.inventories.entry(posting.account.clone()).or_default());
        // Add to inventory via the canonical cost-resolve shared with the Late
        // validator, `build_balances`, and the query engine (see
        // `CostSpec::resolve`). `apply`'s callers book first, which fills the
        // inferred currency into `cost_spec.currency`; direct-`apply` tests use
        // explicit-currency fixtures, which need no inference.
        inv.add(Position::from_posting(units, posting.cost.as_deref(), date))
            .map_err(|e| {
                convert_core_booking_error(
                    rustledger_core::BookingError::Overflow(e),
                    &posting.account,
                )
            })?;
        Ok(())
    }

    /// Whether any `Inventory::add` this transaction performs could overflow.
    ///
    /// Conservative: `true` means "cannot prove otherwise", never "will". A
    /// `false` lets [`Self::apply`] skip the rollback snapshot, which is pure
    /// cost for the overwhelming majority of transactions (#1897).
    ///
    /// Sound because `add` is the ONLY operation whose failure `apply` rolls
    /// back — `reduce` reports a missing lot, a caller precondition violation
    /// that is deliberately non-fatal, never `Overflow`.
    ///
    /// The headroom offered to each account is the absolute magnitude of the
    /// WHOLE transaction, not of that account's own postings. That over-states
    /// what any one account can consume, which is the safe direction, and it
    /// avoids grouping postings by account and currency — an allocation, which
    /// is the thing being removed.
    /// Whether `apply` must snapshot before mutating.
    ///
    /// Two reasons a posting can fail partway through, and both now abort the
    /// transaction, so both need the earlier postings rolled back:
    ///
    /// * an `add` that overflows (#1863) — [`Self::overflow_is_possible`];
    /// * a `reduce` with no matching lot, which since #1987 is an error rather
    ///   than something to ignore.
    ///
    /// The reduction half is checked separately because `overflow_is_possible`
    /// is about magnitudes and answers `true` for an unfilled posting only by
    /// coincidence. Relying on that coincidence would leave a filled-but-
    /// unbookable transaction (an ambiguous STRICT match with explicit
    /// amounts) mutating half its accounts and then returning `Err`.
    ///
    /// Kept as two predicates rather than folded into one so the #1897
    /// perf reasoning stays legible: snapshotting EVERY transaction cost 2.4x
    /// heap churn and 6% CPU, which is why neither half is unconditional.
    /// Reductions are a minority of transactions in a real ledger, so this
    /// widens the gate without reopening that regression.
    fn rollback_needed(&self, txn: &Transaction) -> bool {
        self.overflow_is_possible(txn) || self.has_reduction(txn)
    }

    /// Whether any posting could fail the way a reduction fails.
    ///
    /// Deliberately NOT [`Inventory::is_booking_reduction`], despite that being
    /// the canonical "is this a reduction" predicate: this one must hold for a
    /// transaction that has not been applied yet, and the inline comment below
    /// records the panic that reading current state caused. The header used to
    /// claim the opposite — it predates #2067's rewrite.
    fn has_reduction(&self, txn: &Transaction) -> bool {
        txn.postings.iter().any(|posting| {
            let Some(units) = posting.amount() else {
                // Unfilled: booking did not complete, so this transaction is
                // exactly the unbookable kind that needs the rollback.
                return true;
            };
            let method = self.method_for(&posting.account);
            if method == BookingMethod::None {
                // NONE accumulates every posting as an augmentation and never
                // matches a lot, so it cannot fail this way.
                return false;
            }
            // Deliberately NOT `is_booking_reduction` against the CURRENT
            // inventory. `apply` classifies each posting against the state
            // its earlier reductions left, not the state before the
            // transaction, so an answer read from state before it runs can be
            // falsified mid-transaction. It once was:
            //
            //     Assets:Stock   10 X {100.00 USD}
            //     Assets:Stock  -20 X {100.00 USD}
            //
            // Against an empty account that answered "no reduction", so no
            // rollback was prepared; `apply` then added the buy first, the
            // second posting failed, and the engine hit its own "the guard is
            // unsound" assertion. (That shape is now a valid short sale of 10,
            // as booking and beancount read it, #2368, but the lesson holds.)
            //
            // Carrying a cost spec is what makes a posting able to reduce, and
            // that does not depend on state, so it cannot be falsified by the
            // transaction itself. Strictly more conservative: every posting
            // this used to catch carries a cost spec too.
            let Some(spec) = posting.cost.as_deref() else {
                return false;
            };
            // `{*}` fails in BOTH directions (#2068). It is checked against the
            // pool booking recorded, and a positive-units posting can be a
            // reduction too — closing a short reduces cost-bearing lots while
            // the sign test below says "augmentation". Left out, a rejected
            // merge on that shape reaches the rollback assert with no log
            // open, turning a reportable error into a panic. Sign-independent
            // and state-independent, so it cannot be falsified mid-transaction
            // either; only `{*}` postings widen the gate, which are rare enough
            // not to reopen the #1897 snapshot regression.
            spec.merge || units.number.is_sign_negative()
        })
    }

    fn overflow_is_possible(&self, txn: &Transaction) -> bool {
        let mut sum_abs = rustledger_core::Decimal::ZERO;
        for posting in &txn.postings {
            let Some(units) = posting.amount() else {
                // An unfilled posting means booking did not complete; do not
                // reason about arithmetic that has not been determined yet.
                return true;
            };
            match sum_abs.checked_add(units.number.abs()) {
                Some(next) => sum_abs = next,
                // The magnitudes alone exceed the range — exactly the case the
                // snapshot exists for.
                None => return true,
            }
        }

        !txn.postings.iter().all(|posting| {
            let Some(units) = posting.amount() else {
                return false;
            };
            // An account with no inventory yet starts from zero, so only the
            // transaction's own magnitudes matter, and `sum_abs` is in range.
            self.inventories
                .get(&posting.account)
                .is_none_or(|inv| inv.add_headroom_for(&units.currency, sum_abs))
        })
    }

    /// Apply a transaction's postings to the running inventories (update
    /// balances).
    ///
    /// # Precondition
    ///
    /// The transaction MUST already be booked — postings filled with complete
    /// units and resolved costs, as produced by [`Self::book_and_interpolate`]
    /// or the free [`book`](crate::book) function. The loader pipeline
    /// guarantees this ordering. A caller that CANNOT guarantee booked input
    /// must not derive a figure from this lot-matching realization — e.g. the
    /// returns engine values **net units at market** (`rustledger-returns`),
    /// never `apply`, so a re-merged booking-failed transaction cannot
    /// over-sell it.
    ///
    /// # Errors
    ///
    /// [`BookingError`] for arithmetic overflow (#1863) or for a reduction
    /// that finds no matching lot (#1987). Either way the transaction is rolled
    /// back whole: no posting of a failing transaction stays applied.
    ///
    /// The reduction case used to be `debug_assert!`-then-ignore, which made
    /// the two build profiles disagree about a user's ledger — debug panicked,
    /// release silently over-stated the holding. Reporting it is what lets a
    /// caller decide, which is the whole point of the precondition.
    pub fn apply(&mut self, txn: &Transaction) -> Result<(), BookingError> {
        // Snapshot every account this transaction touches, so an overflow
        // partway through cannot leave the earlier postings applied.
        //
        // Without this, a transaction the loader then DROPS (`run_booking`'s
        // `failed_indices`) still moved the running balances, and every later
        // transaction booked against the corruption — silently wrong reports
        // and lot matching, which is the outcome this whole change exists to
        // prevent. `Inventory`'s positions are an `imbl::Vector`, so each
        // clone is O(1) structural sharing.
        //
        // `None` records an account that did not exist yet, which must be
        // REMOVED rather than restored to an empty inventory: `apply` is the
        // only thing that creates entries here, and leaving a phantom empty
        // one changes `into_inventories`' output.
        // ...but only when overflow is actually possible. `imbl::Vector`'s clone
        // is O(1), yet it leaves the chunks SHARED, so the next `Inventory::add`
        // pays `Arc::make_mut` and copies a 64-`Position` chunk. Snapshotting
        // every transaction cost 2.4x heap churn and 6% CPU on the nightly
        // profile to guard a case needing values near 7.9e28 (#1897).
        // Record what changes rather than copying what exists.
        //
        // This used to clone every touched account's `Inventory`, justified by
        // a comment saying the positions were an `imbl::Vector` whose clone is
        // O(1). That stopped being true at #2056, when booking's backing became
        // owned — so the guard silently turned into an O(lots) copy per touched
        // account per transaction, and grew into the largest superlinear term
        // left in the pipeline. Ablating it was worth 56% of a
        // 20,000-transaction `investment` run and took the curve from 19.4x to
        // 9.9x per 10x of input.
        //
        // A reduction touches one or two lots; the undo log is proportional to
        // that rather than to what the account holds.
        //
        // Accounts that do not exist yet are tracked separately: `apply` is the
        // only thing that creates entries, and a failed transaction must leave
        // no phantom empty inventory, which would change `into_inventories`'
        // output.
        let recording = self.rollback_needed(txn);
        let mut created: Vec<rustledger_core::Account> = Vec::new();
        if recording {
            // Deduplicate the accounts FIRST, then open one log each.
            //
            // Skipping `begin_undo` when a log is already open would handle a
            // repeated account too, but it would also silently adopt a log left
            // over from an earlier transaction and roll back to the wrong
            // point. `begin_undo` asserts it is not called twice; that
            // assertion only does its job if this never calls it twice for a
            // legitimate reason.
            let mut touched: Vec<&rustledger_core::Account> = Vec::new();
            for posting in &txn.postings {
                if !touched.contains(&&posting.account) {
                    touched.push(&posting.account);
                }
            }
            for account in touched {
                match self.inventories.get_mut(account) {
                    Some(inv) => std::sync::Arc::make_mut(inv).begin_undo(),
                    None => created.push(account.clone()),
                }
            }
        }

        // Roll back only the accounts this transaction touched, found through
        // its postings rather than by sweeping every inventory the engine
        // holds. `undo_is_open` guards the repeat visit when a transaction has
        // two postings on one account.
        let rollback =
            |engine: &mut Self, txn: &Transaction, created: &[rustledger_core::Account]| {
                for posting in &txn.postings {
                    if let Some(inv) = engine.inventories.get_mut(&posting.account)
                        && inv.undo_is_open()
                    {
                        std::sync::Arc::make_mut(inv).rollback_undo();
                    }
                }
                for account in created {
                    engine.inventories.remove(account);
                }
            };

        // Accounts this transaction has already mutated. Booking books every
        // posting against the inventory as it stood BEFORE the transaction,
        // while `apply` mutates sequentially — so once an earlier posting has
        // touched an account, the pool a later `{*}` sees is legitimately not
        // the pool booking recorded, and comparing them would reject a valid
        // ledger (a buy and a `{*}` sale in one transaction). The recorded cost
        // is only comparable against the state booking actually saw.
        let mut touched: rustc_hash::FxHashSet<&rustledger_core::Account> =
            rustc_hash::FxHashSet::default();

        // Decide each posting exactly as `book` did, then realize it the same
        // way (#2070, #2368).
        //
        // `book` walks a transaction in TEXTUAL order against the inventory as
        // it stood before the transaction, threaded with that transaction's
        // earlier REDUCTIONS. It never adds an augmentation to that view: a buy
        // is invisible to every later posting of the same transaction, and so
        // is a short opened by a sale that ran past the end of its lot.
        //
        // So this walks in textual order too, and applies a reduction the
        // moment it is found while holding every augmentation back until the
        // walk is done. Live state during the walk is then exactly `book`'s
        // view -- the pre-transaction inventory plus the reductions so far --
        // so each classification is `book`'s by construction, not by argument.
        // Holding augmentations back is also what keeps a re-derived pool
        // (`AVERAGE`, `{*}`) from seeing the same transaction's buys, which is
        // why reductions went first in the first place (#2070).
        //
        // What this replaced classified every posting against the untouched
        // pre-transaction inventory to ORDER them, then let each posting ask
        // live state again as it ran. Its justification was that threading
        // "can only make a posting look less like a reduction". That is false
        // once a reduction exhausts a lot and the next sale opens a short: the
        // short is an opposite-sign position `book` never sees, and a buy in
        // the same transaction then looked to `apply` like a reduction of it.
        // Holding 2 @ 100, `+9 @101, -2 @100, -2 @100` booked, and then `apply`
        // failed on the buy's own lot. A randomized comparison with lots small
        // enough to exhaust inside one transaction found that and further
        // shapes of the same divergence; the 40-unit property almost never
        // reached any of them.
        //
        // The validator's inventory pass (`update_inventories` in
        // rustledger-validate) walks the same way for the same reason; change
        // one and change the other. [`TransactionReplay`], which the query
        // executor replays through, shares [`Self::walk_step`] with this loop.
        let any_cost = txn.postings.iter().any(|p| p.cost.is_some());
        let mut deferred: smallvec::SmallVec<[usize; 8]> = smallvec::SmallVec::new();
        for (i, posting) in txn.postings.iter().enumerate() {
            let result = match self.walk_step(posting, any_cost) {
                WalkStep::Defer => {
                    deferred.push(i);
                    continue;
                }
                WalkStep::AddNow => self.augment_posting(posting, txn.date),
                WalkStep::Reduce => {
                    // EVERY posting failure aborts the transaction and rolls
                    // back -- overflow and failed reduction alike (#1987). A
                    // carried `{*}` re-executes the merge (#2068), so the pool
                    // it will build is checked against booking's record before
                    // this account first mutates. Here rather than inside
                    // `realize_posting` because a filtered replay for the query
                    // executor legitimately meets a different pool; and per
                    // posting rather than as a pre-pass because an earlier
                    // posting of this transaction can legitimately change the
                    // pool a later `{*}` sees.
                    let checked = if touched.contains(&posting.account) {
                        Ok(())
                    } else {
                        self.verify_merge_precondition(posting)
                    };
                    touched.insert(&posting.account);
                    checked.and_then(|()| self.realize_posting(posting, txn.date))
                }
            };
            if let Err(e) = result {
                assert!(
                    recording,
                    "rollback_needed() returned false but posting application \
                     failed ({e}): the guard is unsound and the earlier \
                     postings of this transaction cannot be rolled back"
                );
                rollback(self, txn, &created);
                return Err(e);
            }
        }
        for posting in deferred.into_iter().map(|i| &txn.postings[i]) {
            let checked = if touched.contains(&posting.account) {
                Ok(())
            } else {
                self.verify_merge_precondition(posting)
            };
            touched.insert(&posting.account);
            // Added, not re-asked: live state now holds the reductions and any
            // shorts they opened, which `book` never saw when it decided this
            // was an augmentation.
            if let Err(e) = checked.and_then(|()| self.augment_posting(posting, txn.date)) {
                assert!(
                    recording,
                    "rollback_needed() returned false but posting application \
                     failed ({e}): the guard is unsound and the earlier \
                     postings of this transaction cannot be rolled back"
                );
                rollback(self, txn, &created);
                return Err(e);
            }
        }

        // Committed: drop the logs and compact the touched accounts.
        // Compaction moved here from `reduce` because it renumbers slots, which
        // an open undo log refers to — this is the one point where no log is
        // open and no rollback can still be required.
        //
        // Skipped entirely when nothing was recorded. Only a reduction creates
        // tombstones, `add` never does, and any reduction makes
        // `rollback_needed` true — so `!recording` means this transaction left
        // nothing to compact and nothing to commit. Without the guard, ledgers
        // that never book a cost spec pay a per-posting map lookup for nothing.
        if !recording {
            return Ok(());
        }
        // Deduplicated: a transaction with several postings on one account
        // would otherwise re-enter `compact_if_sparse` for it, and compaction
        // is O(slots) when it fires.
        let mut committed: Vec<&rustledger_core::Account> = Vec::new();
        for posting in &txn.postings {
            if committed.contains(&&posting.account) {
                continue;
            }
            committed.push(&posting.account);
            if let Some(inv) = self.inventories.get_mut(&posting.account) {
                let inv = std::sync::Arc::make_mut(inv);
                if inv.undo_is_open() {
                    inv.commit_undo();
                }
                inv.compact_if_sparse();
            }
        }
        Ok(())
    }

    /// Book and interpolate a transaction.
    ///
    /// This fills in empty cost specs, then interpolates any missing amounts. Thin
    /// wrapper over [`Self::book_and_interpolate_with_gains`] that discards the
    /// realized gains — a single implementation so the two cannot drift.
    pub fn book_and_interpolate(
        &self,
        txn: &Transaction,
    ) -> Result<InterpolationResult, BookingError> {
        Ok(self.book_and_interpolate_with_gains(txn)?.0)
    }

    /// Book, interpolate and apply `txn` in one step, mutating it in place.
    ///
    /// The three are one step because they share a failure rule: a transaction
    /// that fails any of them is set aside by `run_booking` and merged back
    /// into the ledger by `finalize`, so a user sees it, and it must read as
    /// the author wrote it. Splitting them would hand the caller a
    /// half-interpolated transaction to put back.
    ///
    /// This exists so the common path stops cloning. `book_and_interpolate_
    /// with_gains` hands back an owned transaction the caller assigns over the
    /// original, so every transaction paid a full clone and the original's
    /// drop — 6.9M and 6.0M instructions on a 10,000-transaction ledger, 7.7%
    /// of a warm `check` — to keep a rare failure undoable. Interpolation
    /// touches one or two postings, so `Rollback` saves those instead.
    ///
    /// # Errors
    ///
    /// Any booking, interpolation or apply failure. On every one of them
    /// `txn` is left exactly as it was passed in.
    pub fn book_interpolate_apply(
        &mut self,
        txn: &mut Transaction,
    ) -> Result<Vec<CapitalGain>, BookingError> {
        // Fast path, as in `book_and_interpolate_with_gains`: with no cost
        // specs `book` is an identity, so interpolate the transaction itself.
        if !txn.postings.iter().any(|p| p.cost.is_some()) {
            let tolerances = crate::transaction_tolerances(txn, &self.tolerance.options());
            let undo = crate::interpolate::interpolate_in_place_undoable(txn, &tolerances)?;
            if let Err(e) = self.apply(txn) {
                undo.restore(txn);
                return Err(e);
            }
            return Ok(Vec::new());
        }
        // Slow path: `book` already produces an owned transaction, so work on
        // that and commit only once apply has succeeded. Nothing needs undoing
        // — `txn` is not touched until the end.
        let tolerances = crate::transaction_tolerances(txn, &self.tolerance.options());
        let booked = self.book(txn)?;
        let mut candidate = booked.transaction;
        let _ = crate::interpolate::interpolate_in_place_undoable(&mut candidate, &tolerances)?;
        self.apply(&candidate)?;
        *txn = candidate;
        Ok(booked.gains)
    }

    /// Book and interpolate a transaction, also returning the per-lot
    /// [`CapitalGain`]s `book` computed for it.
    ///
    /// The loader's booking pass uses this so realized gains are captured **once**,
    /// during canonical booking (in booking order, with the ledger's own method,
    /// before `@@` normalization), and exposed on the `Ledger` — rather than each
    /// consumer re-booking the stream and re-deriving them.
    ///
    /// # Errors
    /// Returns a [`BookingError`] if the transaction cannot be booked (e.g. an
    /// ambiguous or unmatched cost reduction) or interpolated (unresolved elided
    /// amounts).
    pub fn book_and_interpolate_with_gains(
        &self,
        txn: &Transaction,
    ) -> Result<(InterpolationResult, Vec<CapitalGain>), BookingError> {
        // Fast path: with no cost specs, `book` is an identity that only clones
        // `txn` verbatim (profiling flagged that clone as ~6 MB / 10k txns — the
        // common case), and it realizes no gains. In the fast path `book(txn)`'s
        // transaction *equals* `txn`, so `interpolate(&book(txn).transaction)` is
        // provably identical to `interpolate(txn)`. Interpolate the original
        // directly, skip the clone, and return no gains (an empty `Vec` does not
        // allocate).
        if !txn.postings.iter().any(|p| p.cost.is_some()) {
            return Ok((
                interpolate_with_tolerances(txn, &self.tolerance.options())?,
                Vec::new(),
            ));
        }
        // Tolerances come from the PRE-booking transaction, matching
        // beancount's `booking_full.book`, which infers them from
        // `entry.postings` before resolving any `{}`. Deriving them after
        // booking would feed the lot's 26-digit per-unit cost into the
        // tolerance and silently disable quantization — see
        // `interpolate_with_tolerance_map`.
        let tolerances = crate::transaction_tolerances(txn, &self.tolerance.options());
        // First book (fill in costs + compute gains), then interpolate amounts.
        let booked = self.book(txn)?;
        let result = interpolate_with_tolerance_map(&booked.transaction, &tolerances)?;
        Ok((result, booked.gains))
    }
}

/// Convert a core inventory `BookingError` into the booking-layer error,
/// attaching the account context that the core layer doesn't carry.
///
/// All inventory-level failures funnel into a single
/// [`BookingError::Inventory`] variant. The user-facing wording lives in the
/// `Display` impl on [`AccountedBookingError`] so it cannot drift between
/// the booking layer and the validator (#748 / #750).
fn convert_core_booking_error(
    err: rustledger_core::BookingError,
    account: &rustledger_core::Account,
) -> BookingError {
    BookingError::Inventory(err.with_account(account.clone()))
}

/// The error for a cost whose per-unit value cannot be represented.
///
/// `total / |units|` leaves `Decimal`'s range (~7.9e28) when the total is large
/// and the unit count small -- `79000000000000000000000000000 W {{...}}` over
/// `0.0000000001` units needs 7.9e38. `rust_decimal`'s `Div` PANICS there, so
/// an absurd but parseable ledger took the process down, and any host embedding
/// the engine with it (#2327).
///
/// #1863 made the multiplication at one of these sites checked and left the
/// division beside it bare; this names the currency the same way that fix does.
fn cost_overflow(
    account: &rustledger_core::Account,
    cost_currency: Option<&rustledger_core::Currency>,
    units: &rustledger_core::Amount,
) -> BookingError {
    convert_core_booking_error(
        rustledger_core::BookingError::Overflow(rustledger_core::OverflowError {
            currency: cost_currency
                .cloned()
                .unwrap_or_else(|| units.currency.clone()),
        }),
        account,
    )
}

/// Book and interpolate a list of transactions.
///
/// This processes transactions in order, tracking inventory to enable
/// proper lot matching and capital gains calculation.
pub fn book_transactions(
    transactions: &[Transaction],
    method: BookingMethod,
) -> Vec<Result<InterpolationResult, BookingError>> {
    let mut engine = BookingEngine::with_method(method);
    let mut results = Vec::with_capacity(transactions.len());

    for txn in transactions {
        // An apply-time overflow belongs to THIS transaction's result, so a
        // caller iterating results sees it rather than silently getting a
        // running balance that never absorbed the posting (#1863).
        let result = engine.book_and_interpolate(txn).and_then(|interpolated| {
            // Apply the booked transaction (with filled-in costs), not the original
            engine.apply(&interpolated.transaction)?;
            Ok(interpolated)
        });
        results.push(result);
    }

    results
}

/// Outcome of booking an entire ledger in one shot — see [`book`].
#[derive(Debug, Clone)]
pub struct LedgerBookResult {
    /// Successfully booked directives, in the **original input order**.
    /// Every `Transaction` has its cost specs filled and elided amounts
    /// interpolated; all other directive kinds pass through unchanged.
    pub booked: Vec<Directive>,
    /// Directives whose `Transaction` failed to book, in original input
    /// order, paired with the error. They are left in their pre-booking
    /// shape so a caller can still surface the user's original input.
    pub failed: Vec<(Directive, BookingError)>,
}

/// Book and interpolate every transaction in a ledger in one shot.
///
/// This is the standalone equivalent of the loader's internal booking
/// pass. Transactions are processed in **booking order** — sorted by
/// `(date, priority)`, with same-key transactions left in the caller's order
/// — so lot matching and capital-gains tracking observe inventory in the
/// same sequence Python does (#2093), while
/// the returned [`LedgerBookResult::booked`] / [`LedgerBookResult::failed`]
/// vectors preserve the caller's **original input order**. Non-transaction
/// directives pass through untouched. Per-account booking methods declared
/// via `Open ... "METHOD"` are honored; `method` is the fallback for
/// accounts that declare none.
///
/// Booking is a pure function of its inputs, so calling it twice on the
/// same `(directives, method)` yields equal results — this is the booking
/// half of the #1235 pipeline-boundary invariants.
#[must_use]
pub fn book(directives: &[Directive], method: BookingMethod) -> LedgerBookResult {
    let mut engine = BookingEngine::with_method(method);
    engine.register_account_methods(directives.iter());

    // Stable sort into booking order. Display order — `(date, priority,
    // file position)` — is already encoded in the input's positional order,
    // and a stable sort keeps that as the tiebreak.
    let mut order: Vec<usize> = (0..directives.len()).collect();
    order.sort_by_key(|&i| rustledger_core::booking_sort_key(&directives[i]));

    // Book in booking order, recording each transaction's outcome against
    // its original index so the result can be reassembled in input order.
    let mut booked_txns: Vec<Option<Transaction>> = directives.iter().map(|_| None).collect();
    let mut booking_errors: Vec<Option<BookingError>> = directives.iter().map(|_| None).collect();
    for &i in &order {
        if let Directive::Transaction(txn) = &directives[i] {
            match engine.book_and_interpolate(txn) {
                Ok(result) => {
                    // Apply the booked transaction (filled-in costs), not
                    // the original, so subsequent lot matching is correct.
                    match engine.apply(&result.transaction) {
                        Ok(()) => booked_txns[i] = Some(result.transaction),
                        Err(e) => booking_errors[i] = Some(e),
                    }
                }
                Err(e) => booking_errors[i] = Some(e),
            }
        }
    }

    // Reassemble in original input order, partitioning failures out.
    let mut booked = Vec::with_capacity(directives.len());
    let mut failed = Vec::new();
    for (i, directive) in directives.iter().enumerate() {
        if let Some(e) = booking_errors[i].take() {
            failed.push((directive.clone(), e));
        } else if let Some(txn) = booked_txns[i].take() {
            booked.push(Directive::Transaction(txn));
        } else {
            booked.push(directive.clone());
        }
    }

    LedgerBookResult { booked, failed }
}

/// The cost currency an augmentation of `posting` is booked with: the spec's
/// own, else the currency its price names, else one inferred from the other
/// postings of `txn`.
///
/// One function for both places `book` needs it, the augmentation's fill-in
/// and the reduction-or-augmentation question asked before it, so the two
/// cannot infer differently (#2384 review).
fn inferred_cost_currency(
    posting: &Posting,
    cost_spec: &CostSpec,
    txn: &Transaction,
) -> Option<rustledger_core::Currency> {
    cost_spec.currency.clone().or_else(|| {
        // `kind` (Unit vs Total) doesn't change the currency, so it's
        // irrelevant here: whatever currency the price names, complete or
        // incomplete.
        posting
            .price
            .as_ref()
            .and_then(|p| p.amount.as_ref())
            .and_then(|inc| inc.currency().map(Into::into))
            .or_else(|| crate::infer_cost_currency_from_postings(txn))
    })
}

/// Move each undated lot's posting in a STRICT expansion to just after the
/// last dated posting at the same cost; see its call site in `book` (#2378).
///
/// Postings with no dated twin stay where they are, so an expansion that could
/// not collide keeps its order exactly.
fn sell_undated_lots_after_their_dated_twins<P: std::ops::Deref<Target = Posting>>(
    expanded: &mut Vec<P>,
) {
    let cost_of = |p: &Posting| {
        p.cost
            .as_deref()
            .map(|c| (c.number.and_then(|n| n.per_unit()), c.currency.clone()))
    };
    let undated = |p: &Posting| p.cost.as_deref().is_some_and(|c| c.date.is_none());
    let mut i = 0;
    while i < expanded.len() {
        if undated(&expanded[i]) {
            let cost = cost_of(&expanded[i]);
            let last_twin = (i + 1..expanded.len())
                .rev()
                .find(|&j| !undated(&expanded[j]) && cost_of(&expanded[j]) == cost);
            if let Some(j) = last_twin {
                // Lands at `j`, past every twin; `i` now holds the next
                // posting, so do not advance.
                let moved = expanded.remove(i);
                expanded.insert(j, moved);
                continue;
            }
        }
        i += 1;
    }
}

/// One step of the booking-order walk; see [`BookingEngine::walk_step`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum WalkStep {
    /// A reduction: apply it now, as `book` did.
    Reduce,
    /// An augmentation in a transaction that carries a cost: hold it back
    /// until every reduction has run.
    Defer,
    /// An augmentation in a transaction with no cost anywhere: nothing can
    /// reduce, so add it now.
    AddNow,
}

/// A transaction being replayed one posting at a time, in `book`'s order.
///
/// Created by [`BookingEngine::begin_replay`]. Call [`Self::advance`] once per
/// posting, in order, reading [`Self::account_snapshot`] between them, then
/// [`Self::finish`]. After posting `i` the snapshot is the state the whole
/// walk would reach over postings `0..=i`: the reductions among them applied,
/// plus the augmentations among them, which the engine itself only adds at
/// the end.
#[must_use = "a replay applies its held-back augmentations only in `finish`"]
pub struct TransactionReplay<'e, 't> {
    engine: &'e mut BookingEngine,
    txn: &'t Transaction,
    any_cost: bool,
    next: usize,
    deferred: smallvec::SmallVec<[usize; 8]>,
}

impl TransactionReplay<'_, '_> {
    /// Replay the next posting of the transaction.
    ///
    /// # Errors
    ///
    /// A reduction that finds no lot to reduce, or an addition that
    /// overflows. Nothing is rolled back.
    ///
    /// # Panics
    ///
    /// If every posting has already been advanced.
    pub fn advance(&mut self) -> Result<(), BookingError> {
        let i = self.next;
        let posting = &self.txn.postings[i];
        self.next += 1;
        match self.engine.walk_step(posting, self.any_cost) {
            WalkStep::Reduce => self.engine.realize_posting(posting, self.txn.date),
            WalkStep::AddNow => self.engine.augment_posting(posting, self.txn.date),
            WalkStep::Defer => {
                self.deferred.push(i);
                Ok(())
            }
        }
    }

    /// `account`'s inventory as of the postings advanced so far, counting
    /// the augmentations still held back.
    ///
    /// Shares the engine's copy when nothing is held back for `account`,
    /// which is every account of a transaction with no reduction after an
    /// augmentation; otherwise builds one.
    ///
    /// # Errors
    ///
    /// [`BookingError::Inventory`] carrying an overflow, if adding a
    /// held-back augmentation overflows.
    pub fn account_snapshot(
        &self,
        account: &rustledger_core::Account,
    ) -> Result<Option<std::sync::Arc<Inventory>>, BookingError> {
        let mut pending = self
            .deferred
            .iter()
            .map(|&i| &self.txn.postings[i])
            .filter(|p| &p.account == account)
            .peekable();
        let base = self.engine.inventory_snapshot(account);
        if pending.peek().is_none() {
            return Ok(base);
        }
        let mut inv = base.map_or_else(Inventory::new, |shared| (*shared).clone());
        for posting in pending {
            // An unfilled posting fails in `finish`; it adds nothing here.
            if let Some(units) = posting.amount() {
                inv.add(Position::from_posting(
                    units,
                    posting.cost.as_deref(),
                    self.txn.date,
                ))
                .map_err(|e| {
                    convert_core_booking_error(
                        rustledger_core::BookingError::Overflow(e),
                        &posting.account,
                    )
                })?;
            }
        }
        Ok(Some(std::sync::Arc::new(inv)))
    }

    /// Replay any postings not yet advanced, then add the held-back
    /// augmentations.
    ///
    /// # Errors
    ///
    /// As [`Self::advance`], and [`BookingError::NotBooked`] for an
    /// augmentation whose units booking never filled.
    pub fn finish(mut self) -> Result<(), BookingError> {
        while self.next < self.txn.postings.len() {
            self.advance()?;
        }
        for &i in &self.deferred {
            self.engine
                .augment_posting(&self.txn.postings[i], self.txn.date)?;
        }
        Ok(())
    }
}

