//! Every combination of up to three BOM tokens, in each line context, is
//! counted as beancount counts it (#2928).
//!
//! A mid-file BOM is reported by rledger's own diagnostic
//! (`BomInDirectiveBody`), which also has to stand in for some of
//! beancount's `Invalid token` errors so that the counts agree: a line's BOM
//! diagnostic, a second one after another line error, a BOM that starts its
//! line, a BOM-led run, a run with a BOM inside it. Each review round of the
//! PR that made a mid-line BOM run to the next blank found another
//! combination whose count drifted, so this checks all of them at once.
//!
//! `data/bom_combination_matrix.tsv` records beancount 3.2.3's per-line
//! parse-error counts for each generated input. It is generated by
//! `scripts/bom-combination-matrix.py`, which runs beancount, so this test
//! needs no Python. Each input is parsed here on both paths (green and red,
//! which must agree), and its per-line counts must equal the table's, except
//! for the inputs listed in `data/bom_combination_matrix_known.tsv`. Each of
//! those names its cause (one of [`CAUSES`]) and records rledger's counts,
//! which must stay as recorded: a known input that changes, for better or
//! worse, fails the test too, so the list cannot go stale.

use std::collections::BTreeMap;

use rustledger_parser::cst::parse_red_only;
use rustledger_parser::{__baseline_canonical_payload, parse};

const DATA: &str = include_str!("data/bom_combination_matrix.tsv");
const KNOWN: &str = include_str!("data/bom_combination_matrix_known.tsv");

/// The lines every generated input starts with (`HEAD` in the script), as
/// the tables write them.
const HEAD: &str = "2024-01-01 open Assets:A\\n2024-01-01 open Assets:B\\n";

/// The causes a known difference may name. Each predates #2928.
const CAUSES: &[&str] = &[
    // A line that starts with a BOM breaks its transaction, and rledger
    // reports each indented line after it, which beancount's recovery skips
    // in silence (#2872).
    "orphan-lines",
    // A run with a BOM inside it, on a line whose BOM diagnostic already
    // stands for the line's first error, is left to that diagnostic: one
    // error fewer than beancount. Reporting it fixes these, and 248 more
    // fuzz-corpus inputs, but also turns 88 matching ones into mismatches,
    // each a difference the old count happened to offset, so it is left for
    // a change of its own.
    "inner-bom-under-line-error",
    // An invalid account after the line's first invalid token is still
    // reported, where beancount reports nothing more for the statement
    // (#2872).
    "account-after-invalid-token",
];

/// A table source back to the input it stands for.
fn unescape(src: &str) -> String {
    src.replace("<BOM>", "\u{FEFF}").replace("\\n", "\n")
}

/// rledger's per-line parse-error counts for `src`, as `line:count` cells.
fn rledger_cells(src: &str) -> String {
    let green = parse(src);
    let red = parse_red_only(src);
    assert_eq!(
        __baseline_canonical_payload(&green),
        __baseline_canonical_payload(&red),
        "green vs red diverged for {src:?}"
    );
    let mut counts: BTreeMap<usize, usize> = BTreeMap::new();
    for e in &green.errors {
        let line = src[..e.span.start.min(src.len())].matches('\n').count() + 1;
        *counts.entry(line).or_default() += 1;
    }
    counts
        .iter()
        .map(|(line, n)| format!("{line}:{n}"))
        .collect::<Vec<_>>()
        .join(",")
}

/// The known differences: source (after [`HEAD`]) to rledger's recorded
/// counts.
fn known() -> BTreeMap<&'static str, &'static str> {
    let mut out = BTreeMap::new();
    for line in KNOWN
        .lines()
        .filter(|l| !l.starts_with('#') && !l.is_empty())
    {
        let fields: Vec<&str> = line.split('\t').collect();
        assert_eq!(fields.len(), 3, "malformed known line: {line:?}");
        for cause in fields[2].split('+') {
            assert!(
                CAUSES.contains(&cause),
                "unknown cause {cause:?} in {line:?}"
            );
        }
        assert!(
            out.insert(fields[0], fields[1]).is_none(),
            "duplicate known line: {line:?}"
        );
    }
    out
}

#[test]
fn test_parse_bom_combination_matrix_matches_beancount() {
    let known = known();
    let mut rows = 0;
    let mut failures = Vec::new();
    let mut seen_known = 0;
    for line in DATA.lines() {
        let (src, expected) = line
            .split_once('\t')
            .unwrap_or_else(|| panic!("malformed matrix line: {line:?}"));
        let tail = src
            .strip_prefix(HEAD)
            .unwrap_or_else(|| panic!("matrix input without the head: {src:?}"));
        let got = rledger_cells(&unescape(src));
        rows += 1;
        match known.get(tail) {
            Some(recorded) => {
                seen_known += 1;
                if got == expected {
                    failures.push(format!("now matches beancount, remove it: {tail}"));
                } else if got != *recorded {
                    failures.push(format!(
                        "{tail}\tbeancount {expected:?}\trecorded {recorded:?}\trledger {got:?}"
                    ));
                }
            }
            None if got != expected => {
                failures.push(format!("{tail}\tbeancount {expected:?}\trledger {got:?}"));
            }
            None => {}
        }
    }
    assert!(rows > 1000, "the matrix has only {rows} rows");
    assert_eq!(
        seen_known,
        known.len(),
        "a known line names an input that is not in the matrix"
    );
    assert!(
        failures.is_empty(),
        "{} input(s) differ from beancount's counts or from the known list:\n{}",
        failures.len(),
        failures.join("\n"),
    );
}
