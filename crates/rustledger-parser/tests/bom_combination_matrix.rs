/// A table source back to the input it stands for.
fn unescape(src: &str) -> String {
    src.replace("<BOM>", "\u{FEFF}")
        .replace("\\n", "\n")
        .replace("\\r", "\r")
        .replace("\\t", "\t")
}

/// `src` with each `#!` or `#+` that does not start its line made `$!` / `$+`,
/// an ordinary invalid run on both sides (`hash_bang_analog` in the script).
fn hash_bang_analog(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let mut prev: Option<char> = None;
    let mut chars = src.chars().peekable();
    while let Some(c) = chars.next() {
        let mid_line = prev.is_some_and(|p| p != '\n');
        if c == '#' && mid_line && matches!(chars.peek(), Some('!' | '+')) {
            out.push('$');
        } else {
            out.push(c);
        }
        prev = Some(c);
    }
    out
}

/// `src` as main read it before #2928 made a mid-line `#!` / `#+` a `#` and
/// the token after it: each `#!` or `#+` past its line's start (and past the
/// BOMs that start the line, which the lexer steps over there) and the rest
/// of its line cut off, since main lexed them as a comment to the end of the
/// line. A `\r` that ends the line is kept.
fn hash_bang_cut(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    for line in src.split_inclusive('\n') {
        let (content, newline) = line.strip_suffix('\n').map_or((line, ""), |c| (c, "\n"));
        let (content, cr) = content
            .strip_suffix('\r')
            .map_or((content, ""), |c| (c, "\r"));
        let start = content.len() - content.trim_start_matches(BOM).len();
        let cut = ["#!", "#+"]
            .iter()
            .filter_map(|m| {
                content
                    .match_indices(m)
                    .map(|(i, _)| i)
                    .find(|&i| i > start)
            })
            .min();
        out.push_str(cut.map_or(content, |i| &content[..i]));
        out.push_str(cr);
        out.push_str(newline);
    }
    out
}

/// `line:count` cells back to a map.
fn parse_cells(cells: &str) -> BTreeMap<usize, usize> {
    cells
        .split(',')
        .filter(|c| !c.is_empty())
        .map(|c| {
            // A cell holds one `:`, so `rsplit_once` would be the same.
            let (line, n) = c.split_once(':').expect("line:count");
            (line.parse().expect("line"), n.parse().expect("count"))
        })
        .collect()
}

fn cells(counts: &BTreeMap<usize, usize>) -> String {
    counts
        .iter()
        .map(|(line, n)| format!("{line}:{n}"))
        .collect::<Vec<_>>()
        .join(",")
}

/// rledger's per-line parse-error counts for `src`.
fn rledger_counts(src: &str) -> BTreeMap<usize, usize> {
    rledger_lines(src).all
}

/// rledger's per-line parse-error counts for one input: all of them, and
/// those of the two kinds a cause names, the stray-BOM diagnostic (`P0026`)
/// and the invalid account (`P0006`).
#[derive(Default)]
struct Kinds {
    all: BTreeMap<usize, usize>,
    bom: BTreeMap<usize, usize>,
    account: BTreeMap<usize, usize>,
}

fn rledger_lines(src: &str) -> Kinds {
    let green = parse(src);
    let red = parse_red_only(src);
    assert_eq!(
        __baseline_canonical_payload(&green),
        __baseline_canonical_payload(&red),
        "green vs red diverged for {src:?}"
    );
    let mut kinds = Kinds::default();
    for e in &green.errors {
        // A file-level error is line 0 on both sides, as in the parity
        // harness (`RLEDGER_EOF_CODES`): beancount reports an unclosed
        // `pushtag` / `pushmeta` there, rledger at the push.
        let file_level = matches!(
            e.kind,
            ParseErrorKind::UnclosedPushtag(_) | ParseErrorKind::UnclosedPushmeta(_)
        );
        let line = if file_level {
            0
        } else {
            src[..e.span.start.min(src.len())].matches('\n').count() + 1
        };
        *kinds.all.entry(line).or_default() += 1;
        match e.kind {
            ParseErrorKind::BomInDirectiveBody => *kinds.bom.entry(line).or_default() += 1,
            ParseErrorKind::InvalidAccount(_) => *kinds.account.entry(line).or_default() += 1,
            _ => {}
        }
    }
    kinds
}

fn strip_boms(s: &str) -> &str {
    s.trim_start_matches(BOM)
}

const fn is_blank(c: char) -> bool {
    c == ' ' || c == '\t'
}

fn indented(line: &str) -> bool {
    strip_boms(line).starts_with(is_blank)
}

/// A date alone on its line: beancount's `DATE` token (`beancount_date`),
/// then nothing it reads but blanks, a `\r` (which its lexer reads as a
/// blank) and a `;` comment (which may start anywhere on a line there), so
/// its grammar meets the end of the line right after the date and reports
/// its `unexpected EOL` on the next line. Not after a BOM: beancount reads
/// `<BOM>2024-01-02` as one invalid token, and reports nothing on the next
/// line.
fn date_alone(line: &str) -> bool {
    let before_comment = line.split_once(';').map_or(line, |(head, _)| head);
    beancount_date(before_comment.trim_end_matches([' ', '\t', '\r']))
}

/// Whether `token` is one `DATE` token to beancount 3.2.3's lexer that it
/// turns into a date: its regex `[0-9]{4,}[-/][0-9]+[-/][0-9]+` (either
/// separator at either place, so `2024-01/02` too), and fields that make a
/// Python `datetime.date` (a year from 1 to 9999, so `02024` is 2024; a
/// month from 1 to 12; a day of that month, leap years included). Its C code
/// reads each field into a 32-bit integer that wraps, so `4294967297-01-01`
/// is year 1 there, and `4294967296-01-01` year 0. An invalid one
/// (`2024-13-45`, `10000-01-01`) is reported on its own line on both sides,
/// so no `unexpected EOL` moves. Written out here rather than asked of the
/// parser, so the parser is not the judge of its own counts; every case in
/// `test_beancount_date_reads_dates_as_beancount_does` was checked against
/// bean-check 3.2.3.
fn beancount_date(token: &str) -> bool {
    let mut fields = token.split(['-', '/']);
    let (Some(year), Some(month), Some(day), None) =
        (fields.next(), fields.next(), fields.next(), fields.next())
    else {
        return false;
    };
    let digits = |f: &str| !f.is_empty() && f.bytes().all(|b| b.is_ascii_digit());
    if year.len() < 4 || !(digits(year) && digits(month) && digits(day)) {
        return false;
    }
    let value = |f: &str| {
        f.bytes().fold(0u32, |n, b| {
            n.wrapping_mul(10).wrapping_add(u32::from(b - b'0'))
        })
    };
    let (year, month, day) = (value(year), value(month), value(day));
    // `% n <= 0` for either `== 0` would be the same: a `u32` remainder is
    // never below 0.
    let leap = year % 4 == 0 && (year % 100 != 0 || year % 400 == 0);
    let days = match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 if leap => 29,
        2 => 28,
        _ => return false,
    };
    (1..=9999).contains(&year) && (1..=days).contains(&day)
}

fn words(line: &str) -> impl Iterator<Item = &str> {
    // The empty-word filter changes no result: the only caller,
    // `lone_capital_glued`, asks for a word's first character, which an
    // empty word does not have.
    line.split(is_blank).filter(|w| !w.is_empty())
}

/// A `#!` or `#+` anywhere but the line's first column.
fn mid_line_hash_bang(line: &str) -> bool {
    let s: String = line.chars().filter(|&c| c != BOM).collect();
    ["#!", "#+"]
        .iter()
        .any(|m| s.match_indices(m).any(|(i, _)| i > 0))
}

/// A lone capital glued to a token (or a `\r`) beancount's `CAPITAL`, which
/// needs a blank after it, does not take.
fn lone_capital_glued(line: &str) -> bool {
    words(line).any(|w| {
        let mut chars = strip_boms(w).chars();
        // `is_none_or` here would change nothing: a word of BOMs alone has
        // no first character, and then no second one for the test below.
        chars.next().is_some_and(|c| c.is_ascii_uppercase())
            && chars
                .next()
                .is_some_and(|c| "#!&?%*~^,|@{}()\"$:;=\r".contains(c))
    })
}

/// The data lines of one of the lists: not empty, and not a header line,
/// which starts `# ` or is a bare `#` (a source may start `#`).
fn data_lines(text: &str) -> impl Iterator<Item = &str> {
    text.lines()
        .filter(|l| !l.is_empty() && !l.starts_with("# ") && *l != "#")
}

/// The hand-kept exceptions (`data/bom_combination_matrix_exceptions.tsv`): a
/// line no rule explains, by input and line, with why.
fn exceptions() -> BTreeMap<(&'static str, usize), &'static str> {
    parse_exceptions(EXCEPTIONS)
}

/// The exceptions written in `text`, as the exceptions file holds them.
/// Panics on a malformed line or a reason that does not start with its
/// counts.
fn parse_exceptions(text: &str) -> BTreeMap<(&str, usize), &str> {
    data_lines(text)
        .map(|l| {
            let f: Vec<&str> = l.split('\t').collect();
            assert_eq!(f.len(), 3, "malformed exception line: {l:?}");
            // A reason of blanks alone is empty under either trim, so
            // `trim_start` would be the same.
            assert!(!f[2].trim().is_empty(), "no reason: {l:?}");
            // Every reason names its counts; `reason_counts` panics if not.
            reason_counts(f[2]);
            ((f[0], f[1].parse().expect("a line number")), f[2])
        })
        .collect()
}

/// The counts an exception's reason was written for, as (rledger,
/// beancount, main), read from the `rledger counts X where beancount counts
/// Y (main Z)` it starts with, as the exceptions file's header says. Panics
/// on a reason that does not start so.
fn reason_counts(reason: &str) -> (usize, usize, usize) {
    let fail = || -> ! {
        panic!(
            "a reason must start `rledger counts X where beancount counts Y (main Z)`: \
             {reason:?}"
        )
    };
    let mut rest = reason
        .strip_prefix("rledger counts ")
        .unwrap_or_else(|| fail());
    let mut number = |upto: &str| -> usize {
        let (n, after) = rest.split_once(upto).unwrap_or_else(|| fail());
        rest = after;
        n.parse().unwrap_or_else(|_| fail())
    };
    (
        number(" where beancount counts "),
        number(" (main "),
        number(")"),
    )
}

/// Whether line `l`'s difference is an end-of-file error put on another
/// line: beancount reports errors on the input's last line `eof` (the
/// split's last piece: the empty line after a final `\n`, or the last line
/// itself in an input that does not end with one), rledger the same number
/// on the line `last` before it, and the two lines together agree (`l` is
/// one of the two).
fn eof_error_on_last_line(lines: &[&str], l: usize, counts: &Counts) -> bool {
    let get = |m: &BTreeMap<usize, usize>, k: usize| m.get(&k).copied().unwrap_or(0);
    // `lines` is never empty (a split yields at least one piece), so the
    // subtraction never saturates, and `wrapping_sub` would be the same.
    let last = lines.len().saturating_sub(1);
    let eof = last + 1;
    // `bc[eof] > 0` cannot change the result: with the other three holding
    // and `bc[eof]` 0, line `eof` counts 0 on both sides and line `last`
    // counts `bc[last]` on both, so `l` is a line with `b == r`, which the
    // only caller, `check_row`, skips. Nor can `l >= last` / `l >= eof`
    // for either `==` of the first test: no line past `eof` has a count on
    // either side (an error is at most at the end of the input, which is on
    // line `eof`), so none is asked.
    // `rl[eof] <= 0` is `rl[eof] == 0` for a count.
    (l == last || l == eof)
        && get(&counts.bc, eof) > 0
        && get(&counts.rl, eof) == 0
        && get(&counts.bc, last) + get(&counts.bc, eof) == get(&counts.rl, last)
}

/// Whether beancount skips a line that starts with `s` (an org-mode heading,
/// a comment, or another of its ignored line starts), as rledger's lexer
/// decides it (`beancount_ignores_line`). `s` is one line, so no `\n`
/// follows its first character, and the lexer's check that the next
/// character is not a `\n` is left out.
fn skipped_line_start(s: &str) -> bool {
    let mut chars = s.chars();
    match (chars.next(), chars.next()) {
        (Some(';'), _) => true,
        (Some('#'), Some(next)) => !(next.is_ascii_alphanumeric() || "-_/.".contains(next)),
        (Some('*' | ':' | '!' | '&' | '?' | '%'), Some(_)) => true,
        _ => false,
    }
}

/// A `{#` with a tag character right after it.
fn brace_hash_before_tag(line: &str) -> bool {
    line.match_indices("{#").any(|(i, _)| {
        line[i + 2..]
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_alphanumeric() || "-_/.".contains(c))
    })
}

/// Where beancount 3.2.3's own lexer puts an input's BOMs (the table's last
/// two columns), as byte offsets into the input: the `ACCOUNT` tokens that
/// start with a BOM, and the BOMs inside an invalid token past its leading
/// BOMs. Read from beancount, not guessed, since where a token starts depends
/// on the token before it (`ab:<BOM>a:B` and `-<BOM>a:B` start an account,
/// `$<BOM>a:B` and `1.5.<BOM>a:B` swallow the BOM into an invalid token).
#[derive(Clone, Default)]
struct BomRoles {
    accounts: Vec<std::ops::Range<usize>>,
    inner: Vec<usize>,
}

impl BomRoles {
    fn parse(accounts: &str, inner: &str) -> Self {
        let number = |s: &str| s.parse::<usize>().expect("a byte offset");
        Self {
            accounts: accounts
                .split(',')
                .filter(|c| !c.is_empty())
                .map(|c| {
                    // A range holds one `-`, so `rsplit_once` would be
                    // the same.
                    let (a, b) = c.split_once('-').expect("start-end");
                    number(a)..number(b)
                })
                .collect(),
            inner: inner
                .split(',')
                .filter(|c| !c.is_empty())
                .map(number)
                .collect(),
        }
    }

    /// Whether a BOM-led account starts in `span`. Asking for its last byte
    /// instead would change nothing: an `ACCOUNT` token holds no `\n`, so it
    /// starts and ends on one line.
    fn account_in(&self, span: &std::ops::Range<usize>) -> bool {
        self.accounts.iter().any(|a| span.contains(&a.start))
    }

    /// Whether a BOM-led account starts exactly at byte `at`.
    fn account_at(&self, at: usize) -> bool {
        self.accounts.iter().any(|a| a.start == at)
    }
}

/// `src` with each account beancount reads from a run of BOMs written as the
/// ordinary account `Assets:X`: an `ACCOUNT` token to beancount either way.
fn ordinary_accounts(src: &str, roles: &BomRoles) -> String {
    let mut out = String::with_capacity(src.len());
    let mut at = 0;
    for account in &roles.accounts {
        out.push_str(&src[at..account.start]);
        // Any other valid account name (`Assets:Y`, `Equity:Z`) gives the
        // same counts: both lexers read it as one `ACCOUNT`, the parser
        // checks an account's name only for validity, and a parse count
        // never depends on whether the account is open.
        out.push_str("Assets:X");
        at = account.end;
    }
    out.push_str(&src[at..]);
    out
}

/// `src` with each BOM inside an invalid token on `span` made a `$`: still
/// one invalid token to beancount.
fn ordinary_inner_boms(src: &str, roles: &BomRoles, span: &std::ops::Range<usize>) -> String {
    let mut out = String::with_capacity(src.len());
    let mut at = 0;
    // The span filter cannot change the count of the line on `span`, the
    // only count read from the rewrite: another line's inner BOM is past its
    // invalid token's first character, and a `$` there is as invalid, runs
    // to the same blank and swallows the same `"` or `;`, so that line stays
    // an error line with the same start, indentation and strings, all a
    // later line's count depends on. Measured too: no input tried
    // (line-start, glued, header, push and pop lines before the line, each
    // with its BOM rewritten) moved the line's count. The filter keeps the
    // rewrite to the line, as the doc says.
    for &i in roles.inner.iter().filter(|i| span.contains(i)) {
        out.push_str(&src[at..i]);
        // A `$`, which starts no token on either side, and not a letter: an
        // `x` makes `t<BOM>n` the keyword `txn`, a token rledger reads on
        // (`$n0 t<BOM>n`, pinned by
        // `test_cause_inner_bom_under_line_error_rewrites_to_no_token`).
        out.push('$');
        at = i + BOM.len_utf8();
    }
    out.push_str(&src[at..]);
    out
}

/// A BOM, then later an account starting with a non-ASCII character.
fn account_after_bom(line: &str) -> bool {
    line.find(BOM).is_some_and(|i| {
        line[i..].match_indices('\u{dc}').any(|(j, _)| {
            // A split always yields a first piece, so `is_none_or` would
            // be the same.
            line[i + j..]
                .split(is_blank)
                .next()
                .is_some_and(|w| w.contains(':'))
        })
    })
}

/// Per-line counts of one input: beancount's, rledger's, main's,
/// beancount's and main's for the input with its BOMs replaced by ordinary
/// characters, beancount's with each mid-line `#!` / `#+` made an ordinary
/// invalid run, and beancount's for each line alone.
struct Counts {
    bc: BTreeMap<usize, usize>,
    rl: BTreeMap<usize, usize>,
    main: BTreeMap<usize, usize>,
    analog_bc: BTreeMap<usize, usize>,
    analog_main: BTreeMap<usize, usize>,
    hash_bang_bc: BTreeMap<usize, usize>,
    /// A line beancount crashed on alone has no entry.
    bc_alone: BTreeMap<usize, usize>,
    /// rledger's `P0026` and `P0006` errors per line.
    rl_bom: BTreeMap<usize, usize>,
    rl_account: BTreeMap<usize, usize>,
    /// Where beancount's lexer puts the input's BOMs.
    roles: BomRoles,
    /// beancount's grammar errors on each line after the line's first error.
    later_grammar: BTreeMap<usize, usize>,
}

/// The byte range of line `l` (1-based) of `input`, without its `\n`.
fn line_span(input: &str, l: usize) -> std::ops::Range<usize> {
    let mut start = 0;
    for (k, line) in input.split('\n').enumerate() {
        if k + 1 == l {
            // Taking the `\n` in as well would change nothing: the span is
            // only asked whether an account or an inner BOM starts in it,
            // and neither starts at a `\n`. `k + 1 >= l` would change only
            // line 0's span (the first line's for the end of the input),
            // which nothing reads: `cause` names line 0 (`l == 0`, or the
            // early `like-main-without-bom`, which reads no span) before
            // anything reads it, and `holds` reads a span only for a cause
            // `cause` never gives line 0.
            return start..start + line.len();
        }
        start += line.len() + 1;
    }
    start..start
}

/// One line's difference, as the cause checks read it.
struct LineFacts<'a> {
    input: &'a str,
    text: &'a str,
    line: usize,
    span: std::ops::Range<usize>,
    roles: &'a BomRoles,
    later_grammar: usize,
    bc: usize,
    rl: usize,
    analog_bc: usize,
    analog_main: usize,
    hash_bang_bc: usize,
    bc_alone: Option<usize>,
    boms: usize,
}

impl LineFacts<'_> {
    fn new<'a>(input: &'a str, text: &'a str, l: usize, counts: &'a Counts) -> LineFacts<'a> {
        let get = |m: &BTreeMap<usize, usize>| m.get(&l).copied().unwrap_or(0);
        LineFacts {
            input,
            text,
            line: l,
            span: line_span(input, l),
            roles: &counts.roles,
            later_grammar: get(&counts.later_grammar),
            bc: get(&counts.bc),
            rl: get(&counts.rl),
            analog_bc: get(&counts.analog_bc),
            analog_main: get(&counts.analog_main),
            hash_bang_bc: get(&counts.hash_bang_bc),
            bc_alone: counts.bc_alone.get(&l).copied(),
            boms: get(&counts.rl_bom),
        }
    }

    /// Whether rledger counts the line alone as beancount does alone.
    fn alone_matches(&self) -> bool {
        self.bc_alone == Some(standalone_count(self.text))
    }

    /// Whether rledger's count is beancount's less exactly the grammar errors
    /// beancount reports on the line after its first error: one diagnostic
    /// for the line, standing for that first error.
    fn later_grammar_is_the_difference(&self) -> bool {
        // `rl >= 1` cannot change the result on real counts: with `rl` 0 the
        // rest needs `bc == later_grammar`, and the errors after a line's
        // first are at most `bc - 1`, so only `bc` 0 passes, a line with
        // `bc == rl` that the callers never ask about.
        self.rl >= 1 && self.bc.checked_sub(self.rl) == Some(self.later_grammar)
    }

    /// Whether a BOM-led account starts on the line, and with each such
    /// account written `Assets:X` (an `ACCOUNT` to beancount either way)
    /// rledger counts the line exactly as beancount does.
    fn account_grammar_error_is_the_difference(&self) -> bool {
        self.roles.account_in(&self.span)
            && rledger_counts(&ordinary_accounts(self.input, self.roles))
                .get(&self.line)
                .copied()
                .unwrap_or(0)
                == self.bc
    }

    /// Whether the line has BOMs inside an invalid token (beancount's own,
    /// not an account, which admits a BOM), and with each made a `$` (still
    /// one invalid token to beancount) rledger counts the line exactly as
    /// beancount does: its count moves by the line's whole difference.
    fn inner_boms_are_the_difference(&self) -> bool {
        // The in-span check cannot change the result on counts rledger
        // produced: with no inner BOM the rewrite changes nothing, so the
        // line counts `rl`, and the only caller asks with `rl < bc`. It
        // keeps made-up counts from passing on an empty rewrite, as
        // `test_cause_inner_bom_under_line_error_needs_fewer_errors_and_a_bom_diagnostic`
        // pins.
        self.roles.inner.iter().any(|i| self.span.contains(i))
            && rledger_counts(&ordinary_inner_boms(self.input, self.roles, &self.span))
                .get(&self.line)
                .copied()
                .unwrap_or(0)
                == self.bc
    }
}

/// The parts of a composite cause, `&`-joined in a cause's name.
const GLUED: &str = "bom-glued-to-account";
const HASH_BANG: &str = "mid-line-hash-bang";
const CONSTRUCT: &str = "extra-construct-error";
const GLUED_HASH_BANG: &str = "bom-glued-to-account&mid-line-hash-bang";
const GLUED_CONSTRUCT: &str = "bom-glued-to-account&extra-construct-error";

/// Whether `parts` (of `GLUED`, `HASH_BANG`, `CONSTRUCT`, in that order)
/// explain line `f.line`'s whole difference: each part's share is not zero,
/// and the shares add up to exactly rledger's count less beancount's. The
/// parts are taken out one after the other, each share measured on what the
/// parts before it left:
///
/// - `GLUED`: how many errors go when each account beancount reads with its
///   BOMs is written as the ordinary account `Assets:X` (`ordinary_accounts`,
///   an `ACCOUNT` to beancount either way, so its count stays): more than
///   none, and no more than the line's `P0026`s;
/// - `HASH_BANG`: the line has a mid-line `#!` / `#+`, and its share is how
///   much of what is left of the difference goes when each is made an
///   ordinary invalid run (`hash_bang_analog`, against beancount's own count
///   for that input);
/// - `CONSTRUCT`: main's own overcount of the BOM-free analog, beancount's
///   and main's counts for the input with its BOMs replaced by ordinary
///   characters.
///
/// A glued or construct share only ever adds errors, so it is positive. A
/// hash-bang share is usually negative: rledger reads a mid-line `#!` / `#+`
/// as one token to the end of the line, counting fewer errors there than
/// beancount. On the `bom-glued-to-account&mid-line-hash-bang` rows it is
/// usually -2 to -4 (-1 on one row), and positive (+1) on one row.
fn parts_hold(parts: &[&str], f: &LineFacts<'_>) -> bool {
    let count = |s: &str| rledger_counts(s).get(&f.line).copied().unwrap_or(0);
    let mut src = f.input.to_string();
    let (mut r, mut b) = (f.rl, f.bc);
    let mut shares = 0;
    for part in parts {
        let share = match *part {
            GLUED => {
                // The first part, so `src` is still the input the roles'
                // offsets are into.
                src = ordinary_accounts(&src, f.roles);
                let after = count(&src);
                let share = signed(r) - signed(after);
                // A zero share is turned away below, with every part's, so
                // `share <= 0` (or `share < 1`) would change nothing.
                if share < 0 || share > signed(f.boms) {
                    return false;
                }
                r = after;
                share
            }
            HASH_BANG => {
                // Needed: the analog rewrites every `#!` / `#+` of the input
                // past a line's first character, not only this line's, and
                // also one after a line-start BOM, which `mid_line_hash_bang`
                // does not count (`<BOM>#!x $y`: rledger 1, the analog 2).
                // So a line with no mid-line `#!` / `#+` can still have a
                // share, from another line's rewrite or from beancount's
                // count for the analog, and would be named for a hash-bang
                // it does not hold. Pinned on made-up counts by
                // `test_cause_glued_hash_bang_needs_a_hash_bang_on_the_line`.
                if !mid_line_hash_bang(f.text) {
                    return false;
                }
                src = hash_bang_analog(&src);
                let after = count(&src);
                // `b` is still `f.bc` here, so either can be read: only this
                // arm sets it, and no cause names `HASH_BANG` twice.
                let share = hash_bang_share(r, b, after, f.hash_bang_bc);
                // Read by no later part today (`HASH_BANG` is the last part
                // of every cause that names it); kept so that a part after
                // it would measure what it left.
                (r, b) = (after, f.hash_bang_bc);
                share
            }
            CONSTRUCT => {
                // A construct error only ever adds one. `share <= 0` (or
                // `share < 1`) would change nothing: a zero share is turned
                // away below.
                let share = signed(f.analog_main) - signed(f.analog_bc);
                if share < 0 {
                    return false;
                }
                share
            }
            // Every caller passes parts of the three above: `cause` its own
            // lists, `holds` only after checking each part.
            _ => unreachable!("not a part of a composite cause: {part}"),
        };
        // Every part's share is not zero. The zero check is the only one that turns away a zero
        // `GLUED` share (its arm leaves zero here), which the matrix test
        // needs: without it a line the rewrite leaves as it was is named
        // `GLUED_HASH_BANG`. It is also what makes the order of `GLUED` and
        // `GLUED_HASH_BANG` in `cause` change no result (see the comment
        // there).
        if share == 0 {
            return false;
        }
        shares += share;
    }
    shares == signed(f.rl) - signed(f.bc)
}

/// The share of a line's difference a mid-line `#!` / `#+` accounts for
/// (`parts_hold`): the difference before the hash-bang rewrite, rledger `r`
/// less beancount `b`, less the difference after it, rledger `after` less
/// beancount `hash_bang_bc` for the rewritten input.
const fn hash_bang_share(r: usize, b: usize, after: usize, hash_bang_bc: usize) -> i64 {
    (signed(r) - signed(b)) - (signed(after) - signed(hash_bang_bc))
}

/// Whether, with each account beancount reads with its BOMs written as an
/// ordinary one, the line loses exactly as many `P0026`s as it counts more
/// than beancount, and gains a non-BOM error in their place.
fn glued_boms_replace_construct(f: &LineFacts<'_>) -> bool {
    let after = rledger_lines(&ordinary_accounts(f.input, f.roles));
    let get = |m: &BTreeMap<usize, usize>| m.get(&f.line).copied().unwrap_or(0);
    let (boms_after, all_after) = (get(&after.bom), get(&after.all));
    let gone = signed(f.boms) - signed(boms_after);
    let non_bom = |all: usize, boms: usize| signed(all) - signed(boms);
    // `>` as `>=` would change no result: with as many non-BOM errors after
    // the rewrite as before, `all_after` is `rl - gone`, which is `bc`, so
    // `GLUED` holds (a share of `gone`, more than none and no more than the
    // line's `P0026`s) and `cause` asks it first.
    gone == signed(f.rl) - signed(f.bc) && non_bom(all_after, boms_after) > non_bom(f.rl, f.boms)
}

/// The cause of line `l`'s difference, or `None` when no rule explains it.
/// `lines` are the input's lines (line `k` is `lines[k - 1]`).
fn cause(
    lines: &[&str],
    l: usize,
    counts: &Counts,
    input: &str,
    tail: &str,
) -> Option<&'static str> {
    let get = |m: &BTreeMap<usize, usize>, k: usize| m.get(&k).copied().unwrap_or(0);
    let (b, r, m) = (get(&counts.bc, l), get(&counts.rl, l), get(&counts.main, l));
    // Every `r > b` and `r < b` below could be `r >= b` and `r <= b`: the
    // only caller, `check_row`, skips `b == r`, and no test asks such a
    // line. (`l == 0` could be `l <= 0` too, for a line number.)
    let line = |k: usize| {
        k.checked_sub(1)
            .and_then(|i| lines.get(i))
            .copied()
            .unwrap_or("")
    };
    let text = line(l);
    let facts = LineFacts::new(input, text, l, counts);
    let worse = r.abs_diff(b) > m.abs_diff(b);
    // Whether line `d` is a date alone whose one error rledger reports there
    // and beancount on the next line: one more on `d` than beancount, and one
    // fewer on `d + 1`.
    let moved_to_next_line = |d: usize| {
        date_alone(line(d))
            && get(&counts.rl, d) == get(&counts.bc, d) + 1
            && get(&counts.bc, d + 1) == get(&counts.rl, d + 1) + 1
    };
    // The errors rledger reports beyond beancount's, and how many of them
    // the named kind could be. Read only where `r > b`, so it never
    // saturates there, and `wrapping_sub` would be the same.
    let extra = r.saturating_sub(b);
    let accounts = get(&counts.rl_account, l);
    let boms = get(&counts.rl_bom, l);
    // Whether the glued-BOM causes are asked: a BOM-led account on the line.
    // `r != b` cannot change the result (the only caller, `check_row`, skips
    // `b == r`), nor can `boms > 0` (`GLUED`, the first part of each, needs
    // `0 < share <= f.boms`): it only spares a line with no `P0026` a parse.
    let glued_asked = r != b && facts.roles.account_in(&facts.span) && boms > 0;
    // The block's header: the last line before `l` that is not indented.
    // Starting the range at 4 would change nothing: where no line from 4 on
    // is the header, `unwrap_or(3)` gives line 3 anyway. `unwrap_or(2)`
    // would change nothing either: line 2 is the head's second `open`,
    // which is not a heading, has no error and holds no BOM, so it adds
    // nothing to `block_err` and starts no `*` heading.
    let header = (3..l).rev().find(|&k| !indented(line(k))).unwrap_or(3);
    // Trimming the end too (`trim_matches`) would change nothing: what a
    // line starts with stays, and a blank line is empty either way.
    let block_err = (header..l)
        .any(|k| get(&counts.bc, k) > 0 || line(k).trim_start_matches(is_blank).starts_with(BOM));
    // The recovery causes, by the shape of the lines before `l`. Asked
    // first, before any cause of the line's own, when the line alone counts
    // as beancount counts it alone: then the lines before it are the whole
    // difference (`foo` then `<BOM>assets:A <BOM>`). Otherwise asked after
    // the line's own causes, as before.
    let recovery = || {
        // `r <= b` is `r < b` here: the only caller skips `b == r`.
        if r <= b || l == 0 {
            None
        } else if indented(text) && strip_boms(line(header)).starts_with('*') {
            // An indented line after a `*` heading: beancount ignores the
            // heading and reads the line under the directive before it,
            // rledger reports it.
            Some("indented-line-after-heading")
        } else if indented(text) && block_err {
            // An indented line in a block whose header or an earlier line
            // beancount could not read (or which starts with a BOM): its
            // recovery skips the line in silence, rledger reports it (#2872).
            Some("indented-line-after-error")
        } else if get(&counts.bc, l - 1) > 0 {
            // A line right after one beancount could not read: its recovery
            // reports no grammar error there, rledger does (#2872).
            Some("line-after-error-line")
        } else {
            None
        }
    };
    Some(
        if let Some(c) = recovery().filter(|_| facts.alone_matches()) {
            // A recovery cause whose line counts alone as beancount counts it
            // alone: the lines before it are the whole difference. Asked first.
            // (`recovery` is `None` on line 0, so no `l > 0` is needed here.)
            c
        } else if worse && get(&counts.analog_bc, l) == b && get(&counts.analog_main, l) == r {
            // Further from beancount than main only because main miscounted the
            // BOM: the input with each BOM replaced by an ordinary character (a
            // run beancount reads into an account by `Ü`, any other by `$`) is
            // counted the same way on main. Checked from
            // the table, whatever else the line holds.
            "like-main-without-bom"
        } else if l == 0 {
            // A `pushtag` / `pushmeta` line with junk after it: beancount's
            // grammar never pushes, so it reports no unclosed push at the end of
            // the file (line 0); rledger keeps the push.
            "failed-push-still-pushed"
        } else if moved_to_next_line(l) || moved_to_next_line(l - 1) {
            // A date alone on a line: beancount reports its `unexpected EOL` on
            // the next line, rledger on the date's. So the date's line counts
            // exactly one more here, and the next line one fewer, both at once;
            // any other difference on either line is not this one. (`l - 1`
            // cannot underflow: line 0 is taken above.)
            "eol-reported-on-next-line"
        } else if r > b && account_after_bom(text) && accounts >= extra {
            // An invalid account (non-ASCII first character) after a BOM token
            // on the line gets rledger's `P0006` as well as the BOM diagnostic,
            // where beancount reports nothing more for the statement: each
            // error more than beancount's is matched by a `P0006`. Asked
            // before `bom-glued-to-account`, whose BOM may lead that account,
            // and before the recovery causes, which hold only for a line that
            // counts right on its own.
            "invalid-account-after-invalid-token"
        } else if let Some(c) = glued_asked
            .then(|| {
                [
                    // The order of the first two cannot change the result:
                    // both cannot hold, since `GLUED` alone takes the whole
                    // difference and `HASH_BANG`'s share is never zero
                    // (`parts_hold`'s zero check, which this order rests
                    // on: see its comment).
                    (GLUED, &[GLUED][..]),
                    (GLUED_HASH_BANG, &[GLUED, HASH_BANG][..]),
                    (GLUED_CONSTRUCT, &[GLUED, CONSTRUCT][..]),
                ]
                .into_iter()
                .find(|(_, parts)| parts_hold(parts, &facts))
                .map(|(c, _)| c)
            })
            .flatten()
        {
            // BOMs glued to an account (`$x <BOM>Assets:A`): beancount reads them
            // into the account and rejects the name on load; rledger reports the
            // stray BOM (`P0026`, with its quick fix: #2928's own design), one
            // error more than beancount's parse errors for each, verified by
            // `parts_hold`. With a mid-line `#!` / `#+` on the line, or a
            // construct error main also reports, both parts are named.
            c
        } else if r > b
            && facts.roles.account_in(&facts.span)
            && glued_boms_replace_construct(&facts)
        {
            // The same glued BOMs, on a line their rewrite turns into one
            // rledger reads with a construct error of its own (a posting's
            // `unexpected trailing tokens`), so the line's count does not
            // drop with the rewrite: its `P0026`s do, by exactly the
            // difference, and one non-BOM error comes in their place.
            "bom-glued-to-account-in-error-line"
        } else if let Some(c) = recovery() {
            c
        } else if mid_line_hash_bang(text) {
            // A `#!` or `#+` in the middle of a line: beancount lexes `#` and
            // `!` / `+`, here it is one token to the end of the line (part 2 of
            // #2928).
            HASH_BANG
        } else if lone_capital_glued(text) {
            // A lone capital glued to a token, or to the `\r` of a CRLF line:
            // beancount's `CAPITAL` needs a blank after it, so it starts an
            // invalid token there; here it lexes as a currency or a flag.
            "lone-capital-glued-to-tokens"
        } else if r > b && brace_hash_before_tag(text) {
            // A `{#` glued to a tag character outside a heading's unread rest:
            // beancount lexes a `{` and a tag, rledger's lexer its `{#` total-
            // cost token and an invalid run after it (`foo {#t`), with or
            // without a BOM on the line; the heading rest reads it as beancount
            // does since #2928.
            "brace-hash-before-tag"
        } else if r < b
            // The BOM check is needed: beancount's error for the line
            // before can land on a skipped line start (an `unexpected EOL`,
            // or a string left open on the line before), so `r < b` holds
            // on a BOM-free `;c` too (`2024-01-02 open` then `;c`). Pinned
            // by `test_cause_line_start_bom_before_comment_needs_a_bom`.
            && text.starts_with(BOM)
            && skipped_line_start(strip_boms(text))
            && !facts.roles.account_at(facts.span.start)
        {
            // A BOM that starts its line keeps its own extent (#2928's
            // deliberate line-start rule, for concatenated files), so a line
            // start beancount skips after it (`;`, `%`, `!`, `*`, `:`, `&`,
            // `?`, a `#` not before a tag character) hides the rest of the
            // line here, where beancount's invalid token runs through it and
            // lexes on. Not where beancount's lexer reads the line's start
            // as an `ACCOUNT` (`<BOM>:A$x!`, which admits the BOM): no
            // invalid token runs there, and the line is left to the account
            // causes below.
            "line-start-bom-before-comment"
        } else if r < b && boms > 0 && facts.inner_boms_are_the_difference() {
            // A run with a BOM inside it, on a line whose BOM diagnostic already
            // stands for the line's first error, is left to that diagnostic (a
            // `P0026` on the line): one error fewer than beancount. Verified:
            // the BOM is inside one of beancount's invalid tokens (not an
            // account, which admits a BOM), and with each such BOM made a `$`
            // rledger counts the line as beancount does. Reporting it
            // fixes these, and 256 more fuzz-corpus inputs, but also turns 98
            // matching ones into mismatches, each a difference the old count
            // happened to offset, so it is left for a change of its own.
            "inner-bom-under-line-error"
        } else if r < b && facts.account_grammar_error_is_the_difference() {
            // One `P0026` stands for both the BOM the line's diagnostic is
            // for and the grammar error beancount reports at a BOM-led
            // account (`<BOM>g 2024-01-02 * "n" <BOM>assets:A0<BOM>"s"`):
            // with each such account written `Assets:X`, the grammar error is
            // its own error again and rledger counts the line as beancount
            // does.
            "bom-account-under-line-diagnostic"
        } else if r < b
            // No BOM is stripped first: a BOM-led `<BOM>poptag` is one
            // invalid token to beancount, which reports no pop for it
            // (`2024-01-02 open` then `<BOM>poptag #t`, pinned by
            // `test_cause_pop_without_push_needs_fewer_errors`).
            && ["poptag", "popmeta"].iter().any(|p| text.starts_with(p))
        {
            // A pop of a tag or key not pushed (its push failed): beancount
            // reports it, rledger does not.
            "pop-without-push"
        } else if r < b
            // `r < b` cannot change the result: the check's `checked_sub`
            // needs `b >= r`, and the only caller skips `b == r`.
            && facts.later_grammar_is_the_difference()
        {
            // beancount reports grammar errors after the line's first error,
            // rledger one diagnostic for the line: its count is beancount's
            // less exactly those (the table's later-grammar column).
            "one-diagnostic-per-line"
        } else if eof_error_on_last_line(lines, l, counts) {
            // An error at the end of the file (an unclosed construct on the
            // last line): beancount reports it on the line after the last,
            // rledger on the last line, the same number of errors.
            "eof-error-on-last-line"
        } else if !text.contains(BOM) && r == m {
            // A line with no BOM, counted exactly as main counts it: a
            // difference from beancount that has nothing to do with #2928.
            "bom-free-line-as-on-main"
        } else if exceptions()
            .get(&(tail, l))
            .is_some_and(|reason| reason_counts(reason) == (r, b, m))
        {
            // Listed by hand, with its reason, in
            // data/bom_combination_matrix_exceptions.tsv. The reason names
            // the counts it was written for, so a later change in any of
            // them leaves the line unexplained rather than kept by a stale
            // reason.
            "listed-exception"
        } else if r > b && (r == m || parts_hold(&[CONSTRUCT], &facts)) {
            // rledger reports one more construct-level error (a custom value, a
            // price's link, a header's stray token, a pipe) on a line
            // beancount's grammar abandons at its first error; the same on main,
            // or, where a BOM changed main's count, on main for the BOM-free
            // analog (`price USD 1 <BOM>x {1 USD}#t`).
            CONSTRUCT
        } else if get(&counts.analog_bc, l) == b && get(&counts.analog_main, l) == r {
            // The mechanism of `like-main-without-bom`, on a line no further
            // from beancount than main: with each BOM replaced by an ordinary
            // character, beancount counts the line as it does here and main
            // counts it as rledger does here, so the difference is an older
            // recovery gap the BOM only carries (such as the grammar error of
            // an indented line whose first token is invalid). Asked last, so it
            // takes no line from a cause above. Checked from the table.
            "like-main-without-bom"
        } else {
            return None;
        },
    )
}

/// A known-list entry: rledger's counts and the causes.
type Entry = (String, String);

/// What one table row yields: its known-list entry when it differs from
/// beancount (`Err` names the lines no rule explains), its lines rledger
/// counts further from beancount than main, each with its cause and text,
/// and the texts of its invalid-token errors.
struct RowResult {
    tail: String,
    /// beancount's counts for the row.
    bc: String,
    entry: Option<Result<Entry, String>>,
    worse: Vec<Worse>,
    texts: String,
    /// The lines `listed-exception` explained.
    excepted: Vec<usize>,
}

/// A line rledger counts further from beancount than main: its number, cause
/// and text, and the counts the cause checks read.
struct Worse {
    line: usize,
    cause: &'static str,
    text: String,
    bc: usize,
    rl: usize,
    /// main's count for the line.
    main: usize,
    analog_bc: usize,
    analog_main: usize,
    /// The whole input, and beancount's count on this line for the input
    /// with each mid-line `#!` / `#+` made an ordinary invalid run
    /// (`hash_bang_analog`).
    input: String,
    hash_bang_bc: usize,
    /// beancount's count for the line alone, when it did not crash.
    bc_alone: Option<usize>,
    /// rledger's `P0026` errors on this line.
    boms: usize,
    roles: BomRoles,
    later_grammar: usize,
}

impl Worse {
    fn facts(&self) -> LineFacts<'_> {
        LineFacts {
            input: &self.input,
            text: &self.text,
            line: self.line,
            span: line_span(&self.input, self.line),
            roles: &self.roles,
            later_grammar: self.later_grammar,
            bc: self.bc,
            rl: self.rl,
            analog_bc: self.analog_bc,
            analog_main: self.analog_main,
            hash_bang_bc: self.hash_bang_bc,
            bc_alone: self.bc_alone,
            boms: self.boms,
        }
    }
}

/// The invalid tokens rledger names in `src`, as `line:token` joined by `|`,
/// so a change in what it reports shows up even where the counts stay.
fn invalid_token_texts(src: &str) -> String {
    let mut out = Vec::new();
    for e in &parse(src).errors {
        if let ParseErrorKind::SyntaxError(m) = &e.kind
            && let Some(token) = m.strip_prefix("unexpected input: invalid token ")
        {
            let line = src[..e.span.start.min(src.len())].matches('\n').count() + 1;
            out.push(format!("{line}:{token}"));
        }
    }
    out.join("|")
}

/// One table row's input after the head (as the table writes it), the input
/// itself, and its counts: the table's and rledger's own.
fn row_counts(line: &str) -> (String, String, Counts) {
    let fields: Vec<&str> = line.split('\t').collect();
    assert_eq!(fields.len(), 10, "malformed matrix line: {line:?}");
    let src = fields[0];
    let tail = src
        .strip_prefix(HEAD)
        .unwrap_or_else(|| panic!("matrix input without the head: {src:?}"))
        .to_string();
    let input = unescape(src);
    let kinds = rledger_lines(&input);
    let counts = Counts {
        bc: parse_cells(fields[1]),
        main: parse_cells(fields[2]),
        analog_bc: parse_cells(fields[3]),
        analog_main: parse_cells(fields[4]),
        hash_bang_bc: parse_cells(fields[5]),
        bc_alone: parse_cells(fields[6]),
        rl: kinds.all,
        rl_bom: kinds.bom,
        rl_account: kinds.account,
        roles: BomRoles::parse(fields[7], fields[8]),
        later_grammar: parse_cells(fields[9]),
    };
    (tail, input, counts)
}

fn check_row(line: &str) -> RowResult {
    let (tail, input, counts) = row_counts(line);
    let texts = if input.contains(BOM) {
        invalid_token_texts(&input)
    } else {
        String::new()
    };
    if counts.rl == counts.bc {
        return RowResult {
            tail,
            bc: cells(&counts.bc),
            entry: None,
            worse: Vec::new(),
            texts,
            excepted: Vec::new(),
        };
    }
    let lines: Vec<&str> = input.split('\n').collect();
    let get = |m: &BTreeMap<usize, usize>, k: usize| m.get(&k).copied().unwrap_or(0);
    let mut causes = BTreeSet::new();
    let mut unexplained = Vec::new();
    let mut excepted = Vec::new();
    let mut worse = Vec::new();
    let differing: BTreeSet<usize> = counts.bc.keys().chain(counts.rl.keys()).copied().collect();
    for l in differing {
        let (b, r, m) = (get(&counts.bc, l), get(&counts.rl, l), get(&counts.main, l));
        // A line counted alike needs no cause (`r == b` is the same test).
        if b == r {
            continue;
        }
        if let Some(c) = cause(&lines, l, &counts, &input, &tail) {
            causes.insert(c);
            if c == "listed-exception" {
                excepted.push(l);
            }
            if r.abs_diff(b) > m.abs_diff(b) {
                let text = l.checked_sub(1).and_then(|i| lines.get(i)).copied();
                worse.push(Worse {
                    line: l,
                    cause: c,
                    text: text.unwrap_or("").to_string(),
                    bc: b,
                    rl: r,
                    main: m,
                    analog_bc: get(&counts.analog_bc, l),
                    analog_main: get(&counts.analog_main, l),
                    input: input.clone(),
                    hash_bang_bc: get(&counts.hash_bang_bc, l),
                    bc_alone: counts.bc_alone.get(&l).copied(),
                    boms: get(&counts.rl_bom, l),
                    roles: counts.roles.clone(),
                    later_grammar: get(&counts.later_grammar, l),
                });
            }
        } else {
            // Read only for the failure message below.
            let f = LineFacts::new(
                &input,
                lines.get(l.wrapping_sub(1)).copied().unwrap_or(""),
                l,
                &counts,
            );
            // For the failure message only, too.
            let rewritten = rledger_counts(&ordinary_inner_boms(&input, &counts.roles, &f.span))
                .get(&l)
                .copied()
                .unwrap_or(0);
            let listed = exceptions()
                .get(&(tail.as_str(), l))
                .map(|reason| {
                    let (lr, lb, lm) = reason_counts(reason);
                    format!(
                        ", a listed exception written for rledger {lr} / beancount {lb} / \
                         main {lm}, not these counts"
                    )
                })
                .unwrap_or_default();
            unexplained.push(format!(
                "{l} ({:?}: later grammar {}, rledger with inner BOMs made `$` \
                 {rewritten}{listed})",
                f.text, f.later_grammar
            ));
        }
    }
    let entry = if unexplained.is_empty() {
        Ok((
            cells(&counts.rl),
            causes.into_iter().collect::<Vec<_>>().join("+"),
        ))
    } else {
        Err(format!(
            "lines {unexplained:?}: beancount {} main {} rledger {}",
            cells(&counts.bc),
            cells(&counts.main),
            cells(&counts.rl)
        ))
    };
    RowResult {
        tail,
        bc: cells(&counts.bc),
        entry: Some(entry),
        worse,
        texts,
        excepted,
    }
}

/// A line further from beancount than main, accepted by hand: its cause, the
/// standalone beancount count for a recovery cause (`-` otherwise), and why.
struct Accepted<'a> {
    cause: &'a str,
    standalone: Option<usize>,
    why: &'a str,
}

/// The hand-maintained list of lines rledger counts further from beancount
/// than main (`data/bom_combination_matrix_worse_than_main.tsv`), by input
/// and line. `BOM_MATRIX_UPDATE` never writes it.
fn accepted() -> BTreeMap<(&'static str, usize), Accepted<'static>> {
    parse_accepted(WORSE_THAN_MAIN)
}

/// The accepted lines written in `text`, as the worse-than-main file holds
/// them. Panics on a malformed, unjustified or duplicate line.
fn parse_accepted(text: &str) -> BTreeMap<(&str, usize), Accepted<'_>> {
    let mut out = BTreeMap::new();
    for l in data_lines(text) {
        let fields: Vec<&str> = l.split('\t').collect();
        assert_eq!(fields.len(), 5, "malformed accepted line: {l:?}");
        let standalone = (fields[3] != "-").then(|| fields[3].parse().expect("a count"));
        // A reason of blanks alone is empty under either trim, so
        // `trim_start` would be the same.
        assert!(!fields[4].trim().is_empty(), "no justification: {l:?}");
        assert!(
            !fields[4].contains("TODO"),
            "justification still to write: {l:?}"
        );
        let key = (fields[0], fields[1].parse().expect("a line number"));
        let entry = Accepted {
            cause: fields[2],
            standalone,
            why: fields[4],
        };
        assert!(
            out.insert(key, entry).is_none(),
            "duplicate accepted line: {l:?}"
        );
    }
    out
}

/// The causes a further-than-main line may be accepted for, by how the test
/// checks each:
///
/// - recovery (`RECOVERY_CAUSES`): wrong only after the lines before it, so
///   alone, after the head (under a bare transaction header when indented),
///   rledger counts the line as beancount does alone (the table's count, and
///   the entry's, which must agree);
/// - `like-main-without-bom`: the analog columns, beancount's and main's
///   counts for the input with its BOMs replaced by ordinary characters,
///   are beancount's and rledger's counts here;
/// - `bom-glued-to-account`, `mid-line-hash-bang`, and a composite of them
///   or of `bom-glued-to-account` and `extra-construct-error` (parts joined
///   by `&`): each part verified, and together the line's whole difference
///   (`parts_hold`);
/// - `inner-bom-under-line-error`: the line has BOMs inside beancount's own
///   invalid tokens, and with each made a `$` rledger counts the line as
///   beancount does (`inner_boms_are_the_difference`);
/// - `bom-account-under-line-diagnostic`: a BOM-led account starts on the
///   line, and with each written `Assets:X` rledger counts the line as
///   beancount does (`account_grammar_error_is_the_difference`);
/// - `one-diagnostic-per-line`: rledger counts beancount's count less
///   exactly beancount's grammar errors after the line's first error (the
///   table's column), one diagnostic standing for the line
///   (`later_grammar_is_the_difference`);
/// - `invalid-account-after-invalid-token`: alone, rledger is off from
///   beancount the same way and at least as far as in context, or rledger
///   counts the line the same alone and beancount reports less in context
///   (its recovery after the line before). That every error more is a
///   `P0006` is the rule's own condition in `cause`, which the cause
///   equality already requires, so it is not checked a second time here.
const RECOVERY_CAUSES: &[&str] = &[
    "indented-line-after-error",
    "indented-line-after-heading",
    "line-after-error-line",
];

/// rledger's count for `text` alone.
fn standalone_count(text: &str) -> usize {
    let header = if indented(text) { "2024-01-02 *\n" } else { "" };
    let src = format!("{}{header}{text}\n", unescape(HEAD));
    let line = if header.is_empty() { 3 } else { 4 };
    rledger_counts(&src).get(&line).copied().unwrap_or(0)
}

#[allow(clippy::cast_possible_wrap)]
const fn signed(n: usize) -> i64 {
    n as i64
}

/// Whether an accepted further-than-main line holds: for its cause, or
/// because main was closer to beancount only by not reading the rest of a
/// line (`main_read_less`).
fn holds(a: &Accepted<'_>, w: &Worse) -> bool {
    cause_holds(a, w) || main_read_less(w)
}

/// Whether main's count for the line is exactly what rledger counts with
/// each mid-line `#!` / `#+` and the rest of its line cut off
/// (`hash_bang_cut`), as main read them before #2928: a comment to the end
/// of the line. Such a line is further from beancount than main only because
/// rledger now reads what main skipped, and the line holds or follows such a
/// `#!` / `#+`, so the cut moves the count.
fn main_read_less(w: &Worse) -> bool {
    let cut = hash_bang_cut(&w.input);
    cut != w.input && rledger_counts(&cut).get(&w.line).copied().unwrap_or(0) == w.main
}

/// Whether an accepted further-than-main line holds for its cause.
fn cause_holds(a: &Accepted<'_>, w: &Worse) -> bool {
    match a.cause {
        "like-main-without-bom" => w.analog_bc == w.bc && w.analog_main == w.rl,
        "inner-bom-under-line-error" => w.facts().inner_boms_are_the_difference(),
        "bom-account-under-line-diagnostic" => w.facts().account_grammar_error_is_the_difference(),
        "one-diagnostic-per-line" => w.facts().later_grammar_is_the_difference(),
        "invalid-account-after-invalid-token" => {
            alone_counts(a, w).is_some_and(|(alone, bc_alone)| {
                let (off_alone, off_here) = (
                    signed(alone) - signed(bc_alone),
                    signed(w.rl) - signed(w.bc),
                );
                // Off the same way alone, and at least as far; or counted
                // the same alone by rledger, with beancount reporting less
                // here only because of its recovery after the line before.
                // `w.bc <= bc_alone` would change nothing: with `alone ==
                // w.rl` and `w.bc == bc_alone` the line is off as far alone
                // as here, which the first test takes.
                (off_alone.signum() == off_here.signum() && off_alone.abs() >= off_here.abs())
                    || (alone == w.rl && w.bc < bc_alone)
            })
        }
        cause if RECOVERY_CAUSES.contains(&cause) => {
            alone_counts(a, w).is_some_and(|(alone, bc_alone)| alone == bc_alone)
        }
        cause
            if cause
                .split('&')
                .all(|p| [GLUED, HASH_BANG, CONSTRUCT].contains(&p)) =>
        {
            parts_hold(&cause.split('&').collect::<Vec<_>>(), &w.facts())
        }
        _ => false,
    }
}

/// For a cause checked by the line alone: rledger's count for the line
/// alone and the accepted standalone beancount count, or `None` when the
/// accepted line gives none or the table's standalone count is another.
fn alone_counts(a: &Accepted<'_>, w: &Worse) -> Option<(usize, usize)> {
    let bc_alone = a.standalone?;
    if w.bc_alone.is_some_and(|table| table != bc_alone) {
        return None;
    }
    Some((standalone_count(&w.text), bc_alone))
}

/// Check every line further from beancount than main against the accepted
/// list: it must be there, with the cause the rules give, and that cause
/// must hold (`holds`). A listed line no longer worse is stale.
fn check_worse_than_main(worse: &[(String, Worse)]) -> Vec<String> {
    let accepted = accepted();
    let mut failures = Vec::new();
    let mut seen = BTreeSet::new();
    for (tail, w) in worse {
        let l = w.line;
        seen.insert((tail.as_str(), l));
        match accepted.get(&(tail.as_str(), l)) {
            None => failures.push(format!(
                "not accepted, further from beancount than main:\n{tail}\t{l}\t{}\t-\tTODO {} {}",
                w.cause, w.bc, w.rl
            )),
            Some(a) if a.cause != w.cause => failures.push(format!(
                "accepted as {} but the rules give {}: {tail} line {l}",
                a.cause, w.cause
            )),
            Some(a) if !holds(a, w) => failures.push(format!(
                "accepted as {} ({}), which does not hold: beancount {}, rledger {} \
                 here: {tail} line {l}",
                a.cause, a.why, w.bc, w.rl
            )),
            Some(_) => {}
        }
    }
    for (tail, l) in accepted.keys() {
        if !seen.contains(&(*tail, *l)) {
            failures.push(format!(
                "accepted but no longer worse than main, remove it: {tail} line {l}"
            ));
        }
    }
    failures
}

#[test]
fn test_parse_bom_combination_matrix_matches_beancount() {
    // Read only by the guard against a table cut short below, which holds
    // by a wide margin: starting at 1 or counting by 2 changes nothing.
    let mut rows = 0;
    let mut computed: Vec<(String, String, String)> = Vec::new();
    let mut worse: Vec<(String, Worse)> = Vec::new();
    let mut failures = Vec::new();
    let mut texts: Vec<(String, String)> = Vec::new();
    let mut bc_cells: BTreeMap<String, String> = BTreeMap::new();
    let mut excepted: BTreeSet<(String, usize)> = BTreeSet::new();
    for line in DATA.lines() {
        rows += 1;
        let result = check_row(line);
        excepted.extend(result.excepted.iter().map(|&l| (result.tail.clone(), l)));
        bc_cells.insert(result.tail.clone(), result.bc.clone());
        if !result.texts.is_empty() {
            texts.push((result.tail.clone(), result.texts.clone()));
        }
        worse.extend(result.worse.into_iter().map(|w| (result.tail.clone(), w)));
        match result.entry {
            None => {}
            Some(Ok((counts, causes))) => computed.push((result.tail, counts, causes)),
            Some(Err(why)) => failures.push(format!("no cause for {}: {why}", result.tail)),
        }
    }
    // A guard against a table cut short, which holds by a wide margin (it
    // has over 13,000 rows): moving the bound or the count by one, or
    // `>=`, changes nothing it can see.
    assert!(rows > 1000, "the matrix has only {rows} rows");
    assert!(
        failures.is_empty(),
        "{} input(s) differ from beancount on a line no rule explains:\n{}",
        failures.len(),
        failures.join("\n")
    );
    let stale = stale_exceptions(exceptions().into_keys(), &excepted);
    assert!(
        stale.is_empty(),
        "{} listed exception(s) no longer needed, remove them from \
         data/bom_combination_matrix_exceptions.tsv:\n{}",
        stale.len(),
        stale.join("\n")
    );
    // Before any update: no update may accept a line further from beancount
    // than main.
    let worse_failures = check_worse_than_main(&worse);
    assert!(
        worse_failures.is_empty(),
        "{} line(s) further from beancount than main fail the accepted list \
         (data/bom_combination_matrix_worse_than_main.tsv, kept by hand):\n{}",
        worse_failures.len(),
        worse_failures.join("\n")
    );

    if std::env::var_os("BOM_MATRIX_UPDATE").is_some() {
        // An update is for counts that moved. A row whose counts stay but
        // whose causes or reported token texts change is a change to the
        // rules or to the text, not to the counts: it needs
        // `BOM_MATRIX_RELABEL=1` as well, so a weakened rule or a changed
        // token text is not taken in by a plain update.
        let relabels = relabeled_rows(&computed, &texts);
        assert!(
            relabels.is_empty() || std::env::var_os("BOM_MATRIX_RELABEL").is_some(),
            "{} row(s) keep their counts but change their causes or token texts; \
             set BOM_MATRIX_RELABEL=1 too if that is meant:\n{}",
            relabels.len(),
            relabels.join("\n")
        );
        // Nor is it for a count that moves further from beancount than the
        // list recorded (or than beancount's own, for a row that matched),
        // even when main is no closer: that is a regression, which needs
        // `BOM_MATRIX_RELABEL=1` and a reason written by hand for exactly the
        // new counts (`reason_holds`).
        let known = known_rows();
        let matching = matching_hashes();
        let regressions = regressed_rows(&computed, &bc_cells, &known, &matching);
        let relabel = std::env::var_os("BOM_MATRIX_RELABEL").is_some();
        let counts_of: BTreeMap<&str, &str> = computed
            .iter()
            .map(|(t, c, _)| (t.as_str(), c.as_str()))
            .collect();
        let refused: Vec<&String> = regressions
            .iter()
            .filter(|(tail, _)| {
                !relabel || !reason_holds(&known, tail, counts_of.get(tail.as_str()).copied())
            })
            .map(|(_, why)| why)
            .collect();
        assert!(
            refused.is_empty(),
            "{} row(s) count a line further from beancount than recorded (the known \
             list's counts, or beancount's for a row that matched). To accept one, \
             give it a known-list line `<source>\\t<counts>\\t<causes>\\t<the same \
             counts>\\t<reason>` (adding the line for a row that matched) and rerun \
             with BOM_MATRIX_UPDATE=1 BOM_MATRIX_RELABEL=1; the reason holds only \
             for those counts:\n{}",
            refused.len(),
            refused
                .iter()
                .map(|s| s.as_str())
                .collect::<Vec<_>>()
                .join("\n")
        );
        let mut out = KNOWN_HEADER.to_string();
        for (tail, counts, causes) in &computed {
            // A reason is kept only while the counts are those it was
            // written for.
            match known
                .get(tail.as_str())
                .and_then(|row| row.2)
                .filter(|(for_counts, _)| for_counts == counts)
            {
                Some((for_counts, reason)) => {
                    writeln!(out, "{tail}\t{counts}\t{causes}\t{for_counts}\t{reason}")
                }
                None => writeln!(out, "{tail}\t{counts}\t{causes}"),
            }
            .expect("write to a String");
        }
        std::fs::write(KNOWN_PATH, out).expect("write the known list");
        let mut out = TEXTS_HEADER.to_string();
        for (tail, t) in &texts {
            writeln!(out, "{tail}\t{t}").expect("write to a String");
        }
        std::fs::write(TEXTS_PATH, out).expect("write the texts list");
        let differing: BTreeSet<&str> = computed.iter().map(|(t, _, _)| t.as_str()).collect();
        let mut out = MATCHING_HEADER.to_string();
        let mut hashes: Vec<String> = bc_cells
            .keys()
            .filter(|t| !differing.contains(t.as_str()))
            .map(|t| fnv(t))
            .collect();
        hashes.sort();
        for h in &hashes {
            writeln!(out, "{h}").expect("write to a String");
        }
        let refs: Vec<&str> = hashes.iter().map(String::as_str).collect();
        writeln!(out, "{}", matching_seal(&refs)).expect("write to a String");
        std::fs::write(MATCHING_PATH, out).expect("write the matching list");
        return;
    }

    let known: BTreeSet<String> = known_rows()
        .into_iter()
        .map(|(t, (c, k, _))| format!("{t}\t{c}\t{k}"))
        .collect();
    let want: BTreeSet<String> = computed
        .iter()
        .map(|(t, c, k)| format!("{t}\t{c}\t{k}"))
        .collect();
    let diff = list_diff(&known, &want);
    assert!(
        diff.is_empty(),
        "the known list is out of date (rerun with BOM_MATRIX_UPDATE=1 and read the \
         diff):\n{}",
        diff.join("\n")
    );

    // The matching list must be exactly the rows that match now: a stale or
    // cut list would let an update take a regression from matching for a
    // new row.
    let differing: BTreeSet<&str> = computed.iter().map(|(t, _, _)| t.as_str()).collect();
    let matching_now: BTreeSet<String> = bc_cells
        .keys()
        .filter(|t| !differing.contains(t.as_str()))
        .map(|t| fnv(t))
        .collect();
    let matching: BTreeSet<String> = matching_hashes().into_iter().map(String::from).collect();
    let diff = list_diff(&matching, &matching_now);
    assert!(
        diff.is_empty(),
        "the matching list is out of date (rerun with BOM_MATRIX_UPDATE=1 and read the \
         diff; `+` a hash missing, `-` one extra):\n{}",
        diff.join("\n")
    );

    // Each texts line is a source, a tab, then the token texts, which are
    // escaped (a tab in one is `\t`), so taken whole.
    let recorded: BTreeSet<String> = data_lines(TEXTS).map(String::from).collect();
    let current: BTreeSet<String> = texts.iter().map(|(t, x)| format!("{t}\t{x}")).collect();
    let diff = list_diff(&recorded, &current);
    assert!(
        diff.is_empty(),
        "the invalid-token texts changed (rerun with BOM_MATRIX_UPDATE=1 and read the \
         diff):\n{}",
        diff.join("\n")
    );
}

/// How the list `now` differs from the list `was`: a `- ` line for each
/// entry gone, then a `+ ` line for each one new. Empty when they agree.
fn list_diff(was: &BTreeSet<String>, now: &BTreeSet<String>) -> Vec<String> {
    was.difference(now)
        .map(|x| format!("- {x}"))
        .chain(now.difference(was).map(|x| format!("+ {x}")))
        .collect()
}

/// The listed exceptions (`listed`, by input and line) that no line needs
/// any more, so are stale: each one `listed-exception` did not explain
/// (`excepted`, from `check_row`), because a rule explains its line, or the
/// line matches.
fn stale_exceptions<'a>(
    listed: impl IntoIterator<Item = (&'a str, usize)>,
    excepted: &BTreeSet<(String, usize)>,
) -> Vec<String> {
    listed
        .into_iter()
        .filter(|(t, l)| !excepted.contains(&((*t).to_string(), *l)))
        .map(|(t, l)| format!("{t} line {l}"))
        .collect()
}

/// The rows whose counts are those the lists record but whose causes (known
/// list) or reported token texts (texts list) differ from them.
fn relabeled_rows(
    computed: &[(String, String, String)],
    texts: &[(String, String)],
) -> Vec<String> {
    let known = known_rows();
    // A texts line has one tab (its token texts are escaped), so
    // `rsplit_once` would be the same.
    let recorded: BTreeMap<&str, &str> = data_lines(TEXTS)
        .filter_map(|l| l.split_once('\t'))
        .collect();
    let mut out = Vec::new();
    for (tail, counts, causes) in computed {
        if let Some((was_counts, was_causes, _)) = known.get(tail.as_str())
            && was_counts == counts
            && was_causes != causes
        {
            out.push(format!("causes {was_causes} -> {causes}: {tail}"));
        }
    }
    for (tail, text) in texts {
        if let Some(was) = recorded.get(tail.as_str())
            && was != text
        {
            out.push(format!("token texts {was} -> {text}: {tail}"));
        }
    }
    out
}

/// A known row: rledger's counts, the causes, and the optional hand-written
/// regression reason with the counts it was written for.
type KnownRow = (
    &'static str,
    &'static str,
    Option<(&'static str, &'static str)>,
);

/// The known list's rows, by source.
fn known_rows() -> BTreeMap<&'static str, KnownRow> {
    parse_known_rows(KNOWN)
}

/// The known rows written in `text`, as the known list holds them: three
/// fields, or five with a reason and the counts it was written for. Panics
/// on any other line, and on a reason of blanks alone.
fn parse_known_rows(text: &str) -> BTreeMap<&str, (&str, &str, Option<(&str, &str)>)> {
    data_lines(text)
        .map(|l| {
            let f: Vec<&str> = l.split('\t').collect();
            let reason = match f.len() {
                3 => None,
                5 => {
                    // A reason of blanks alone is empty under either trim,
                    // so `trim_start` would be the same.
                    assert!(!f[4].trim().is_empty(), "a blank reason: {l:?}");
                    Some((f[3], f[4]))
                }
                _ => panic!("malformed known line: {l:?}"),
            };
            (f[0], (f[1], f[2], reason))
        })
        .collect()
}

/// Whether `tail`'s known row carries a regression reason written for
/// exactly `counts`, rledger's counts now: a reason for other counts does
/// not accept a later change.
fn reason_holds(known: &BTreeMap<&str, KnownRow>, tail: &str, counts: Option<&str>) -> bool {
    known
        .get(tail)
        .and_then(|row| row.2)
        .is_some_and(|(for_counts, _)| Some(for_counts) == counts)
}

/// The matching list's hashes. Its last line, `# total <n> <digest>`, seals
/// it: a list cut short or edited by hand no longer agrees with it, and
/// fails here in either mode, so a stale list cannot quietly let an update
/// take a regression from matching for a new row.
fn matching_hashes() -> BTreeSet<&'static str> {
    // `split('\n')` for `lines()` would be the same here and below: the list
    // holds no `\r` (`test_data_files_hold_no_carriage_return`).
    let hashes: Vec<&str> = MATCHING
        .lines()
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect();
    let seal = MATCHING
        .lines()
        .rev()
        // The list has one `# total` line, so `rfind` (finding it from the
        // other end) would be the same.
        .find(|l| l.starts_with("# total "))
        .expect("the matching list has no `# total` line");
    assert_eq!(
        seal,
        matching_seal(&hashes),
        "the matching list does not agree with its own `# total` line: cut short or \
         edited by hand? Restore it from git, or rerun with BOM_MATRIX_UPDATE=1."
    );
    hashes.into_iter().collect()
}

/// The `# total <n> <digest>` line for `hashes`, in the list's order.
fn matching_seal(hashes: &[&str]) -> String {
    format!("# total {} {}", hashes.len(), fnv(&hashes.join("\n")))
}

/// The rows with a line rledger now counts further from beancount than the
/// known list recorded, or than beancount's own count for a row that matched
/// at the last update (the matching list): each with a line saying which.
fn regressed_rows(
    computed: &[(String, String, String)],
    bc_cells: &BTreeMap<String, String>,
    known: &BTreeMap<&str, KnownRow>,
    matching: &BTreeSet<&str>,
) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for (tail, counts, _) in computed {
        let bc = parse_cells(bc_cells.get(tail).map_or("", String::as_str));
        let now = parse_cells(counts);
        // A row that matched at the last update regresses from beancount's
        // own counts, whatever known row was added for it by hand since.
        let before = if matching.contains(fnv(tail).as_str()) {
            bc.clone()
        } else if let Some(row) = known.get(tail.as_str()) {
            parse_cells(row.0)
        } else {
            // New to the table: nothing recorded to regress from.
            continue;
        };
        let get = |m: &BTreeMap<usize, usize>, k: usize| m.get(&k).copied().unwrap_or(0);
        let lines: BTreeSet<usize> = bc
            .keys()
            .chain(now.keys())
            .chain(before.keys())
            .copied()
            .collect();
        for l in lines {
            let b = get(&bc, l);
            if get(&now, l).abs_diff(b) > get(&before, l).abs_diff(b) {
                out.push((
                    tail.clone(),
                    format!(
                        "{tail} line {l}: beancount {b}, recorded {}, now {}",
                        get(&before, l),
                        get(&now, l)
                    ),
                ));
            }
        }
    }
    out
}

/// The two `open` lines of a made-up input, so its own line is line 3.
const MADE_UP_HEAD: &str = "2024-01-01 open Assets:A\n2024-01-01 open Assets:B\n";

/// Counts for line `l` only: beancount `b`, rledger `r`, main `m`, and
/// rledger's `P0026`s `boms`. Nothing else is set: no analog or standalone
/// count, no later grammar errors, no BOM roles.
fn line_counts(l: usize, b: usize, r: usize, m: usize, boms: usize) -> Counts {
    let on_line = |n: usize| BTreeMap::from([(l, n)]);
    Counts {
        bc: on_line(b),
        rl: on_line(r),
        main: on_line(m),
        analog_bc: BTreeMap::new(),
        analog_main: BTreeMap::new(),
        hash_bang_bc: BTreeMap::new(),
        bc_alone: BTreeMap::new(),
        rl_bom: on_line(boms),
        rl_account: BTreeMap::new(),
        roles: BomRoles::default(),
        later_grammar: BTreeMap::new(),
    }
}

/// Counts for line 3 only, as `line_counts` sets them.
fn line3_counts(b: usize, r: usize, m: usize, boms: usize) -> Counts {
    line_counts(3, b, r, m, boms)
}

/// `cause` of line `l` of the made-up input whose lines from line 3 on are
/// `rest`.
fn made_up_cause(rest: &str, l: usize, counts: &Counts) -> Option<&'static str> {
    let input = format!("{MADE_UP_HEAD}{rest}\n");
    let lines: Vec<&str> = input.split('\n').collect();
    cause(&lines, l, counts, &input, "made-up row, in no data file")
}

/// `cause` of line 3 of the made-up input whose line 3 is `text`.
fn line3_cause(text: &str, counts: &Counts) -> Option<&'static str> {
    made_up_cause(text, 3, counts)
}

/// One table row's input and counts, found by its input after the head.
fn table_row(tail: &str) -> (String, Counts) {
    let row = DATA
        .lines()
        .find(|row| row.split('\t').next().and_then(|s| s.strip_prefix(HEAD)) == Some(tail))
        .unwrap_or_else(|| panic!("no table row for {tail:?}"));
    let (_, input, counts) = row_counts(row);
    (input, counts)
}

/// The row `scripts/bom-combination-matrix.py` would write for an input the
/// table does not hold, its columns recorded by hand from bean-check 3.2.3
/// and main's `parse_error_lines`, so its counts are real: `tail` is the
/// input after the head, escaped as the table writes it, and `columns` the
/// nine columns after it (beancount, main, the BOM-free analog's beancount
/// and main, the hash-bang analog's beancount, beancount alone, the account
/// and inner BOM roles, the later grammar errors), blank-separated, `-` for
/// an empty one. rledger's counts are its own, as for a table row.
fn recorded_row(tail: &str, columns: &str) -> (String, Counts) {
    let columns: Vec<&str> = columns
        .split(' ')
        .map(|c| if c == "-" { "" } else { c })
        .collect();
    assert_eq!(
        columns.len(),
        9,
        "nine columns after the input: {columns:?}"
    );
    let (_, input, counts) = row_counts(&format!("{HEAD}{tail}\t{}", columns.join("\t")));
    (input, counts)
}

/// `cause` of line `l` of the recorded row `tail` / `columns`
/// (`recorded_row`).
fn recorded_cause(tail: &str, columns: &str, l: usize) -> Option<&'static str> {
    let (input, counts) = recorded_row(tail, columns);
    let lines: Vec<&str> = input.split('\n').collect();
    cause(&lines, l, &counts, &input, "recorded row, in no data file")
}

