//! Every combination of up to three BOM tokens, in each line context, is
//! counted as beancount counts it, or differs for a named reason (#2928).
//!
//! A mid-file BOM is reported by rledger's own diagnostic
//! (`BomInDirectiveBody`), which also has to stand in for some of
//! beancount's `Invalid token` errors so that the counts agree: a line's BOM
//! diagnostic, a second one after another line error, a BOM that starts its
//! line, a BOM-led run, a run with a BOM inside it, BOMs beancount reads into
//! an account. Each review round of the PR that made a mid-line BOM run to
//! the next blank found another combination whose count drifted, so this
//! checks all of them at once.
//!
//! `data/bom_combination_matrix.tsv` records, for each generated input (the
//! combination matrix, the shapes the reviews found, and a seeded random
//! probe), beancount 3.2.3's per-line parse-error counts, main's, and both of
//! those for the input with its BOMs replaced by ordinary characters. It is
//! generated by `scripts/bom-combination-matrix.py`, so this test needs no
//! Python and no main build.
//!
//! Each input is parsed here on both paths (green and red, which must agree).
//! Where its counts differ from beancount's, each differing line is given a
//! cause by [`cause`], one rule per cause, and the input must be listed in
//! `data/bom_combination_matrix_known.tsv` with exactly those causes and its
//! current counts. A line no rule explains fails the test, and so does a
//! listed input that now matches or counts differently. Regenerate the list
//! after a deliberate change with `BOM_MATRIX_UPDATE=1`, and read the diff.
//!
//! No cause makes a line further from beancount than main acceptable on its
//! own: each such line must be listed, by hand, in
//! `data/bom_combination_matrix_worse_than_main.tsv` with its cause and the
//! reason (and, for a recovery cause, the count beancount gives the line
//! alone, which rledger must match). The update never writes that file, and
//! refuses to run while a further-than-main line is not in it.
//!
//! The invalid tokens rledger names for each input with a BOM are recorded too,
//! in `data/bom_combination_matrix_texts.tsv`, so a change in the reported
//! token text fails even where the counts stay. An update that keeps a row's
//! counts but changes its causes or its token texts also needs
//! `BOM_MATRIX_RELABEL=1`: a plain update takes in moved counts only. Nor
//! does an update take in a line counted further from beancount than the
//! known list recorded (than beancount's count, for a row that matched), even
//! one main is no closer on: that needs `BOM_MATRIX_RELABEL=1` and a reason in
//! the known row, written for exactly the new counts. The matching list
//! (`data/bom_combination_matrix_matching.tsv`) must be exactly the rows that
//! match now, and the hand-kept exceptions
//! (`data/bom_combination_matrix_exceptions.tsv`) exactly the lines no rule
//! explains.

