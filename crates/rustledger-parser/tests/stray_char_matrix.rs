/// Up to three insertions of characters, words and numbers into a header.
fn mutated_header() -> impl Strategy<Value = String> {
    let piece = prop_oneof![
        proptest::sample::select(CHARS.chars().map(String::from).collect::<Vec<_>>()),
        proptest::sample::select(
            [
                " ",
                "A",
                "USD",
                "1",
                "-",
                "+",
                "/",
                "\"s\"",
                "#x",
                "^y",
                "kk:",
                "Assets:Z",
                "2024-02-02",
                "TRUE",
                "NULL",
                ";"
            ]
            .iter()
            .map(|s| (*s).to_string())
            .collect::<Vec<_>>()
        ),
    ];
    (
        proptest::sample::select(HEADER_BASES),
        proptest::collection::vec((any::<proptest::sample::Index>(), piece), 1..=3),
    )
        .prop_map(|(base, edits)| {
            let mut s = base.to_string();
            for (at, text) in edits {
                // Insert anywhere but after the final newline, on a char
                // boundary (the snippets and pieces are ASCII).
                let i = at.index(s.len());
                s.insert_str(i, &text);
            }
            s
        })
}

proptest! {
    // A fixed seed and no failure file: the same inputs run everywhere.
    #![proptest_config(ProptestConfig {
        cases: 2048,
        rng_seed: proptest::test_runner::RngSeed::Fixed(2802),
        failure_persistence: None,
        ..ProptestConfig::default()
    })]

    /// For a header line with zero parse errors, `rledger format` keeps every
    /// non-whitespace character in order. Its only normalizations on these
    /// lines are whitespace: spacing between tokens and around arithmetic
    /// operators, and the space it puts between a number and its currency.
    #[test]
    fn test_try_format_source_keeps_the_text_of_a_clean_header(src in mutated_header()) {
        if parse(&src).errors.is_empty() {
            let out = try_format_source(&src).expect("a clean file formats");
            prop_assert_eq!(non_whitespace(&out), non_whitespace(&src), "{:?} -> {:?}", src, out);
        }
    }
}

/// A plain currency must END with a letter or digit, as in beancount
/// (`[A-Z][A-Z0-9'._-]*[A-Z0-9]`, or one capital letter). Ours let it end in
/// `_`, `-`, `'` or `.`, so `commodity CAC_` loaded clean and bean-check
/// refused it. The trailing character is now left over, and an error.
#[test]
fn test_parse_rejects_a_currency_ending_in_punctuation() {
    for src in [
        "2024-01-01 commodity CAC_\n",
        "2024-01-01 price HOOL_ 10 USD\n",
        "2024-01-01 price HOOL' 10 USD\n",
        "2024-01-01 price HOOL. 10 USD\n",
        "2024-01-01 price HOOL 10 CAC-\n",
        "2024-01-01 open Assets:A USD_,EUR\n",
        "2024-01-01 open Assets:A USD-,EUR\n",
        "2024-01-01 open Assets:A USD',EUR\n",
        "2024-01-01 open Assets:A USD.,EUR\n",
        "2024-01-01 open Assets:A USD,EUR_\n",
        "2024-01-01 custom \"budget\" Assets:A \"x\" 10 USD_ TRUE\n",
        "2024-01-01 *\n  Assets:A  1 CAC_\n  Assets:B\n",
    ] {
        assert!(!parse(src).errors.is_empty(), "{src:?} must be rejected");
    }
    // Inner punctuation is still part of the currency, and quotes in strings
    // are not currencies at all.
    for (src, want) in [
        ("2024-01-01 commodity NT.TO\n", "NT.TO"),
        ("2024-01-01 commodity BRK-B\n", "BRK-B"),
        ("2024-01-01 commodity TLT_040921C144\n", "TLT_040921C144"),
        ("2024-01-01 commodity USD.5\n", "USD.5"),
    ] {
        let r = parse(src);
        assert!(r.errors.is_empty(), "{src:?}: {:?}", r.errors);
        let rustledger_core::Directive::Commodity(c) = &r.directives[0].value else {
            panic!("{src:?}");
        };
        assert_eq!(c.currency.as_str(), want);
    }
    assert!(
        parse("2024-01-01 note Assets:A \"HOOL' and CAC_\"\n")
            .errors
            .is_empty()
    );
}

/// A token left over after a posting's amount, cost or price is an error, as
/// in beancount (`unexpected MINUS`). Ending a currency at its last letter or
/// digit made `1 USD-` lex as `USD` then `-`, and the posting converter, which
/// reads only its amount, cost and price, loaded `1 USD` and `rledger format`
/// wrote it back that way.
#[test]
fn test_parse_rejects_a_token_left_over_after_a_posting_amount() {
    for (posting, glued) in [
        ("1 USD-", true),
        ("1 HOOL @ 2 USD-", true),
        ("1 HOOL @@ 2 USD-", true),
        ("1 HOOL {2 USD} @ 3 USD-", true),
        ("-1 USD-", true),
        ("1 USD--", true),
        ("1 USD- ; c", true),
        ("1 USD+", false),
        ("1 USD -", false),
        ("1 USD *", false),
    ] {
        let src = format!("2024-01-01 *\n  Assets:A  {posting}\n  Equity:E\n");
        let r = parse(&src);
        assert_eq!(r.errors.len(), 1, "{src:?}: {:?}", r.errors);
        let msg = r.errors[0].to_string();
        assert!(msg.contains("after the posting amount"), "{msg}");
        assert_eq!(msg.contains("a currency cannot end in"), glued, "{msg}");
        // Reported, not deleted: the error-tolerant formatter keeps the line.
        assert_eq!(rustledger_parser::format::format_source(&src), src);
    }
    for src in [
        "2024-01-01 *\n  Assets:A  1 HOOL {2 USD}\n  Equity:E\n",
        "2024-01-01 *\n  Assets:A  1 USD ; c\n  Equity:E\n",
    ] {
        assert!(parse(src).errors.is_empty(), "{src:?}");
    }
}

