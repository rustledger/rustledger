//! A stray character on any line of a directive is an error when beancount
//! says it is, and only then (#2802).
//!
//! The parser grouped a header line into tokens and each converter read the
//! fields it wanted, so a token with no place in the directive was dropped in
//! silence: `2024-01-01 open! Assets:A` loaded clean, and `rledger format`
//! deleted the `!`. `open Assets:A U*SD` loaded as the currency list `U,SD`.
//!
//! `data/stray_char_matrix.tsv` records beancount 3.2.3's verdict for every
//! insertion of each character of [`CHARS`] at every offset of each snippet
//! (and, after a space, the character plus a space). It is generated by
//! `scripts/stray-char-matrix.py`, which runs beancount, so this test needs no
//! Python. The tests below check rledger's verdict against it, row by row.
//!
//! #2802 was fixed in stages, which [`stage`] still names: stage 1 the header
//! lines of the non-transaction directives, stage 2 metadata lines (under any
//! directive, a transaction or a posting), stage 3 transaction headers and
//! posting lines. Every stage is checked.

use proptest::prelude::*;
use rustledger_parser::format::try_format_source;
use rustledger_parser::parse;

/// Must match `CHARS` in `scripts/stray-char-matrix.py`.
const CHARS: &str = "!@?*~^$&|{}(),#%\"/_-'.A0";

const DATA: &str = include_str!("data/stray_char_matrix.tsv");

/// Rows pinned as known differences, by count: see the `known_*` functions.
const KNOWN_COLUMN_0: usize = 180;
const KNOWN_DATES: [usize; 3] = [259, 6, 147];

/// One generated input.
struct Case {
    /// Byte offset the character was inserted at.
    offset: usize,
    /// The inserted character.
    ch: char,
    src: String,
}

/// The generated inputs for one snippet, in the order the table records them.
/// Must match `cases()` in `scripts/stray-char-matrix.py`.
fn cases(base: &str) -> Vec<Case> {
    let mut out = Vec::new();
    for i in 0..base.len() {
        let before = &base[..i];
        let line = &before[before.rfind('\n').map_or(0, |p| p + 1)..];
        if !line.is_empty() && line.chars().all(|c| c == ' ') {
            continue;
        }
        for ch in CHARS.chars() {
            out.push(Case {
                offset: i,
                ch,
                src: format!("{before}{ch}{}", &base[i..]),
            });
            if i > 0 && base.as_bytes()[i - 1] == b' ' {
                out.push(Case {
                    offset: i,
                    ch,
                    src: format!("{before}{ch} {}", &base[i..]),
                });
            }
        }
    }
    out
}

/// A snippet and beancount's verdict on each of its cases.
struct Row {
    name: String,
    base: String,
    /// `'0'` accepted, `'1'` rejected, `'x'` excluded; one per case.
    verdicts: Vec<char>,
}

fn rows() -> Vec<Row> {
    let rows: Vec<Row> = DATA
        .lines()
        .map(|line| {
            let fields: Vec<&str> = line.split('\t').collect();
            assert_eq!(fields.len(), 4, "malformed matrix line: {line:?}");
            assert_eq!(fields[0], "base");
            let base: String =
                serde_json::from_str(fields[2]).expect("the snippet is a JSON string");
            let verdicts: Vec<char> = fields[3].chars().collect();
            assert_eq!(
                verdicts.len(),
                cases(&base).len(),
                "{}: the table and `cases()` disagree on the case count; \
                 regenerate with scripts/stray-char-matrix.py",
                fields[1]
            );
            Row {
                name: fields[1].to_string(),
                base,
                verdicts,
            }
        })
        .collect();
    assert!(
        rows.len() >= 21,
        "only {} snippets in the matrix",
        rows.len()
    );
    rows
}

/// The stage of #2802 a case belongs to, by the line the character lands on
/// (a character inserted at a line's start lands on that line): 2 for a
/// metadata line (`key: value` under a directive, transaction or posting), 3
/// for a transaction's header or posting lines, 1 for any other line.
fn stage(row: &Row, case: &Case) -> u8 {
    let start = row.base[..case.offset].rfind('\n').map_or(0, |p| p + 1);
    let line = &row.base[start..];
    let line = &line[..line.find('\n').unwrap_or(line.len())];
    let body = line.trim_start_matches(' ');
    let is_meta = body.len() < line.len()
        && body.split_once(':').is_some_and(|(key, _)| {
            key.starts_with(|c: char| c.is_ascii_lowercase()) && !key.contains(' ')
        });
    // A transaction's second word is its flag: `*`, `!`, `txn`, or a capital
    // letter (`P`).
    let is_txn = row.base.split([' ', '\r', '\n']).nth(1).is_some_and(|kw| {
        matches!(kw, "*" | "!" | "txn")
            || (kw.len() == 1 && kw.bytes().all(|b| b.is_ascii_uppercase()))
    });
    if is_meta {
        2
    } else if is_txn {
        3
    } else {
        1
    }
}

/// beancount ignores a whole line that starts with `!`, `?` or `&` at column
/// 0; we report it. That is #2779, a separate fix, so these rows may disagree
/// until it lands (the count is pinned below, so the fix will have to update
/// it).
fn known_column_0_divergence(row: &Row, case: &Case) -> bool {
    "!?&".contains(case.ch) && (case.offset == 0 || row.base.as_bytes()[case.offset - 1] == b'\n')
}

/// A digit inserted into a date: beancount's `DATE` is
/// `[0-9]{4,}[-/][0-9]+[-/][0-9]+`, so `02024-01-01` and `2024-001-01` are
/// dates there, and our lexer rejects them; `20024-02-02` lexes as a date
/// there and then fails as one, where ours reads the number expression
/// `20024 - 02 - 02`. A date-lexing difference, not a stray token: #2808.
/// Pinned by count below until it is fixed.
fn known_date_digit_divergence(row: &Row, case: &Case) -> bool {
    let b = row.base.as_bytes();
    let is_date_at = |s: usize| {
        b.get(s..s + 10).is_some_and(|w| {
            w.iter().enumerate().all(|(i, c)| match i {
                4 | 7 => *c == b'-',
                _ => c.is_ascii_digit(),
            })
        }) && (s == 0 || !b[s - 1].is_ascii_digit())
    };
    case.ch.is_ascii_digit()
        && (0..b.len()).any(|s| is_date_at(s) && (s..=s + 10).contains(&case.offset))
}

/// A character inserted right after a `\r` that the line goes on past: a
/// mid-line `\r`, which we report and beancount accepts. A deliberate
/// deviation (#2804): the formatter turns a bare `\r` into a line break, so
/// accepting it would let `rledger check` pass a file `rledger format` then
/// breaks. Pinned by count.
const fn known_mid_line_cr(row: &Row, case: &Case) -> bool {
    case.offset > 0 && row.base.as_bytes()[case.offset - 1] == b'\r'
}

/// A `*` inserted as a component of its own in a cost spec: cost merging,
/// which beancount 3.2.3 rejects ("Cost merging is not supported yet") and
/// rledger implements. Kept until that decision is made (#2802); pinned by
/// count. See `test_parse_accepts_cost_merging_unlike_beancount`.
/// A posting whose cost and price name different currencies: beancount's
/// builder rejects it at parse time; we leave it to booking, which reports it
/// for a sale (E4001) but not for a buy. Pinned by count until the one rule
/// is moved to a single place (#2802). See
/// `test_parse_leaves_a_cost_and_price_currency_mismatch_to_booking`.
fn known_currency_mismatch(src: &str) -> bool {
    parse(src).directives.iter().any(|d| {
        let rustledger_core::Directive::Transaction(t) = &d.value else {
            return false;
        };
        t.postings.iter().any(|p| {
            let cost = p
                .cost
                .as_ref()
                .and_then(|c| c.currency.as_ref())
                .map(rustledger_core::Currency::as_str);
            let price = p
                .price
                .as_ref()
                .and_then(|a| a.amount.as_ref())
                .and_then(|a| a.currency());
            matches!((cost, price), (Some(c), Some(q)) if c != q)
        })
    })
}

fn known_cost_merge(case: &Case) -> bool {
    if case.ch != '*' {
        return false;
    }
    let (before, after) = (&case.src[..case.offset], &case.src[case.offset + 1..]);
    let line = &before[before.rfind('\n').map_or(0, |p| p + 1)..];
    let open = line.rfind('{').is_some_and(|o| !line[o..].contains('}'));
    let before = before.trim_end_matches(' ');
    let after = after.trim_start_matches(' ');
    open && before.ends_with(['{', ',']) && after.starts_with([',', '}'])
}

#[test]
fn test_parse_reports_a_stray_character_exactly_when_beancount_does() {
    let mut checked = [0usize; 3];
    let mut known = 0usize;
    let mut known_dates = [0usize; 3];
    let mut known_cr = 0usize;
    let mut known_merge = 0usize;
    let mut known_mismatch = 0usize;
    let mut wrong = Vec::new();
    for row in rows() {
        for (case, verdict) in cases(&row.base).iter().zip(&row.verdicts) {
            if *verdict == 'x' {
                continue;
            }
            let stage = usize::from(stage(&row, case)) - 1;
            let beancount_rejects = *verdict == '1';
            let we_reject = !parse(&case.src).errors.is_empty();
            let disagree = we_reject != beancount_rejects;
            if known_column_0_divergence(&row, case) && we_reject && !beancount_rejects {
                known += 1;
                continue;
            }
            if known_date_digit_divergence(&row, case) && disagree {
                known_dates[stage] += 1;
                continue;
            }
            if known_mid_line_cr(&row, case) && we_reject && !beancount_rejects {
                known_cr += 1;
                continue;
            }
            if known_cost_merge(case) && !we_reject && beancount_rejects {
                known_merge += 1;
                continue;
            }
            if !we_reject && beancount_rejects && known_currency_mismatch(&case.src) {
                known_mismatch += 1;
                continue;
            }
            checked[stage] += 1;
            if disagree {
                wrong.push(format!(
                    "stage {}: {}@{}:{:?}  {:?}  beancount {}, rledger {}",
                    stage + 1,
                    row.name,
                    case.offset,
                    case.ch,
                    case.src,
                    if beancount_rejects {
                        "rejects"
                    } else {
                        "accepts"
                    },
                    if we_reject { "rejects" } else { "accepts" },
                ));
            }
        }
    }
    assert!(
        checked[0] > 9_000,
        "only {} header cases checked",
        checked[0]
    );
    assert!(
        checked[1] > 5_000,
        "only {} metadata cases checked",
        checked[1]
    );
    assert_eq!(known, KNOWN_COLUMN_0, "the #2779 rows changed");
    assert_eq!(
        known_dates, KNOWN_DATES,
        "the date-digit (#2808) rows changed"
    );
    assert!(
        checked[2] > 20_000,
        "only {} transaction and posting cases checked",
        checked[2]
    );
    assert_eq!(known_cr, 5, "the mid-line `\\r` (#2804) rows changed");
    assert_eq!(known_merge, 1, "the cost-merge (`{{*}}`) rows changed");
    assert_eq!(known_mismatch, 64, "the cost/price currency rows changed");
    assert!(
        wrong.is_empty(),
        "{} of {} cases disagree with beancount, first 20:\n{}",
        wrong.len(),
        checked.iter().sum::<usize>(),
        wrong
            .iter()
            .take(20)
            .cloned()
            .collect::<Vec<_>>()
            .join("\n")
    );
}

/// The issue's rows. Each is reported, the directive is still KEPT (as
/// `reject_tags_and_links` keeps one: a stray character must not cascade into
/// unopened-account errors), `rledger format` refuses the file, and the
/// error-tolerant formatter keeps the line as written.
#[test]
fn test_parse_reports_the_issue_2802_rows_and_keeps_the_directive() {
    for src in [
        "2024-01-01 open! Assets:A\n",
        "2024-01-01 open Assets:A USD @\n",
        "2024-01-01 price HOOL ? 10 USD\n",
        "2024-01-01 open Assets:A U*SD\n",
        "2024-01-01 close! Assets:A\n",
    ] {
        let result = parse(src);
        assert_eq!(result.errors.len(), 1, "{src:?}: {:?}", result.errors);
        assert_eq!(result.directives.len(), 1, "{src:?}: the directive is kept");
        assert!(try_format_source(src).is_err(), "{src:?}");
        assert_eq!(rustledger_parser::format::format_source(src), src);
    }
    // The kept `open` still carries what it said, so a later posting to the
    // account does not cascade.
    let result = parse("2024-01-01 open! Assets:A USD\n");
    let rustledger_core::Directive::Open(open) = &result.directives[0].value else {
        panic!("an open");
    };
    assert_eq!(open.account.as_str(), "Assets:A");
    assert_eq!(open.currencies.len(), 1);
}

/// A `/`-currency (a futures symbol) may have a digit right after the slash,
/// as beancount's lexer allows: `/[A-Z0-9'._-]*[A-Z]([A-Z0-9'._-]*[A-Z0-9])?`,
/// its own example being `/6J`. Ours required a letter first, so `/6J` lexed
/// as `/`, `6`, `J`: `price /6J 10 USD` became a price of `J`, and
/// `price HOOL 10 /6J` an amount of `10 / 6` in `J`.
#[test]
fn test_parse_reads_a_slash_currency_with_a_digit_after_the_slash() {
    use rustledger_core::Directive as D;
    let one = |src: &str| {
        let r = parse(src);
        assert!(r.errors.is_empty(), "{src:?}: {:?}", r.errors);
        assert_eq!(r.directives.len(), 1, "{src:?}");
        r.directives[0].value.clone()
    };
    let D::Commodity(c) = one("2024-01-01 commodity /6J\n") else {
        panic!()
    };
    assert_eq!(c.currency.as_str(), "/6J");
    let D::Open(o) = one("2024-01-01 open Assets:A USD,/6J,/6E_X\n") else {
        panic!()
    };
    let cs: Vec<&str> = o
        .currencies
        .iter()
        .map(rustledger_core::Currency::as_str)
        .collect();
    assert_eq!(cs, ["USD", "/6J", "/6E_X"]);
    let D::Price(p) = one("2024-01-01 price /6J 10 USD\n") else {
        panic!()
    };
    assert_eq!(
        (p.currency.as_str(), p.amount.currency.as_str()),
        ("/6J", "USD")
    );
    let D::Price(p) = one("2024-01-01 price HOOL 10 /6J\n") else {
        panic!()
    };
    assert_eq!(p.amount.to_string(), "10 /6J");
    let D::Balance(b) = one("2024-01-01 balance Assets:A 1 /6J\n") else {
        panic!()
    };
    assert_eq!(b.amount.to_string(), "1 /6J");
    // Longest match, as in flex: with no letter after the slash it is still a
    // division.
    let D::Price(p) = one("2024-01-01 price HOOL 10/4 USD\n") else {
        panic!()
    };
    assert_eq!(p.amount.to_string(), "2.50 USD");
    // And `rledger format` keeps the currency whole.
    for src in [
        "2024-01-01 price HOOL 10 /6J\n",
        "2024-01-01 custom \"b\" 10 /6J\n",
    ] {
        assert_eq!(try_format_source(src).expect("formats"), src);
    }
}

/// beancount's `currency_list COMMA currency` reduces from `%empty`, so one
/// leading comma is valid there and here. `rledger format` used to delete it.
#[test]
fn test_try_format_source_keeps_a_leading_comma_in_a_currency_list() {
    for (src, want) in [
        (
            "2024-01-01 open Assets:A , USD,EUR\n",
            "2024-01-01 open Assets:A ,USD,EUR\n",
        ),
        (
            "2024-01-01 open Assets:A, USD \"FIFO\"\n",
            "2024-01-01 open Assets:A ,USD \"FIFO\"\n",
        ),
    ] {
        assert!(parse(src).errors.is_empty(), "{src:?}");
        let out = try_format_source(src).expect("formats");
        assert_eq!(out, want);
        assert_eq!(try_format_source(&out).expect("formats"), out);
    }
    // Two are a syntax error in beancount, and here.
    assert!(!parse("2024-01-01 open Assets:A ,,USD\n").errors.is_empty());
}

/// A transaction flag written `txn` reads back as `*`: `txn` is the long
/// spelling of the `*` flag, and the formatter writes the flag it parsed (a
/// documented normalization, from before #2802).
fn normalize_txn_flag(s: &str) -> String {
    s.split_inclusive('\n')
        .map(|line| {
            let bytes = line.as_bytes();
            let dated = bytes.len() >= 14
                && bytes[..10].iter().enumerate().all(|(i, b)| match i {
                    4 | 7 => *b == b'-',
                    _ => b.is_ascii_digit(),
                });
            if dated
                && line[10..].starts_with(" txn")
                && matches!(bytes.get(14), Some(b' ' | b'\n' | b'\r') | None)
            {
                format!("{} *{}", &line[..10], &line[14..])
            } else {
                line.to_string()
            }
        })
        .collect()
}

/// `s` without whitespace, and without a comma between two digits: the
/// formatter drops thousands separators (a documented normalization, see the
/// `cst::format` module docs), so `2,024` and `2024` are the same text here.
fn non_whitespace(s: &str) -> String {
    let chars: Vec<char> = s.chars().filter(|c| !c.is_whitespace()).collect();
    chars
        .iter()
        .enumerate()
        .filter(|&(i, &c)| {
            !(c == ','
                && i > 0
                && chars[i - 1].is_ascii_digit()
                && chars.get(i + 1).is_some_and(char::is_ascii_digit))
        })
        .map(|(_, &c)| c)
        .collect()
}

/// Of the in-scope cases that parse clean, `rledger format` keeps every
/// non-whitespace character: the bug was that it deleted the stray one.
#[test]
fn test_try_format_source_keeps_the_text_of_every_clean_matrix_case() {
    let mut clean = 0usize;
    let mut lost = Vec::new();
    for row in rows() {
        for case in cases(&row.base) {
            if !parse(&case.src).errors.is_empty() {
                continue;
            }
            clean += 1;
            let out = try_format_source(&case.src).expect("a clean file formats");
            if non_whitespace(&out) != non_whitespace(&normalize_txn_flag(&case.src)) {
                lost.push(format!(
                    "{}@{}:{:?} lost text: {:?} -> {out:?}",
                    row.name, case.offset, case.ch, case.src
                ));
            }
        }
    }
    assert!(clean > 900, "only {clean} clean cases");
    assert!(
        lost.is_empty(),
        "{} clean cases lost text, first 20:\n{}",
        lost.len(),
        lost.iter().take(20).cloned().collect::<Vec<_>>().join("\n")
    );
}

