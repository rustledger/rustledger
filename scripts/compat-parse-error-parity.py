# Self-test


def self_test():
    """The classifier and the pin check, on hand-written shapes.

    Runs before the real comparison in CI: a classifier bug that called every
    input `match` would otherwise read as perfect parity.
    """
    lex, syn = "LexerError", "ParserSyntaxError"
    text = "a\n  b\nc\nd\n"
    cases = [
        ([[2, syn, ""]], [[2, "P0003", ""]], "match"),
        ([], [[2, "P0003", ""]], "rl-only"),
        ([[2, syn, ""]], [], "bc-only"),
        ([[1, lex, ""]], [[1, "P0012", ""], [1, "P0012", ""]], "lexer-token-split"),
        ([[1, syn, ""]], [[1, "P0012", ""], [1, "P0012", ""]], "more-on-line"),
        ([[1, syn, ""], [1, lex, ""]], [[1, "P0012", ""]], "lexer-tokens-merged"),
        ([[1, syn, ""], [1, syn, ""]], [[1, "P0012", ""]], "fewer-on-line"),
        ([[1, syn, ""]], [[1, "P0012", ""], [2, "P0012", ""]], "rl-indented-line"),
        ([[2, syn, ""]], [[2, "P0012", ""], [3, "P0012", ""]], "rl-top-level-line"),
        ([[1, syn, ""], [3, syn, ""]], [[1, "P0012", ""]], "rl-misses-line"),
        ([[3, syn, ""]], [[2, "P0012", ""]], "off-by-one"),
        ([[1, syn, ""], [0, "ParserError", ""]], [[1, "P0012", ""]], "eof"),
        # rledger's unclosed-pushtag error is beancount's line 0.
        ([[0, "ParserError", ""]], [[1, "P0021", ""]], "match"),
        # The first disagreeing line decides; line 0 sorts last.
        (
            [[0, "ParserError", ""], [3, syn, ""], [4, syn, ""]],
            [[3, "P0012", ""], [3, "P0012", ""]],
            "more-on-line",
        ),
    ]
    for bc, rl, want in cases:
        got = categorize(bc, rl, text)
        assert got == want, f"categorize({bc}, {rl}) = {got}, want {want}"
    # beancount's end-of-line error is moved back to the line it is on; an
    # end-of-file error and any other error keep their line.
    class ParserSyntaxError:
        def __init__(self, line, message):
            self.source, self.message = {"lineno": line}, message

    kept = keep_parse_errors(
        [
            ParserSyntaxError(3, "syntax error, unexpected EOL, expecting STRING"),
            ParserSyntaxError(2, "syntax error, unexpected end of file"),
            ParserSyntaxError(4, "syntax error, unexpected NUMBER"),
        ],
        lambda e: False,
    )
    assert [e[0] for e in kept] == [2, 2, 4], kept
    # beancount's error at an indented comment no entry continues is dropped
    # (CRLF too); one at an indented line with content is kept.
    indent = "syntax error, unexpected INDENT"
    for src, want in [
        ("2024-01-01 open Assets:A\n; note\n  ; continued\n", []),
        ("; note\r\n\t; continued\r\n", []),
        ("\n  ; c\n", []),
        ("* heading\n  ; c\n", []),
        ("; note\n  x ; c\n", [2]),
        ("option \"a\" \"b\"\n  ; c\n", [2]),
        ("#tag\n  ; c\n", [2]),
    ]:
        line = 3 if src.startswith("2024") else 2
        kept = keep_parse_errors([ParserSyntaxError(line, indent)], lambda e: False, src)
        assert [e[0] for e in kept] == want, (src, kept)
    # beancount's tags-after-first-posting error, on the header line, moves
    # to each late tag line in turn; a tag line before the first posting, a
    # comment and a posting with a flag are read past.
    tags = "Tags or links not allowed after first Posting: TagsLinks()"
    for src, want in [
        ('2024-01-02 * "x"\n  Assets:A 1 USD\n  #tag\n  Assets:A -1 USD\n', [3]),
        (
            '2024-01-02 * "x"\r\n  #pre\r\n  ! Assets:A 1 USD\r\n; c\r\n'
            '  #t ^l ; c\r\n  Assets:A\r\n    ^m\r\n',
            [5, 7],
        ),
        ('2024-01-02 * "x"\n  Assets:A 1 USD\n\n  #tag\n', [1, 1]),
    ]:
        errs = [ParserSyntaxError(1, tags) for _ in want]
        kept = keep_parse_errors(errs, lambda e: False, src)
        assert [e[0] for e in kept] == want, (src, kept)
    assert bucket("more-on-line", [[1, syn, ""]], [[1, "P0012", ""]] * 2) == "count"
    assert bucket("off-by-one", [[3, syn, ""]], [[2, "P0012", ""]]) == "lines"
    assert set(CATEGORIES) == {w for _, _, w in cases} | {"crash"}

    inputs = Inputs()
    inputs.add("fuzz", "f1", b"a")
    inputs.add("fuzz", "f2", b"b")
    inputs.add("tracked", "tests/x.beancount", b"c")
    inputs.add("fuzz", "f3", b"\xff")
    inputs.add("fuzz", "f1-dup", b"a")
    assert inputs.non_utf8["fuzz"] == 1 and inputs.duplicates == 1
    ids = {label: cid for cid, (_, label, _) in inputs.items.items()}
    results = {
        ids["f1"]: ("rl-only", [], []),
        ids["f2"]: ("match", [], []),
        ids["tests/x.beancount"]: ("match", [], []),
    }
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        write_baseline(path, inputs, results, "abc", counts={"k|a b": 2, "k|c": 1}, revision="r1")
        meta, pins = read_baseline(path)
    assert meta == {
        "fuzz-commit": "abc",
        "ptadiff-rev": "r1",
        "category-key": CATEGORY_KEY,
        "generators": " ".join(GENERATOR_SAMPLE),
        "inputs": {"fuzz": 3, "matrix": 0, "gen": 0},
        "categories": {"k|a b": 2, "k|c": 1},
    }, meta
    assert set(pins) == {ids["f1"], ids["tests/x.beancount"]}, pins
    assert check_against_baseline(inputs, results, pins) == ([], [], [], [])
    # f2 regresses, f1 starts matching, the ledger changes category.
    later = dict(results)
    later[ids["f2"]] = ("off-by-one", [], [])
    later[ids["f1"]] = ("match", [], [])
    later[ids["tests/x.beancount"]] = ("rl-extra", [], [])
    reg, imp, chg, unp = check_against_baseline(inputs, later, pins)
    assert sorted(reg) == [("f2", "off-by-one"), ("tests/x.beancount", "rl-extra")], reg
    assert imp == [("f1", "rl-only")], imp
    assert chg == [] and unp == [], (chg, unp)
    # A ledger with no row is unpinned, not a regression.
    del pins[ids["tests/x.beancount"]]
    reg, _, _, unp = check_against_baseline(inputs, later, pins)
    assert reg == [("f2", "off-by-one")] and unp == [
        ("tests/x.beancount", "rl-extra", True, ids["tests/x.beancount"])
    ], (reg, unp)
    # --update keeps a compat row whose content this run did not see.
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        old = {"aaaaaaaaaaaa": ("compat", "rl-only", "tests/compatibility/files/y")}
        write_baseline(path, inputs, results, "abc", previous=old)
        _, kept = read_baseline(path)
    assert kept["aaaaaaaaaaaa"] == old["aaaaaaaaaaaa"], kept
    # A copied `pin-row` appended after a fuzz section still reads as a pin.
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        path.write_text("@ fuzz rl-only\nbbbbbbbbbbbb\ncompat\tcccccccccccc\tmatch\tz\n")
        _, appended = read_baseline(path)
    assert appended == {
        "bbbbbbbbbbbb": ("fuzz", "rl-only", ""),
        "cccccccccccc": ("compat", "match", "z"),
    }, appended
    assert strip_bom("\ufeffx") == "x" and strip_bom("x\ufeff") == "x\ufeff"

    # beancount's errors: option, account-name and cost-merge errors dropped,
    # a missing line read as 0.
    class Err:
        def __init__(self, line, message):
            self.source = {"filename": "<string>", "lineno": line}
            self.message = message

    class LexerError(Err):
        pass

    errs = [
        Err(1, "Invalid option: 'x'"),
        Err(2, "Invalid account name: 'a'"),
        Err(3, "Error for option 'booking_method': Invalid value"),
        Err(4, "Option 'filename' may not be set"),
        Err(5, "Cost merging is not supported yet"),
        LexerError(6, "Invalid token: 'q'"),
        Err(None, "Unbalanced pushed tag: 't'"),
    ]
    is_not_syntax = load_matrix_module().is_not_syntax  # imports beancount
    assert keep_parse_errors(errs, is_not_syntax) == [
        [6, "LexerError", "Invalid token: 'q'"],
        [0, "Err", "Unbalanced pushed tag: 't'"],
    ], keep_parse_errors(errs, is_not_syntax)

    # --check's exit code. `inputs` holds 3 fuzz inputs (f1 pinned rl-only,
    # f2 a pinned match) and a pinned tracked ledger.
    meta = {
        "fuzz-commit": "abc",
        "ptadiff-rev": "r1",
        "category-key": CATEGORY_KEY,
        "generators": " ".join(GENERATOR_SAMPLE),
        "inputs": {"fuzz": 3, "matrix": 0, "gen": 0},
        "categories": {"k|a": 1},
    }
    pins = {ids["f1"]: ("fuzz", "rl-only", ""), ids["tests/x.beancount"]: ("tracked", "match", "x")}

    def code(results, meta=meta, pins=pins, counts=None, revision=None):
        return run_check(
            inputs, results, meta, pins, out=lambda _: None, counts=counts, revision=revision
        )

    assert code(results) == 0
    assert code({**results, ids["f2"]: ("off-by-one", [], [])}) == 1  # regression
    assert code({**results, ids["f1"]: ("match", [], [])}) == 1  # stale: improved
    assert code({**results, ids["f1"]: ("off-by-one", [], [])}) == 1  # stale: shape
    no_row = {ids["f1"]: ("fuzz", "rl-only", "")}
    assert code(results, pins=no_row) == 0  # unpinned tracked ledger: warns
    assert code(results, meta={**meta, "inputs": {"fuzz": 9, "matrix": 0, "gen": 0}}) == 1
    # A coverage failure (a matrix base added, say) says how to fix it.
    said = []
    seven = {**meta, "inputs": {"fuzz": 3, "matrix": 7, "gen": 0}}
    run_check(inputs, results, seven, pins, out=said.append)
    assert any("--update" in line for line in said), said
    assert code(results, meta={**meta, "inputs": {"matrix": 0, "gen": 0}}) == 1  # no count
    # The category counts: equal passes, any difference (a count, a new key,
    # a vanished key) is a stale pin, and the pinned ptadiff revision, key and
    # generator sample are coverage.
    assert code(results, counts={"k|a": 1}, revision="r1") == 0
    assert code(results, counts={"k|a": 2}) == 1
    assert code(results, counts={"k|a": 1, "k|b": 1}) == 1
    assert code(results, counts={}) == 1
    assert category_changes({"k|a": 1, "k|b": 2}, {"k|b": 3, "k|c": 1}) == [
        ("k|a", 1, 0),
        ("k|b", 2, 3),
        ("k|c", 0, 1),
    ]
    assert code(results, revision="r2") == 1
    assert code(results, meta={**meta, "generators": "g1:1:5"}) == 1
    assert code(results, meta={**meta, "category-key": "coarse"}) == 1
    # A category row after a fuzz section stays a category; a copied
    # `pin-row` after the categories stays a pin.
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        path.write_text(
            "@ categories\n3\timpl-more|impl:P0012|top|^ error\n"
            "compat\tcccccccccccc\tmatch\tz\n"
        )
        cmeta, cpins = read_baseline(path)
    assert cmeta["categories"] == {"impl-more|impl:P0012|top|^ error": 3}, cmeta
    assert cpins == {"cccccccccccc": ("compat", "match", "z")}, cpins

    # The category key of a mismatch, from both sides' errors and
    # beancount's tokens: rledger reports an indented line twice that
    # beancount reports once, as an invalid token.
    fmt = ptadiff.get_format("beancount")
    toks = [ptadiff.Token("INDENT", 2, "  "), ptadiff.Token("error", 2, "$")]
    key = category_key(
        fmt,
        "\ufeffx\n  $\n",
        [[2, "LexerError", "Invalid token: '$'"]],
        [[2, "P0012", "a"], [2, "P0012", "b"], [1, "P0021", "c"]],
        toks,
    )
    assert key == "impl-more|impl:P0012|indented|INDENT error", key
    # rledger's unclosed push is beancount's line 0, so it diverges there.
    key = category_key(fmt, "pushtag #a\n", [], [[1, "P0021", "u"]], [])
    assert key == "eof|impl:P0021|eof|-", key
    # A lexer crash leaves the shape unknown, not the input uncategorized.
    key = category_key(fmt, "x\n", [], [[1, "P0012", "a"]], ptadiff.Crash("killed"))
    assert key == "impl-more|impl:P0012|top|?", key
    ghost = {**pins, "dddddddddddd": ("fuzz", "rl-only", "")}
    assert code(results, pins=ghost) == 1  # a pinned id that did not run
    assert rl_lines([[5, "P0021", ""], [5, "P0003", ""]]) == [0, 5]
    print("self-test: ok")


