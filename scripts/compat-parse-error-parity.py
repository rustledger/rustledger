# Report


def render_report(inputs, results, examples=1):
    buckets = {
        cid: bucket(c, bc, rl) if c != "crash" else "crash"
        for cid, (c, bc, rl) in results.items()
    }
    by_bucket = collections.Counter(buckets.values())
    by_cat = collections.Counter(c for c, _, _ in results.values())
    by_source = collections.defaultdict(collections.Counter)
    for cid in results:
        by_source[inputs.items[cid][0]][buckets[cid]] += 1
    # Inputs whose every disagreeing line is of one kind: what fixing that
    # kind alone would turn into a match.
    sole = collections.Counter()
    for cid, (c, bc, rl) in results.items():
        if c not in ("match", "crash", "rl-only", "bc-only"):
            kinds = set(line_kinds(bc, rl, inputs.items[cid][2]))
            if len(kinds) == 1:
                sole[kinds.pop()] += 1
    total = len(results)
    lines = ["# Parse-error parity: rledger vs beancount 3.2.3", ""]
    lines.append(f"Inputs compared: {total}")
    excluded = sum(inputs.non_utf8.values())
    lines.append(
        f"Excluded as not UTF-8: {excluded} "
        + "("
        + ", ".join(f"{k} {v}" for k, v in sorted(inputs.non_utf8.items()))
        + ")"
    )
    lines.append(f"Duplicate contents counted once: {inputs.duplicates}")
    lines.append("")
    lines.append(
        "| Source | Inputs | Match | Only the count differs | Lines differ "
        "| beancount crashed (not compared) |"
    )
    lines.append("|---|---|---|---|---|---|")
    for source in sorted(by_source) + ["all"]:
        c = by_bucket if source == "all" else by_source[source]
        n = sum(c.values())
        lines.append(
            f"| {source} | {n} | {c['match']} ({100 * c['match'] / max(n, 1):.1f}%) "
            f"| {c['count']} | {c['lines']} | {c['crash']} |"
        )
    lines.append("")
    lines.append(
        f"{by_bucket['crash']} inputs crashed beancount (or made it raise): "
        "they have no beancount verdict, so rledger is not compared on them, "
        "and they count in neither the matches nor the mismatches."
    )
    lines.append("")
    lines.append("## Mismatch categories")
    lines.append("")
    lines.append(
        "An input's category is the kind of the FIRST line the two sides "
        "disagree on. *Sole kind* counts the inputs whose every disagreeing "
        "line is of that kind: the ones fixing it alone would turn into matches."
    )
    lines.append("")
    lines.append("| Category | Inputs | Sole kind | Meaning |")
    lines.append("|---|---|---|---|")
    for cat, n in by_cat.most_common():
        if cat != "match":
            lines.append(f"| `{cat}` | {n} | {sole.get(cat, '')} | {CATEGORIES[cat]} |")
    lines.append("")
    lines.append("## Smallest example of each category")
    for cat, _ in by_cat.most_common():
        if cat == "match":
            continue
        cands = sorted(
            (len(inputs.items[cid][2]), cid)
            for cid, (c, _, _) in results.items()
            if c == cat
        )[:examples]
        for _, cid in cands:
            source, label, text = inputs.items[cid]
            _, bc, rl = results[cid]
            lines.append("")
            lines.append(f"### `{cat}`: {label}")
            lines.append("")
            lines.append("```")
            lines.append(json.dumps(text))
            lines.append("```")
            if isinstance(bc, str):
                lines.append(f"- beancount: {bc}")
            else:
                lines.append(
                    "- beancount: " + "; ".join(f"{e[0]}: {e[2]}" for e in bc)
                )
            lines.append(
                "- rledger: " + "; ".join(f"{e[0]}: {e[1]} {e[2]}" for e in rl)
            )
    return "\n".join(lines) + "\n"


