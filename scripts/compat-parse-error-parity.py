# change (a tracked file is edited, a downloaded one changes upstream), so an
# unlisted one is new, not a pinned match.
LEDGER_SOURCES = ("tracked", "compat")
# Sources whose input set the manifest fixes: the fuzz corpus at the pinned
# commit, and the matrix this checkout generates. Their counts are pinned.
FIXED_SOURCES = ("fuzz", "matrix")
# Where `fetch-compat-test-files.sh` puts the downloaded corpus: the prefix of
# every compat label, whatever `--compat-dir` is.
COMPAT_LABEL_ROOT = Path("tests/compatibility/files")
# rledger's file-level errors: beancount reports these at line 0.
RLEDGER_EOF_CODES = {"P0021", "P0023"}  # UnclosedPushtag, UnclosedPushmeta
# A single beancount parse that runs longer than this is recorded as a crash.
BEANCOUNT_TIMEOUT_S = 20

CATEGORIES = {
    "match": "error lines and counts match",
    "crash": "beancount crashed or raised (no verdict)",
    "rl-only": "rledger reports errors, beancount none",
    "bc-only": "beancount reports errors, rledger none",
    "lexer-token-split": "beancount reads a run of bad characters up to the next "
    "space as ONE invalid token; rledger reports several errors on that line",
    "lexer-tokens-merged": "beancount reports each bad token on the line (often plus "
    "a grammar error); rledger reports the line fewer times",
    "more-on-line": "both report the line, rledger more often (not a lexer run)",
    "fewer-on-line": "both report the line, rledger less often (not a lexer error)",
    "rl-indented-line": "rledger reports an indented line that beancount's recovery "
    "skips (the lines under a broken directive)",
    "rl-top-level-line": "rledger reports a top-level line that beancount stays "
    "quiet on (bison's recovery accepts 3 tokens before it reports again)",
    "rl-misses-line": "beancount reports a line that rledger does not",
    "off-by-one": "the same error, reported one line apart",
    "eof": "they differ only on a file-level error (line 0)",
}


def log(message):
    print(message, file=sys.stderr, flush=True)


def load_matrix_module():
    spec = importlib.util.spec_from_file_location("stray_char_matrix", MATRIX_SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def content_id(data):
    return hashlib.sha256(data).hexdigest()[:12]


# --------------------------------------------------------------------------
# Inputs


class Inputs:
    """Inputs keyed by content id, each with a source and a display label."""

    def __init__(self):
        self.items = {}  # id -> (source, label, text)
        self.non_utf8 = collections.Counter()
        # UTF-8 inputs read per source, duplicates included: what `#@inputs`
        # pins. Counted before deduplication, so it does not depend on what
        # other sources (a machine's downloaded corpus) happen to hold.
        self.seen = collections.Counter()
        self.duplicates = 0

    def add(self, source, label, data):
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            self.non_utf8[source] += 1
            return
        self.seen[source] += 1
        cid = content_id(data)
        if cid in self.items:
            self.duplicates += 1
            return
        self.items[cid] = (source, label, text)


def tracked_ledgers():
    out = subprocess.run(
        ["git", "-C", str(REPO), "ls-files", "-z", "*.beancount", "*.bean"],
        check=True,
        capture_output=True,
    ).stdout
    return sorted(p for p in out.decode().split("\0") if p)


def collect(args):
    inputs = Inputs()
    matrix = load_matrix_module()
    for name, base in matrix.BASES:
        for i, src in enumerate(matrix.cases(base)):
            inputs.add("matrix", f"matrix:{name}#{i}", src.encode("utf-8"))
    for rel in tracked_ledgers():
        inputs.add("tracked", rel, (REPO / rel).read_bytes())
    for d in FUZZ_REGRESSIONS:
        if d.is_dir():
            # Every file but the directory's README is a fuzz input.
            for p in sorted(q for q in d.iterdir() if q.name != "README.md"):
                inputs.add("tracked", str(p.relative_to(REPO)), p.read_bytes())
    if args.compat_dir:
        compat = Path(args.compat_dir)
        found = sorted(compat.rglob("*.beancount"))
        if len(found) < args.min_compat:
            sys.exit(
                f"error: {len(found)} .beancount files under {compat}, expected at "
                f"least {args.min_compat}; the corpus fetch likely failed"
            )
        for p in found:
            # Labelled by the corpus's place in the repo, wherever this copy
            # of it lives, so a pin written from another directory keeps the
            # same labels.
            rel = (COMPAT_LABEL_ROOT / p.relative_to(compat)).as_posix()
            inputs.add("compat", rel, p.read_bytes())
    if args.fuzz_dir:
        root = Path(args.fuzz_dir)
        for target in FUZZ_TARGETS:
            d = root / target
            if not d.is_dir():
                sys.exit(f"error: {d} is missing; extract the fuzz-corpus commit there")
            for p in sorted(d.iterdir()):
                inputs.add("fuzz", f"{target}/{p.name}", p.read_bytes())
    return inputs


# --------------------------------------------------------------------------
# beancount side


def strip_bom(text):
    return text[1:] if text.startswith("\ufeff") else text


# More errors beancount's grammar actions raise that are not parse errors in
# rledger, on top of the matrix script's `is_not_syntax`: option VALUES and
# option names that may not be set, which rledger's loader checks
# (`rustledger-loader/src/options.rs` reports each of these), and cost merging
# (`{*}`), which beancount 3.2.3 rejects and rledger implements on purpose
# (see `known_cost_merge` in `tests/stray_char_matrix.rs`). Kept here rather
# than in `is_not_syntax`, which also decides the matrix's exclusions.
NOT_PARSE_ERRORS = (
    "Error for option",
    "may not be set",
    "Renamed to '",
    "Allowing pipe separator",
    "Cost merging is not supported yet",
)


def beancount_errors(parser, is_not_syntax, text):
    """beancount's parse errors for `text` as `[line, type, message]`."""
    _, errors, _ = parser.parse_string(strip_bom(text))
    return keep_parse_errors(errors, is_not_syntax)


def keep_parse_errors(errors, is_not_syntax):
    """beancount `errors` minus the ones that are not parse errors in rledger."""
    out = []
    for e in errors:
        if is_not_syntax(e) or any(m in str(e.message) for m in NOT_PARSE_ERRORS):
            continue
        line = (e.source or {}).get("lineno") or 0
        out.append([int(line), type(e).__name__, str(e.message)])
    return out


def _worker(items, wfd):
    from beancount.parser import parser

    is_not_syntax = load_matrix_module().is_not_syntax
    with os.fdopen(wfd, "w") as w:
        for cid, text in items:
            signal.alarm(BEANCOUNT_TIMEOUT_S)
            try:
                result = {"errors": beancount_errors(parser, is_not_syntax, text)}
            except Exception as exc:  # the parser raised: no verdict
                result = {"crash": f"raised {type(exc).__name__}: {exc}"}
            signal.alarm(0)
            w.write(cid + "\t" + json.dumps(result) + "\n")
            w.flush()


def _spawn(items):
    r, w = os.pipe()
    pid = os.fork()
    if pid == 0:
        os.close(r)
        # No core file. beancount segfaults on some inputs (see the module
        # doc), and the harness records those as `crash`, so a core is pure
        # waste: 50-70 MB each, and fuzz runs wrote thousands of them.
        resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
        # Exit 3 unless the worker finishes; `finally` runs on any exception,
        # so the child never returns into the parent's code.
        code = 3
        try:
            _worker(items, w)
            code = 0
        finally:
            os._exit(code)
    os.close(w)
    return pid, os.fdopen(r, "r")


def run_beancount(items, jobs):
    """beancount's result for every `(id, text)`, in forked workers.

    A worker that dies (a segfault, the timeout's SIGALRM) loses only the
    input it was on: that one is recorded as a crash, and a new worker takes
    the rest of its share.
    """
    results = {}
    shares = [items[i::jobs] for i in range(jobs)]
    sel = selectors.DefaultSelector()
    for share in shares:
        if share:
            pid, f = _spawn(share)
            sel.register(f, selectors.EVENT_READ, [pid, share, 0, ""])
    while sel.get_map():
        for key, _ in sel.select():
            f, state = key.fileobj, key.data
            chunk = os.read(f.fileno(), 1 << 16).decode("utf-8")
            if chunk:
                state[3] += chunk
                *lines, state[3] = state[3].split("\n")
                for line in lines:
                    cid, payload = line.split("\t", 1)
                    if cid != state[1][state[2]][0]:
                        sys.exit(f"error: worker out of order at {cid}")
                    results[cid] = json.loads(payload)
                    state[2] += 1
                continue
            sel.unregister(f)
            f.close()
            _, status = os.waitpid(state[0], 0)
            done, share = state[2], state[1]
            if done < len(share):
                if os.WIFSIGNALED(status):
                    why = f"killed by {signal.Signals(os.WTERMSIG(status)).name}"
                else:
                    why = f"exited {os.WEXITSTATUS(status)}"
                results[share[done][0]] = {"crash": why}
                rest = share[done + 1 :]
                if rest:
                    pid, nf = _spawn(rest)
                    sel.register(nf, selectors.EVENT_READ, [pid, rest, 0, ""])
            elif not os.WIFEXITED(status) or os.WEXITSTATUS(status) != 0:
                sys.exit(f"error: a beancount worker failed after its share: {status}")
    return results


