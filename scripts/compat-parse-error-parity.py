#!/usr/bin/env python3
"""Differential harness: rledger's parse errors against beancount 3.2.3's.

For every input, both parsers run and each side's errors are reduced to the
set of `(line, count)` pairs: the lines errors are reported on, and how many
errors each line carries. The input MATCHES when the two sets are equal. This
replaces the hand-kept table in #2872 with a number CI tracks.

Ground truth is beancount's own parser, in process
(`beancount.parser.parser.parse_string`), never `bean-check`: only parse,
grammar and lexer errors are compared, not validation errors. rledger's side
is `rustledger_parser::parse`, through the `parse_error_lines` example of
`rustledger-loader` (which computes lines with the `LineIndex` that
`rledger check` uses).

Inputs (each one keyed by a content hash, so a duplicate counts once):

  * `matrix`: every case of the stray-character matrix, generated by
    `cases()` and `BASES` imported from `scripts/stray-char-matrix.py`, not
    copied;
  * `tracked`: every git-tracked `.beancount` / `.bean` file, and the fuzz
    crash regressions of the two parser targets below;
  * `compat`: the downloaded compat corpus under `tests/compatibility/files`
    (`--compat-dir`, fetched by `scripts/fetch-compat-test-files.sh`);
  * `fuzz`: the `fuzz_parse` and `fuzz_green_eq_red` corpora of the
    `fuzz-corpus` branch, at the commit pinned in the baseline
    (`--fuzz-dir`, extracted by the caller with `git archive`).

Only UTF-8 inputs are compared (both fuzz targets skip the rest too); the
report counts the ones excluded.

Normalization, applied identically to both sides:

  * BOM: rledger strips a byte-0 UTF-8 BOM before it parses (in one place,
    `rustledger_parser::bom::strip_leading`) and accepts the file; beancount
    3.2.3 does not strip it, and reports `Invalid token: '\\ufeff...'` on
    line 1. That is one deliberate, known difference, and left in it would
    mismatch every BOM-prefixed input whatever the rest of the file does, so
    the harness strips a byte-0 BOM from beancount's input too (the same
    predicate: U+FEFF as the very first character). A BOM anywhere else is
    passed through untouched to both sides.
  * Lines: both sides count `\\n` only. A CRLF line is one line on both; a
    bare `\\r` is not a line break on either (beancount's lexer and
    `LineIndex` agree), so no rewriting is needed or done.
  * Locations with no line: beancount reports an unclosed `pushtag` /
    `pushmeta` at line 0 of `<string>` (`<load>:0` in bean-check). rledger
    reports the same errors at the push. Both map to line 0, "end of file":
    the difference is where each prints a file-level error, not recovery.
  * Not syntax: beancount's parser also rejects option names, option values
    and account names, which rledger checks when it loads the file, and cost
    merging (`{*}`), which rledger implements deliberately. Those errors are
    dropped from beancount's side (`is_not_syntax` from the matrix script,
    the predicate that excludes them there, plus `NOT_PARSE_ERRORS`).

beancount can crash on some inputs (`1./00` in an amount segfaults its C
parser; some `pushmeta` / `popmeta` values make its builder raise). Each
beancount parse runs in a forked worker; a worker that dies takes only the
input it was on, which is recorded as `crash`, never skipped. A Python
exception from the parser is recorded the same way. A crashed input has no
verdict, so rledger is not compared on it; the report counts them apart.

Baseline (`tests/baselines/parse-error-parity.manifest`): every mismatching
or crashing input with its category, plus every `tracked` and `compat` file
with its status, matches included. A `fuzz` or `matrix` input that is absent
from the manifest is pinned as matching: the fuzz inputs come from the commit
the manifest pins (`#@fuzz-commit`), and the matrix from this checkout, so
both sets are fixed, and `#@inputs <source> <n>` records how many each has.

With `--check`, the run FAILS when:

  * a pinned match now mismatches (a regression);
  * a pinned mismatch now matches or changes category (a stale pin: run
    `--update` and commit the manifest, so a later PR cannot regress it
    unnoticed);
  * a `fuzz` or `matrix` input count differs from `#@inputs`, or a pinned
    `fuzz` / `matrix` id is not among the inputs (the run did not compare
    what the pin covers, e.g. an empty fuzz directory).

A `tracked` or `compat` input with no row is new content (a test ledger was
added or edited, or upstream changed a downloaded file). It only warns, and
prints the `pin-row` line that pins it.

Usage (build rledger's side first with `cargo build --release -p
rustledger-loader --no-default-features --example parse_error_lines`):

    python3 -I scripts/compat-parse-error-parity.py \\
        --rledger target/release/examples/parse_error_lines \\
        --fuzz-dir DIR --fuzz-commit SHA --compat-dir tests/compatibility/files \\
        [--check | --update] [--report FILE] [--results FILE]
    python3 -I scripts/compat-parse-error-parity.py --self-test
"""

