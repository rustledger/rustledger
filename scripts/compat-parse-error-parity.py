# Baseline


def read_baseline(path):
    """`(meta, pins)` from a manifest `write_baseline` wrote.

    `pins` maps a content id to `(source, category, label)`; the label is
    empty for the bare ids of a `fuzz` or `matrix` section.
    """
    meta, pins = {}, {}
    if not path.exists():
        return meta, pins
    section = None
    for line in path.read_text().splitlines():
        if line.startswith("#@inputs "):
            source, n = line[len("#@inputs ") :].split(" ")
            meta.setdefault("inputs", {})[source] = int(n)
        elif line.startswith("#@"):
            key, _, value = line[2:].partition(" ")
            meta[key] = value
        elif not line or line.startswith("#"):
            continue
        elif line.startswith("@ "):
            section = line[2:].split(" ")
        elif "\t" in line:
            # A ledger row; accepted in any section, so rows appended at the
            # end (copied `pin-row` lines) read as pins until --update sorts
            # them into place.
            source, cid, category, label = line.split("\t")
            pins[cid] = (source, category, label)
        elif section and len(section) == 2:
            pins[line] = (section[0], section[1], "")
        else:
            sys.exit(f"error: {path}: a row outside any section: {line!r}")
    return meta, pins


def write_baseline(path, inputs, results, fuzz_commit, previous=None):
    """Write the manifest: every ledger in full, then mismatches by section.

    `tracked` and `compat` files get one row each, matches included, with
    their path. `fuzz` and `matrix` inputs are listed only when they do not
    match, as bare ids under a `@ <source> <category>` header: there are tens
    of thousands, and a path or label per row would make the file several
    megabytes.

    `previous` (the old pins) keeps every `compat` row whose content this run
    did not see. The downloaded corpus is not the same everywhere (CI replays
    a cached copy, a local fetch is fresher), so a pin written on one machine
    must not drop the rows another machine's corpus needs.
    """
    ledgers, sections = [], collections.defaultdict(list)
    for cid, (source, category, label) in (previous or {}).items():
        if source == "compat" and cid not in results:
            ledgers.append((source, label, cid, category))
    for cid, (category, _, _) in results.items():
        source, label, _ = inputs.items[cid]
        if source in LEDGER_SOURCES:
            ledgers.append((source, label, cid, category))
        elif category != "match":
            sections[(source, category)].append(cid)
    with open(path, "w") as f:
        f.write(
            "# Parse-error parity baseline: rledger against beancount 3.2.3.\n"
            "# Written by scripts/compat-parse-error-parity.py --update; see its\n"
            "# docstring for the full command and what each category means.\n"
            "#\n"
            "# Ids are content hashes (sha256, first 12 hex digits).\n"
            "# `@ ledgers`: source<TAB>id<TAB>category<TAB>path, one row per\n"
            "# tracked or downloaded ledger, matches included.\n"
            "# `@ <source> <category>`: the fuzz or matrix inputs that do not\n"
            "# match, one id per line. An unlisted fuzz or matrix input is pinned\n"
            "# as matching.\n"
        )
        f.write(f"#@fuzz-commit {fuzz_commit}\n")
        for source in FIXED_SOURCES:
            f.write(f"#@inputs {source} {inputs.seen[source]}\n")
        f.write("@ ledgers\n")
        for source, label, cid, category in sorted(ledgers):
            f.write(f"{source}\t{cid}\t{category}\t{label}\n")
        for source, category in sorted(sections):
            f.write(f"@ {source} {category}\n")
            for cid in sorted(sections[(source, category)]):
                f.write(f"{cid}\n")


def check_against_baseline(inputs, results, pins):
    """`(regressions, improvements, changed, unpinned)` against the pins.

    A regression is an input pinned as matching (listed `match`, or a matrix
    or fuzz input not listed at all) that now mismatches. An unpinned input
    is a ledger with no row: its content is new (a downloaded file changed
    upstream, or a tracked file was added or edited).
    """
    regressions, improvements, changed, unpinned = [], [], [], []
    for cid, (category, _, _) in sorted(results.items()):
        source, label, _ = inputs.items[cid]
        pin = pins.get(cid)
        if pin is None:
            if source in LEDGER_SOURCES:
                unpinned.append((label, category, source == "tracked", cid))
                continue
            pinned = "match"
        else:
            pinned = pin[1]
        if pinned == category:
            continue
        if pinned == "match":
            regressions.append((label, category))
        elif category == "match":
            improvements.append((label, pinned))
        else:
            changed.append((label, pinned, category))
    return regressions, improvements, changed, unpinned


def coverage_errors(inputs, meta, pins):
    """Why this run does not cover what the manifest pins, if it does not.

    The fuzz and matrix sets are fixed by the manifest, so a different count,
    or a pinned id that is not among the inputs, means the run compared
    something else (an empty or partial fuzz directory, a changed matrix):
    its "no regressions" would not be about the pinned inputs.
    """
    errors = []
    pinned = meta.get("inputs", {})
    for source in FIXED_SOURCES:
        if source not in pinned:
            errors.append(f"the manifest has no `#@inputs {source}` count")
        elif inputs.seen[source] != pinned[source]:
            errors.append(
                f"{inputs.seen[source]} {source} inputs, the manifest pins "
                f"{pinned[source]}"
            )
    missing = collections.Counter(
        source
        for cid, (source, _, _) in pins.items()
        if source in FIXED_SOURCES and cid not in inputs.items
    )
    for source, n in sorted(missing.items()):
        errors.append(f"{n} pinned {source} id(s) are not among the inputs")
    return errors


def run_check(inputs, results, meta, pins, out=print):
    """`--check`: print every finding, return the exit code.

    Fails on a regression, a stale pin (an improvement or a changed
    category: `--update` and commit, as the corpus baselines force
    `BASELINE_UPDATE`), and a run that does not cover the pinned inputs.
    An unpinned tracked or downloaded ledger only warns, with its pin row.
    """
    coverage = coverage_errors(inputs, meta, pins)
    regressions, improvements, changed, unpinned = check_against_baseline(
        inputs, results, pins
    )
    for message in coverage:
        out(f"::error::the run does not cover the pinned inputs: {message}")
    for label, category, tracked, cid in unpinned:
        source = "tracked" if tracked else "compat"
        out(f"::warning::no pin for this content ({category}): {label}")
        # The row that pins it, on a line of its own so it can be copied out
        # of a log (see tests/baselines/README.md).
        out(f"pin-row\t{source}\t{cid}\t{category}\t{label}")
    for label, pinned in improvements:
        out(f"::error::stale pin, now matches beancount (pinned {pinned}): {label}")
    for label, pinned, category in changed:
        out(f"::error::stale pin, mismatch changed {pinned} -> {category}: {label}")
    for label, category in regressions:
        out(f"::error::regression, matched beancount and now {category}: {label}")
    stale = len(improvements) + len(changed)
    if coverage or regressions or stale:
        out(
            f"FAILED: {len(regressions)} regression(s), {stale} stale pin(s), "
            f"{len(coverage)} coverage error(s)"
        )
        if (stale or coverage) and not regressions:
            out(
                "Parity or the input set changed: run this script with "
                "--update (see tests/baselines/README.md) and commit "
                "tests/baselines/parse-error-parity.manifest."
            )
        return 1
    out(f"no regressions ({len(unpinned)} unpinned ledger(s))")
    return 0


