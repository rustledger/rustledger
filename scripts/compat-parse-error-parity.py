# Self-test


def self_test():
    """The classifier and the pin check, on hand-written shapes.

    Runs before the real comparison in CI: a classifier bug that called every
    input `match` would otherwise read as perfect parity.
    """
    lex, syn = "LexerError", "ParserSyntaxError"
    text = "a\n  b\nc\nd\n"
    cases = [
        ([[2, syn, ""]], [[2, "P0003", ""]], "match"),
        ([], [[2, "P0003", ""]], "rl-only"),
        ([[2, syn, ""]], [], "bc-only"),
        ([[1, lex, ""]], [[1, "P0012", ""], [1, "P0012", ""]], "lexer-token-split"),
        ([[1, syn, ""]], [[1, "P0012", ""], [1, "P0012", ""]], "more-on-line"),
        ([[1, syn, ""], [1, lex, ""]], [[1, "P0012", ""]], "lexer-tokens-merged"),
        ([[1, syn, ""], [1, syn, ""]], [[1, "P0012", ""]], "fewer-on-line"),
        ([[1, syn, ""]], [[1, "P0012", ""], [2, "P0012", ""]], "rl-indented-line"),
        ([[2, syn, ""]], [[2, "P0012", ""], [3, "P0012", ""]], "rl-top-level-line"),
        ([[1, syn, ""], [3, syn, ""]], [[1, "P0012", ""]], "rl-misses-line"),
        ([[3, syn, ""]], [[2, "P0012", ""]], "off-by-one"),
        ([[1, syn, ""], [0, "ParserError", ""]], [[1, "P0012", ""]], "eof"),
        # rledger's unclosed-pushtag error is beancount's line 0.
        ([[0, "ParserError", ""]], [[1, "P0021", ""]], "match"),
        # The first disagreeing line decides; line 0 sorts last.
        (
            [[0, "ParserError", ""], [3, syn, ""], [4, syn, ""]],
            [[3, "P0012", ""], [3, "P0012", ""]],
            "more-on-line",
        ),
    ]
    for bc, rl, want in cases:
        got = categorize(bc, rl, text)
        assert got == want, f"categorize({bc}, {rl}) = {got}, want {want}"
    assert bucket("more-on-line", [[1, syn, ""]], [[1, "P0012", ""]] * 2) == "count"
    assert bucket("off-by-one", [[3, syn, ""]], [[2, "P0012", ""]]) == "lines"
    assert set(CATEGORIES) == {w for _, _, w in cases} | {"crash"}

    inputs = Inputs()
    inputs.add("fuzz", "f1", b"a")
    inputs.add("fuzz", "f2", b"b")
    inputs.add("tracked", "tests/x.beancount", b"c")
    inputs.add("fuzz", "f3", b"\xff")
    inputs.add("fuzz", "f1-dup", b"a")
    assert inputs.non_utf8["fuzz"] == 1 and inputs.duplicates == 1
    ids = {label: cid for cid, (_, label, _) in inputs.items.items()}
    results = {
        ids["f1"]: ("rl-only", [], []),
        ids["f2"]: ("match", [], []),
        ids["tests/x.beancount"]: ("match", [], []),
    }
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        write_baseline(path, inputs, results, "abc")
        meta, pins = read_baseline(path)
    assert meta == {"fuzz-commit": "abc"}, meta
    assert set(pins) == {ids["f1"], ids["tests/x.beancount"]}, pins
    assert check_against_baseline(inputs, results, pins) == ([], [], [], [])
    # f2 regresses, f1 starts matching, the ledger changes category.
    later = dict(results)
    later[ids["f2"]] = ("off-by-one", [], [])
    later[ids["f1"]] = ("match", [], [])
    later[ids["tests/x.beancount"]] = ("rl-extra", [], [])
    reg, imp, chg, unp = check_against_baseline(inputs, later, pins)
    assert sorted(reg) == [("f2", "off-by-one"), ("tests/x.beancount", "rl-extra")], reg
    assert imp == [("f1", "rl-only")], imp
    assert chg == [] and unp == [], (chg, unp)
    # A ledger with no row is unpinned, not a regression.
    del pins[ids["tests/x.beancount"]]
    reg, _, _, unp = check_against_baseline(inputs, later, pins)
    assert reg == [("f2", "off-by-one")] and unp == [
        ("tests/x.beancount", "rl-extra", True)
    ], (reg, unp)
    assert strip_bom("\ufeffx") == "x" and strip_bom("x\ufeff") == "x\ufeff"
    assert rl_lines([[5, "P0021", ""], [5, "P0003", ""]]) == [0, 5]
    print("self-test: ok")


