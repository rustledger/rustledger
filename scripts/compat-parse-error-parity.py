# Self-test


def self_test():
    """The classifier and the pin check, on hand-written shapes.

    Runs before the real comparison in CI: a classifier bug that called every
    input `match` would otherwise read as perfect parity.
    """
    lex, syn = "LexerError", "ParserSyntaxError"
    text = "a\n  b\nc\nd\n"
    cases = [
        ([[2, syn, ""]], [[2, "P0003", ""]], "match"),
        ([], [[2, "P0003", ""]], "rl-only"),
        ([[2, syn, ""]], [], "bc-only"),
        ([[1, lex, ""]], [[1, "P0012", ""], [1, "P0012", ""]], "lexer-token-split"),
        ([[1, syn, ""]], [[1, "P0012", ""], [1, "P0012", ""]], "more-on-line"),
        ([[1, syn, ""], [1, lex, ""]], [[1, "P0012", ""]], "lexer-tokens-merged"),
        ([[1, syn, ""], [1, syn, ""]], [[1, "P0012", ""]], "fewer-on-line"),
        ([[1, syn, ""]], [[1, "P0012", ""], [2, "P0012", ""]], "rl-indented-line"),
        ([[2, syn, ""]], [[2, "P0012", ""], [3, "P0012", ""]], "rl-top-level-line"),
        ([[1, syn, ""], [3, syn, ""]], [[1, "P0012", ""]], "rl-misses-line"),
        ([[3, syn, ""]], [[2, "P0012", ""]], "off-by-one"),
        ([[1, syn, ""], [0, "ParserError", ""]], [[1, "P0012", ""]], "eof"),
        # rledger's unclosed-pushtag error is beancount's line 0.
        ([[0, "ParserError", ""]], [[1, "P0021", ""]], "match"),
        # The first disagreeing line decides; line 0 sorts last.
        (
            [[0, "ParserError", ""], [3, syn, ""], [4, syn, ""]],
            [[3, "P0012", ""], [3, "P0012", ""]],
            "more-on-line",
        ),
    ]
    for bc, rl, want in cases:
        got = categorize(bc, rl, text)
        assert got == want, f"categorize({bc}, {rl}) = {got}, want {want}"
    assert bucket("more-on-line", [[1, syn, ""]], [[1, "P0012", ""]] * 2) == "count"
    assert bucket("off-by-one", [[3, syn, ""]], [[2, "P0012", ""]]) == "lines"
    assert set(CATEGORIES) == {w for _, _, w in cases} | {"crash"}

    inputs = Inputs()
    inputs.add("fuzz", "f1", b"a")
    inputs.add("fuzz", "f2", b"b")
    inputs.add("tracked", "tests/x.beancount", b"c")
    inputs.add("fuzz", "f3", b"\xff")
    inputs.add("fuzz", "f1-dup", b"a")
    assert inputs.non_utf8["fuzz"] == 1 and inputs.duplicates == 1
    ids = {label: cid for cid, (_, label, _) in inputs.items.items()}
    results = {
        ids["f1"]: ("rl-only", [], []),
        ids["f2"]: ("match", [], []),
        ids["tests/x.beancount"]: ("match", [], []),
    }
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        write_baseline(path, inputs, results, "abc")
        meta, pins = read_baseline(path)
    assert meta == {"fuzz-commit": "abc", "inputs": {"fuzz": 3, "matrix": 0}}, meta
    assert set(pins) == {ids["f1"], ids["tests/x.beancount"]}, pins
    assert check_against_baseline(inputs, results, pins) == ([], [], [], [])
    # f2 regresses, f1 starts matching, the ledger changes category.
    later = dict(results)
    later[ids["f2"]] = ("off-by-one", [], [])
    later[ids["f1"]] = ("match", [], [])
    later[ids["tests/x.beancount"]] = ("rl-extra", [], [])
    reg, imp, chg, unp = check_against_baseline(inputs, later, pins)
    assert sorted(reg) == [("f2", "off-by-one"), ("tests/x.beancount", "rl-extra")], reg
    assert imp == [("f1", "rl-only")], imp
    assert chg == [] and unp == [], (chg, unp)
    # A ledger with no row is unpinned, not a regression.
    del pins[ids["tests/x.beancount"]]
    reg, _, _, unp = check_against_baseline(inputs, later, pins)
    assert reg == [("f2", "off-by-one")] and unp == [
        ("tests/x.beancount", "rl-extra", True, ids["tests/x.beancount"])
    ], (reg, unp)
    # --update keeps a compat row whose content this run did not see.
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        old = {"aaaaaaaaaaaa": ("compat", "rl-only", "tests/compatibility/files/y")}
        write_baseline(path, inputs, results, "abc", previous=old)
        _, kept = read_baseline(path)
    assert kept["aaaaaaaaaaaa"] == old["aaaaaaaaaaaa"], kept
    # A copied `pin-row` appended after a fuzz section still reads as a pin.
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "m"
        path.write_text("@ fuzz rl-only\nbbbbbbbbbbbb\ncompat\tcccccccccccc\tmatch\tz\n")
        _, appended = read_baseline(path)
    assert appended == {
        "bbbbbbbbbbbb": ("fuzz", "rl-only", ""),
        "cccccccccccc": ("compat", "match", "z"),
    }, appended
    assert strip_bom("\ufeffx") == "x" and strip_bom("x\ufeff") == "x\ufeff"

    # beancount's errors: option, account-name and cost-merge errors dropped,
    # a missing line read as 0.
    class Err:
        def __init__(self, line, message):
            self.source = {"filename": "<string>", "lineno": line}
            self.message = message

    class LexerError(Err):
        pass

    errs = [
        Err(1, "Invalid option: 'x'"),
        Err(2, "Invalid account name: 'a'"),
        Err(3, "Error for option 'booking_method': Invalid value"),
        Err(4, "Option 'filename' may not be set"),
        Err(5, "Cost merging is not supported yet"),
        LexerError(6, "Invalid token: 'q'"),
        Err(None, "Unbalanced pushed tag: 't'"),
    ]
    is_not_syntax = load_matrix_module().is_not_syntax  # imports beancount
    assert keep_parse_errors(errs, is_not_syntax) == [
        [6, "LexerError", "Invalid token: 'q'"],
        [0, "Err", "Unbalanced pushed tag: 't'"],
    ], keep_parse_errors(errs, is_not_syntax)

    # --check's exit code. `inputs` holds 3 fuzz inputs (f1 pinned rl-only,
    # f2 a pinned match) and a pinned tracked ledger.
    meta = {"fuzz-commit": "abc", "inputs": {"fuzz": 3, "matrix": 0}}
    pins = {ids["f1"]: ("fuzz", "rl-only", ""), ids["tests/x.beancount"]: ("tracked", "match", "x")}

    def code(results, meta=meta, pins=pins):
        return run_check(inputs, results, meta, pins, out=lambda _: None)

    assert code(results) == 0
    assert code({**results, ids["f2"]: ("off-by-one", [], [])}) == 1  # regression
    assert code({**results, ids["f1"]: ("match", [], [])}) == 1  # stale: improved
    assert code({**results, ids["f1"]: ("off-by-one", [], [])}) == 1  # stale: shape
    no_row = {ids["f1"]: ("fuzz", "rl-only", "")}
    assert code(results, pins=no_row) == 0  # unpinned tracked ledger: warns
    assert code(results, meta={"inputs": {"fuzz": 9, "matrix": 0}}) == 1  # count
    # A coverage failure (a matrix base added, say) says how to fix it.
    said = []
    run_check(inputs, results, {"inputs": {"fuzz": 3, "matrix": 7}}, pins, out=said.append)
    assert any("--update" in line for line in said), said
    assert code(results, meta={"inputs": {"matrix": 0}}) == 1  # no count pinned
    ghost = {**pins, "dddddddddddd": ("fuzz", "rl-only", "")}
    assert code(results, pins=ghost) == 1  # a pinned id that did not run
    assert rl_lines([[5, "P0021", ""], [5, "P0003", ""]]) == [0, 5]
    print("self-test: ok")


