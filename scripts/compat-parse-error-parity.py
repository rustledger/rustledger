# Comparison and categories


def line_counts(lines):
    return dict(collections.Counter(lines))


def bc_lines(errors):
    return [e[0] for e in errors]


def rl_lines(errors):
    return [0 if e[1] in RLEDGER_EOF_CODES else e[0] for e in errors]


def line_kinds(bc, rl, text):
    """The kind of every line the two sides disagree on, in line order.

    `bc` is beancount's `[line, type, message]` list and `rl` rledger's
    `[line, code, message]` list; `text` is the input. Line 0 (a file-level
    error) sorts last. Each kind names the shape of one disagreement; see
    `CATEGORIES`.
    """
    b, r = line_counts(bc_lines(bc)), line_counts(rl_lines(rl))
    src = text.split("\n")
    out = []
    for line in sorted(set(b) | set(r), key=lambda k: (k == 0, k)):
        nb, nr = b.get(line, 0), r.get(line, 0)
        if nb == nr:
            continue
        if line == 0:
            out.append("eof")
            continue
        here = [e[1] for e in bc if e[0] == line]
        if nb and nr:
            if nr > nb:
                lexer_only = all(t == "LexerError" for t in here)
                out.append("lexer-token-split" if lexer_only else "more-on-line")
            else:
                lexer = "LexerError" in here
                out.append("lexer-tokens-merged" if lexer else "fewer-on-line")
            continue
        # One side is silent on this line: the same error one line over on the
        # other side, or a line only one side reports.
        mine, theirs = (r, b) if nr else (b, r)
        if any(mine.get(k, 0) == 0 and theirs.get(k, 0) for k in (line - 1, line + 1)):
            out.append("off-by-one")
        elif nb:
            out.append("rl-misses-line")
        elif line <= len(src) and src[line - 1][:1] in (" ", "\t"):
            out.append("rl-indented-line")
        else:
            out.append("rl-top-level-line")
    return out


def categorize(bc, rl, text):
    """The category of one input: its first disagreeing line's kind.

    The first divergence is the one to read: what follows it is usually its
    cascade. An input on which only one side reports anything is `rl-only` or
    `bc-only` instead, whatever its lines.
    """
    b, r = line_counts(bc_lines(bc)), line_counts(rl_lines(rl))
    if b == r:
        return "match"
    if not b:
        return "rl-only"
    if not r:
        return "bc-only"
    return line_kinds(bc, rl, text)[0]


def bucket(category, bc, rl):
    """The headline bucket: `match`, `crash`, `count` or `lines`.

    `count` means both sides report errors on the same lines, only how many
    differs; `lines` that the sets of lines differ.
    """
    if category in ("match", "crash"):
        return category
    if set(bc_lines(bc)) == set(rl_lines(rl)):
        return "count"
    return "lines"


def compare(inputs, bc_results, rl_results):
    """`{id: (category, bc, rl)}` for every input."""
    out = {}
    for cid, (_, _, text) in inputs.items.items():
        bc = bc_results[cid]
        rl = rl_results[cid]
        if "crash" in bc:
            out[cid] = ("crash", bc["crash"], rl)
            continue
        out[cid] = (categorize(bc["errors"], rl, text), bc["errors"], rl)
    return out


