# Inputs


class Inputs:
    """Inputs keyed by content id, each with a source and a display label."""

    def __init__(self):
        self.items = {}  # id -> (source, label, text)
        self.non_utf8 = collections.Counter()
        # UTF-8 inputs read per source, duplicates included: what `#@inputs`
        # pins. Counted before deduplication, so it does not depend on what
        # other sources (a machine's downloaded corpus) happen to hold.
        self.seen = collections.Counter()
        self.duplicates = 0

    def add(self, source, label, data):
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            self.non_utf8[source] += 1
            return
        self.seen[source] += 1
        cid = content_id(data)
        if cid in self.items:
            self.duplicates += 1
            return
        self.items[cid] = (source, label, text)


def tracked_ledgers():
    out = subprocess.run(
        ["git", "-C", str(REPO), "ls-files", "-z", "*.beancount", "*.bean"],
        check=True,
        capture_output=True,
    ).stdout
    return sorted(p for p in out.decode().split("\0") if p)


def collect(args):
    inputs = Inputs()
    matrix = load_matrix_module()
    for name, base in matrix.BASES:
        for i, src in enumerate(matrix.cases(base)):
            inputs.add("matrix", f"matrix:{name}#{i}", src.encode("utf-8"))
    for rel in tracked_ledgers():
        inputs.add("tracked", rel, (REPO / rel).read_bytes())
    for d in FUZZ_REGRESSIONS:
        if d.is_dir():
            # Every file but the directory's README is a fuzz input.
            for p in sorted(q for q in d.iterdir() if q.name != "README.md"):
                inputs.add("tracked", str(p.relative_to(REPO)), p.read_bytes())
    if args.compat_dir:
        compat = Path(args.compat_dir)
        found = sorted(compat.rglob("*.beancount"))
        if len(found) < args.min_compat:
            sys.exit(
                f"error: {len(found)} .beancount files under {compat}, expected at "
                f"least {args.min_compat}; the corpus fetch likely failed"
            )
        for p in found:
            # Labelled by the corpus's place in the repo, wherever this copy
            # of it lives, so a pin written from another directory keeps the
            # same labels.
            rel = (COMPAT_LABEL_ROOT / p.relative_to(compat)).as_posix()
            inputs.add("compat", rel, p.read_bytes())
    if args.fuzz_dir:
        root = Path(args.fuzz_dir)
        for target in FUZZ_TARGETS:
            d = root / target
            if not d.is_dir():
                sys.exit(f"error: {d} is missing; extract the fuzz-corpus commit there")
            for p in sorted(d.iterdir()):
                inputs.add("fuzz", f"{target}/{p.name}", p.read_bytes())
    generators = ptadiff.get_format("beancount").generators
    for spec in GENERATOR_SAMPLE:
        name, seed, n = spec.split(":")
        for i, text in enumerate(generators[name](int(seed), int(n))):
            inputs.add("gen", f"gen:{name}:{seed}#{i}", text.encode("utf-8"))
    return inputs


# --------------------------------------------------------------------------
# beancount side


def strip_bom(text):
    return text[1:] if text.startswith("\ufeff") else text


# More errors beancount's grammar actions raise that are not parse errors in
# rledger, on top of the matrix script's `is_not_syntax`: option VALUES and
# option names that may not be set, which rledger's loader checks
# (`rustledger-loader/src/options.rs` reports each of these), and cost merging
# (`{*}`), which beancount 3.2.3 rejects and rledger implements on purpose
# (see `known_cost_merge` in `tests/stray_char_matrix.rs`). Kept here rather
# than in `is_not_syntax`, which also decides the matrix's exclusions.
NOT_PARSE_ERRORS = (
    "Error for option",
    "may not be set",
    "Renamed to '",
    "Allowing pipe separator",
    "Allowing None for tags and link",
    "Cost merging is not supported yet",
)


# A syntax error whose lookahead is an end of line: beancount reports it on the
# line AFTER the one it is on (bison takes the line from the lexer, which has
# already counted the `\n`). rledger reports it on the line whose statement
# ends there, where the mistake is, on purpose. See the module docstring.
EOL_SYNTAX_ERROR = "syntax error, unexpected EOL"


# beancount's error at the indent of a line no entry continues.
INDENT_SYNTAX_ERROR = "syntax error, unexpected INDENT"


def _is_indented_comment(text):
    rest = text.lstrip(" \t")
    return len(rest) < len(text) and rest.startswith(";")


def _is_gap(text):
    """A blank line, or one beancount's lexer skips at column 0: a `;`
    comment, or `*`, `:`, `#` or a flag character with more after it (not a
    `#` starting a tag)."""
    if not text.strip(" \t\r") or text.startswith(";"):
        return True
    tag = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_/."
    return (
        len(text) >= 2
        and text[0] in "*:#!&?%"
        and not (text[0] == "#" and text[1] in tag)
    )


def is_indented_comment_indent_error(message, line, lines):
    """Whether beancount's error `message` on `line` (1-based) of `lines` is
    its `unexpected INDENT` on a line of blanks and a `;` comment after a gap
    (a blank line, a column-0 comment, the top of the file; other indented
    comments between), which rledger reads as a comment on purpose (see the
    module docstring). Not one after a directive that takes no metadata
    (`option "a" "b"` then `  ; c`), which rledger reports too."""
    if not message.startswith(INDENT_SYNTAX_ERROR) or not 0 < line <= len(lines):
        return False
    if not _is_indented_comment(lines[line - 1]):
        return False
    before = line - 2
    while before >= 0 and _is_indented_comment(lines[before]):
        before -= 1
    return before < 0 or _is_gap(lines[before])


# beancount's builder error for a tag line after a transaction's first
# posting, which it reports on the transaction's header line.
TAGS_AFTER_POSTING_ERROR = "Tags or links not allowed after first Posting"


def _is_tags_links_line(text):
    """Whether `text` is an indented line of only `#tag` / `^link` tokens
    (and a trailing `;` comment)."""
    if text[:1] not in (" ", "\t"):
        return False
    words = text.split(";", 1)[0].split()
    return bool(words) and all(w[:1] in "#^" and len(w) > 1 for w in words)


def tags_after_posting_lines(header, lines):
    """The tag lines (1-based) after the first posting of the transaction
    whose header is on line `header` of `lines`, in order: its indented lines
    up to the first line that is neither indented nor a `;` comment."""
    out = []
    posting_seen = False
    for n in range(header, len(lines)):
        text = lines[n].rstrip("\r")
        if text.startswith(";"):
            continue
        if text[:1] not in (" ", "\t") or not text.strip():
            break
        if _is_tags_links_line(text):
            if posting_seen:
                out.append(n + 1)
            continue
        rest = text.lstrip(" \t")
        if rest[:1] in "*!&#?%PSTCURM" and rest[1:2] in (" ", "\t"):
            rest = rest[1:].lstrip(" \t")
        if rest[:1].isupper() and ":" in rest.split()[0]:
            posting_seen = True
    return out


def beancount_errors(parser, is_not_syntax, text):
    """beancount's parse errors for `text` as `[line, type, message]`."""
    _, errors, _ = parser.parse_string(strip_bom(text))
    return keep_parse_errors(errors, is_not_syntax, strip_bom(text))


def keep_parse_errors(errors, is_not_syntax, text=None):
    """beancount `errors` minus the ones that are not parse errors in rledger
    (and, given the input `text`, minus its errors at indented comments)."""
    lines = text.split("\n") if text is not None else []
    out = []
    # Per header line, the tag lines its errors are not yet moved to.
    tag_lines = {}
    for e in errors:
        if is_not_syntax(e) or any(m in str(e.message) for m in NOT_PARSE_ERRORS):
            continue
        line = int((e.source or {}).get("lineno") or 0)
        if is_indented_comment_indent_error(str(e.message), line, lines):
            continue
        if str(e.message).startswith(TAGS_AFTER_POSTING_ERROR) and 0 < line <= len(lines):
            # Reported on the transaction's header line; rledger reports it
            # on the tag line, where the mistake is, on purpose (#2575). The
            # k-th such error of a header is its k-th late tag line.
            pending = tag_lines.setdefault(line, tags_after_posting_lines(line, lines))
            if pending:
                line = pending.pop(0)
        if str(e.message).startswith(EOL_SYNTAX_ERROR) and line > 1:
            line -= 1
        out.append([line, type(e).__name__, str(e.message)])
    return out


def run_beancount(items, jobs):
    """beancount's result for every `(id, text)`: `{"errors": [...]}` (kept
    and moved by `beancount_errors`), or `{"crash": why}`.

    Each parse runs in a `ptadiff.run_forked` worker: a worker that dies (a
    segfault, the timeout's SIGALRM) or a parse that raises loses only that
    input, recorded as a crash, and a new worker takes the rest of its share.
    """
    # Imported here, before the workers fork, so each one inherits them.
    from beancount.parser import parser

    is_not_syntax = load_matrix_module().is_not_syntax

    def one(text):
        return beancount_errors(parser, is_not_syntax, text)

    raw = ptadiff.run_forked(items, one, jobs=jobs, timeout=BEANCOUNT_TIMEOUT_S)
    return {
        cid: {"crash": r.why} if isinstance(r, ptadiff.Crash) else {"errors": r}
        for cid, r in raw.items()
    }


