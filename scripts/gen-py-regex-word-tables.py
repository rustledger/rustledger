#!/usr/bin/env python3
"""Regenerate crates/rustledger-core/src/py_regex_word_tables.rs (#2656).

`\\b` in a BQL or plugin regex is answered with the `regex` crate's word
boundary, which is exact only on text holding no character whose word-ness
Python's `re` and `regex` disagree on. This script builds that set:

1. For each supported Python (3.9 to 3.14), the code points `re` matches
   with `\\w` (`str.isalnum()` or `_`), run with `uv run --python 3.X`.
   They differ because each Python ships its own Unicode version.
2. The code points the `regex` crate matches with `\\w`, dumped by the
   ignored test `py_regex::tests::dump_regex_word_set` (so it is the regex
   version in Cargo.lock).
3. WORD_DISAGREE = code points where `regex` differs from ANY of those
   Pythons, which is (regex XOR reference Python) | PY_WORD_VARIES.

The checked-in file keeps the reference Python's word set (PY_WORD, from
the newest Python), the code points whose word-ness differs between the
Pythons (PY_WORD_VARIES), and WORD_DISAGREE. The test
`word_disagreement_table_is_exact` walks every code point and checks
WORD_DISAGREE against `regex` and the two Python tables, so a `regex`
upgrade that changes `\\w` fails it until this script is run again.

Run from the repository root, inside `nix develop`:

    python3 scripts/gen-py-regex-word-tables.py
"""

import json
import os
import subprocess
import sys
import tempfile

VERSIONS = ["3.9", "3.10", "3.11", "3.12", "3.13", "3.14"]
REFERENCE = "3.14"
OUT = "crates/rustledger-core/src/py_regex_word_tables.rs"

PROBE = r"""
import json, re, sys, unicodedata
w = re.compile(r'\w')
out = []
start = None
for c in range(0x110000):
    word = not (0xD800 <= c <= 0xDFFF) and w.fullmatch(chr(c)) is not None
    if word and start is None:
        start = c
    elif not word and start is not None:
        out.append((start, c - 1))
        start = None
if start is not None:
    out.append((start, 0x10FFFF))
print(json.dumps({"python": sys.version.split()[0],
                  "unicode": unicodedata.unidata_version, "ranges": out}))
"""


def expand(ranges):
    s = set()
    for lo, hi in ranges:
        s.update(range(lo, hi + 1))
    return s


def to_ranges(points):
    out = []
    for c in sorted(points):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def rust_table(name, doc, ranges, test_only=False):
    lines = [f"/// {line}" if line else "///" for line in doc.split("\n")]
    if test_only:
        lines.append("#[cfg(test)]")
    lines.append(f"pub(super) const {name}: &[(u32, u32)] = &[")
    row = []
    for lo, hi in ranges:
        row.append(f"(0x{lo:X}, 0x{hi:X}),")
        if len(row) == 4:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def main():
    pythons = {}
    for v in VERSIONS:
        out = subprocess.run(
            ["uv", "run", "--quiet", "--no-project", "--python", v, "python", "-I", "-c", PROBE],
            check=True, capture_output=True, text=True,
        ).stdout
        pythons[v] = json.loads(out)
        print(f"python {pythons[v]['python']} (Unicode {pythons[v]['unicode']}): "
              f"{len(expand(pythons[v]['ranges']))} word characters", file=sys.stderr)

    with tempfile.TemporaryDirectory() as tmp:
        dump = os.path.join(tmp, "regex-word.json")
        subprocess.run(
            ["cargo", "test", "-q", "-p", "rustledger-core", "--lib",
             "py_regex::tests::dump_regex_word_set", "--", "--ignored", "--exact"],
            check=True, env={**os.environ, "PY_REGEX_DUMP": dump},
        )
        with open(dump) as f:
            regex_word = expand(json.load(f))

    sets = {v: expand(p["ranges"]) for v, p in pythons.items()}
    ref = sets[REFERENCE]
    varies = set()
    for v in VERSIONS:
        varies |= sets[v] ^ ref
    disagree = (regex_word ^ ref) | varies
    for v in VERSIONS:
        print(f"regex vs python {v}: {len(regex_word ^ sets[v])} code points differ",
              file=sys.stderr)
    print(f"varies across Pythons: {len(varies)}; WORD_DISAGREE: {len(disagree)} code points "
          f"in {len(to_ranges(disagree))} ranges", file=sys.stderr)

    summary = ", ".join(f"{v} (Unicode {pythons[v]['unicode']}): {len(regex_word ^ sets[v])}"
                        for v in VERSIONS)
    text = "\n\n".join([
        "//! Word-character tables for `py_regex`'s word-boundary check (#2656).\n"
        "//!\n"
        "//! Generated by `scripts/gen-py-regex-word-tables.py`; do not edit. Rerun\n"
        "//! it (inside `nix develop`, from the repository root) when the `regex`\n"
        "//! crate or the supported Pythons change. `word_disagreement_table_is_exact`\n"
        "//! fails until it is.\n"
        "//!\n"
        f"//! Code points where `regex`'s `\\w` and Python's differ, per Python: {summary}.",
        rust_table("PY_WORD",
                   f"The code points Python {REFERENCE}'s `re` matches with `\\w`\n"
                   "(`str.isalnum()` or `_`), the reference the other tables are taken against.",
                   to_ranges(ref), test_only=True),
        rust_table("PY_WORD_VARIES",
                   "The code points whose word-ness differs between any two of Python\n"
                   + ", ".join(VERSIONS) + " (each has its own Unicode version).",
                   to_ranges(varies), test_only=True),
        rust_table("WORD_DISAGREE",
                   "The code points whose word-ness differs between the `regex` crate's `\\w`\n"
                   "and Python's in any of the Pythons above: a word boundary is exact on a text\n"
                   "holding none of them.",
                   to_ranges(disagree)),
    ]) + "\n"
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
